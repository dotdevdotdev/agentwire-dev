def is_glob_pattern(pattern: str) -> bool:
    return '*' in pattern or '?' in pattern or '[' in pattern


def glob_to_regex(pattern: str) -> str:
    """Convert a glob to a regex usable inside command-line contexts.

    Trailing word-boundary check ensures e.g. ``*.py`` doesn't match
    ``foo.python``.
    """
    result = ""
    for char in pattern:
        if char == '*':
            result += r'[^\s/]*'
        elif char == '?':
            result += r'[^\s/]'
        elif char in r'\.^$+{}[]|()':
            result += '\\' + char
        else:
            result += char
    result += r'(?![a-zA-Z0-9_])'
    return result


def canonicalize_command(command: str) -> str:
    """Expand ``~``, ``$HOME`` and ``${HOME}`` in a command to the home dir.

    The rule patterns are stored in ``~``-form and expanded with
    ``expanduser`` before matching; without expanding the COMMAND too, a
    tilde/``$HOME`` secret read (``cat ~/.ssh/id_rsa``, ``cat $HOME/.aws/credentials``)
    only ever matched against its fully-expanded ``/Users/<me>/...`` form and
    slipped past. Canonicalizing both sides closes that gap. ``./``-prefixes are
    handled by the path-context boundary in :func:`path_match_regex` (a leading
    ``/`` is an accepted boundary char), so no separate ``normpath`` of the raw
    command string — which is not a pure path — is attempted here.
    """
    home = os.path.expanduser("~")
    if not home or home == "~":
        return command
    out = command.replace("${HOME}", home).replace("$HOME", home)
    # Only expand ``~`` when it begins a path (start of string or after a
    # whitespace/quote/=/: boundary and immediately followed by ``/``), so we
    # never touch ``~`` used as a literal (e.g. inside a sed expression).
    out = re.sub(r'(^|[\s=:"\'(<>])~(?=/)', lambda m: m.group(1) + home, out)
    return out


def path_match_regex(expanded_pattern: str) -> str:
    """Build a path-context regex for a rule pattern (glob or literal).

    Both glob and literal patterns are matched as a whole path COMPONENT — never
    a bare substring. The literal branch previously used ``expanded in command``,
    which hard-blocked innocuous text: ``.env`` matched ``.environment``,
    ``docs/.env.example``, ``grep -v .environ`` (#492). The component boundary
    (a leading path-separator/whitespace boundary, and a trailing boundary that
    forbids the basename being extended by another filename char) fixes those
    false positives while still catching real secret paths.
    """
    lead = r'(?:^|[\s=:"\'<>(/])'
    if is_glob_pattern(expanded_pattern):
        glob_regex = glob_to_regex(expanded_pattern)
        return r'(?:^|[\s/="\'<>])' + glob_regex + r'(?:[\s"\')<>]|$)'
    is_dir = expanded_pattern.endswith('/')
    body = re.escape(expanded_pattern.rstrip('/'))
    if is_dir:
        # Directory prefix: anything under it counts as a hit.
        trail = r'(?:/|[\s"\')<>;&|]|$)'
    else:
        # Filename/path: the basename must end here — the next char must not be
        # a path-extending char, so ``.env`` no longer matches ``.env.example``.
        trail = r'(?![A-Za-z0-9_.\-])'
    return lead + body + trail


# ``.env.example`` / ``.env.sample`` / ``.env.template`` / ``.env.dist`` are
# committed, secret-free TEMPLATE files — never the real env. The ``.env.*`` glob
# would otherwise hard-block reading them (#492), so they are carved out.
_SAFE_ENV_TEMPLATE_RE = re.compile(
    r'\.env\.(?:example|sample|template|dist)(?![A-Za-z0-9_])', re.IGNORECASE
)


def matches_path_in_command(pattern: str, command: str) -> bool:
    """Check if a path pattern occurs in a command string in a path-context.

    The command is canonicalized (``~``/``$HOME`` expanded) and the pattern is
    matched as a whole path component against both the raw and canonicalized
    forms, so neither tilde indirection (#2) nor bare-substring over-blocking
    (#492) defeats it.
    """
    expanded = os.path.expanduser(pattern)
    regex = path_match_regex(expanded)
    haystacks = [command]
    canon = canonicalize_command(command)
    if canon != command:
        haystacks.append(canon)

    matched = False
    for hay in haystacks:
        try:
            m = re.search(regex, hay, re.IGNORECASE)
        except re.error:
            return False
        if m and not _SAFE_ENV_TEMPLATE_RE.search(m.group(0)):
            matched = True
            break
    if not matched:
        return False

    if is_glob_pattern(pattern):
        # Reject method-call lookalikes: foo.py( should not match *.py
        extension = pattern.split('*')[-1] if '*' in pattern else pattern
        if extension.startswith('.'):
            extension = extension[1:]
        if extension and re.search(r'\w\.' + re.escape(extension) + r'\s*\(', command):
            return False
    return True


def match_path(file_path: str, pattern: str) -> bool:
    """Match a single absolute file path against a pattern (glob or prefix)."""
    expanded_pattern = os.path.expanduser(pattern)
    normalized = os.path.normpath(file_path)
    expanded_normalized = os.path.expanduser(normalized)
    if is_glob_pattern(pattern):
        lower_path = expanded_normalized.lower()
        lower_pattern = expanded_pattern.lower()
        if fnmatch.fnmatch(lower_path, lower_pattern):
            return True
        basename = os.path.basename(expanded_normalized)
        if fnmatch.fnmatch(basename.lower(), lower_pattern):
            return True
        return False
    return (
        expanded_normalized.startswith(expanded_pattern)
        or expanded_normalized == expanded_pattern.rstrip('/')
    )


def _parse_allowed_entry(entry: Dict[str, Any]) -> Dict[str, Any]:
    """Normalize an allowed-paths entry to ``{path: str, allow: set}``."""
    allow = entry.get("allow", "all")
    if isinstance(allow, str) and allow.strip().lower() == "all":
        return {"path": entry["path"], "allow": ALL_OPERATIONS.copy()}
    if isinstance(allow, list):
        return {"path": entry["path"], "allow": {a.strip().lower() for a in allow}}
    if isinstance(allow, str):
        return {"path": entry["path"], "allow": {allow.strip().lower()}}
    return {"path": entry["path"], "allow": ALL_OPERATIONS.copy()}


def _find_project_config() -> Tuple[str, List[Any]]:
    """Walk up from $PWD to find ``.damagecontrol.yml`` and return its allowed_paths.

    The per-project allowlist lives in the PROTECTED ``.damagecontrol.yml``
    (top-level ``allowed_paths``), never the agent-writable ``.agentwire.yml``.
    Otherwise an agent could allowlist a control-plane path in ``.agentwire.yml``
    and re-permit its own write to ``damagecontrol.yml`` — the exact bypass #466
    set out to close. The allowlist is the one knob that overrides the protected
    check, so it must itself live behind the protected control plane (#467).
    """
    cwd = os.environ.get("PWD", os.getcwd())
    current = os.path.abspath(cwd)
    while True:
        config_file = os.path.join(current, ".damagecontrol.yml")
        if os.path.isfile(config_file):
            try:
                if yaml:
                    with open(config_file, "r") as f:
                        data = yaml.safe_load(f) or {}
                    if isinstance(data, dict):
                        paths = data.get("allowed_paths", [])
                        if isinstance(paths, list):
                            return current, paths
            except Exception:
                pass
            return current, []
        parent = os.path.dirname(current)
        if parent == current:
            break
        current = parent
    return cwd, []


def load_allowed_paths(config: Dict[str, Any]) -> List[Dict[str, Any]]:
    """Merge global ``allowedPaths`` from config with per-project ``.damagecontrol.yml`` entries."""
    raw = list(config.get("allowedPaths", []))

    project_root, project_paths = _find_project_config()
    for p in project_paths:
        if not isinstance(p, dict):
            continue
        entry = _parse_allowed_entry(p)
        if not os.path.isabs(os.path.expanduser(entry["path"])):
            entry["path"] = os.path.join(project_root, entry["path"])
        raw.append(entry)

    result = []
    for item in raw:
        if not isinstance(item, dict):
            continue
        if "allow" in item and isinstance(item["allow"], set):
            result.append(item)
        else:
            result.append(_parse_allowed_entry(item))
    return result


def is_path_allowed_for_op(
    file_path: str,
    allowed_paths: List[Dict[str, Any]],
    operation: str,
) -> bool:
    """Check if ``file_path`` has ``operation`` permitted by some allowed-path entry."""
    for entry in allowed_paths:
        if match_path(file_path, entry["path"]):
            if operation in entry["allow"]:
                return True
    return False


def _extract_command_paths(command: str) -> List[str]:
    """Extract file/directory paths from a bash command string."""
    paths = []
    for m in re.finditer(r'''["']([^"']+)["']''', command):
        candidate = m.group(1)
        if '/' in candidate or candidate.startswith('.'):
            paths.append(os.path.expanduser(candidate))
    for token in re.split(r'\s+', command):
        token = token.strip("\"'")
        if token.startswith(('/', '~/', './')):
            paths.append(os.path.expanduser(token))
        elif '/' in token and not token.startswith('-'):
            paths.append(os.path.expanduser(token))
    return paths


def is_command_path_allowed(
    command: str,
    allowed_paths: List[Dict[str, Any]],
    operation: str = "write",
) -> bool:
    """ALL paths in ``command`` must have ``operation`` permitted by allowlist.

    Security: ALL paths must match (not any) — this stops e.g.
    ``rm /tmp/safe.txt /etc/passwd`` from being allowed just because /tmp is
    allowlisted.
    """
    if not allowed_paths:
        return False
    paths = _extract_command_paths(command)
    if not paths:
        return False
    for p in paths:
        if not is_path_allowed_for_op(p, allowed_paths, operation):
            return False
    return True


def _infer_operation_from_reason(reason: str) -> str:
    """Map a pattern's reason text back to one of the allowlist operation names."""
    reason_lower = reason.lower()
    if (
        "rm" in reason_lower
        or "delet" in reason_lower
        or "trash" in reason_lower
        or "rmdir" in reason_lower
    ):
        return "delete"
    if "chmod" in reason_lower or "permission" in reason_lower:
        return "chmod"
    if "chown" in reason_lower or "chgrp" in reason_lower:
        return "chmod"
    if "mv" in reason_lower or "move" in reason_lower:
        return "move"
    return "write"


def check_path_patterns(
    command: str,
    path: str,
    patterns: List[Tuple[str, str]],
    path_type: str,
) -> Tuple[bool, str]:
    """Check if any operation pattern matches ``command`` targeting ``path``.

    Returns ``(matched, reason)`` where reason names the operation that triggered.
    """
    if is_glob_pattern(path):
        # Allow an optional (possibly quoted) directory prefix: ``*`` in the
        # glob can't span ``/``, so without this a basename glob like
        # ``*.agentwire.yml`` never matched an absolute target
        # (``> /repo/.agentwire.yml`` sailed past every write pattern) (#678).
        path_regex = r'["\']?(?:[^\s"\';|&<>]*/)?' + glob_to_regex(path)
    else:
        expanded = os.path.expanduser(path)
        if expanded == path:
            path_regex = re.escape(path)
        else:
            path_regex = r'(?:' + re.escape(expanded) + r'|' + re.escape(path) + r')'

    for pattern_template, operation in patterns:
        try:
            full_pattern = pattern_template.replace("{path}", path_regex)
            if re.search(full_pattern, command, re.IGNORECASE):
                return True, f"{operation} operation on {path_type} {path}"
        except re.error:
            continue
    return False, ""


