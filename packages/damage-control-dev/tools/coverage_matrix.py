#!/usr/bin/env python3
"""Generate ``docs/coverage.md``: which Claude Code tools damage control judges, and how.

The README claim "what is covered" must not drift from the code, so the table is DERIVED from the
same tables the hooks use (``claude_code.MATCHERS``, ``adapter.HOOK_KINDS``, ``policy``): a tool
registered but not judged, or judged but not registered, shows up here.

    coverage_matrix.py          # write docs/coverage.md
    coverage_matrix.py --check  # exit 1 if it is stale
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import List

from damage_control import adapter, claude_code, policy

OUT = Path(__file__).resolve().parent.parent / "docs" / "coverage.md"

# Tools Claude Code has that no hook judges, by name. They are listed so "unsupported" is a stated
# fact rather than an omission; the list is not exhaustive and the check cannot prove it is.
UNSUPPORTED = ("WebFetch", "WebSearch", "Task", "Agent", "Skill", "Monitor", "TodoWrite", "AskUserQuestion")


def render() -> str:
    path_kinds = set(policy._PATH_VERB)  # kinds that judge one path: block only, never ask
    rows: List[str] = []
    for matcher, hook in claude_code.MATCHERS.items():
        tools, shell = adapter.HOOK_KINDS[hook]
        if tools is None:
            kind, judges = "mcp", "the tool name and its path-valued arguments, plus a synthesized shell command for outbound tools"
        else:
            names = [t for t, (_, _) in tools.items() if matcher == "mcp__.*" or t == matcher]
            kind = tools[names[0]][0] if names else "?"
            fields = tools[names[0]][1] if names else ()
            judges = "the command line" if kind == "shell" else f"the path in `{'` / `'.join(fields)}`"
        ask = "yes" if kind not in path_kinds else "no"
        rows.append(f"| `{matcher}` | `{hook}` | {judges} | yes | {ask} | yes |")
    unsupported = ", ".join(f"`{t}`" for t in UNSUPPORTED)
    return "\n".join([
        "# Coverage",
        "",
        "Generated by `tools/coverage_matrix.py` from the hooks' own tables; `--check` fails if it is stale.",
        "",
        "| Tool matcher | Hook | Judged on | Block | Ask | Audited |",
        "|---|---|---|---|---|---|",
        *rows,
        "",
        "`Ask` is *no* for the path tools: a path is either allowed or blocked. An `ask` outside an attended",
        "session becomes a block (unattended) or an allow (bypass permission mode) -- except an `unverifiable`",
        "one, which bypass never demotes.",
        "",
        f"**Unsupported (no hook is registered, so nothing is judged):** {unsupported}.",
        "",
    ])


def main(argv: List[str]) -> int:
    text = render()
    if argv == ["--check"]:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale; run: uv run python packages/damage-control-dev/tools/coverage_matrix.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
