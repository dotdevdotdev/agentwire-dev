# Terminator for a generated command prefix. ``\b`` is NOT enough: it matches
# between a word char and ``-``, so ``\bgit\s+merge\b`` swallowed the read-only
# ``git merge-base`` and refused it as a merge (#933). The lookahead forbids the
# last token being EXTENDED by another command-name char.
_CMD_PREFIX_TERM = r'(?![\w-])'


def _cmd_fixed_tokens(cmd: str, include_flags: bool = False) -> Tuple[str, ...]:
    """The leading literal tokens of a tooldef ``cmd:`` string.

    Stops at the first placeholder (``<...>``) or optional (``[...]``); flags
    (``-``/``--``) also stop it unless ``include_flags`` — read-command prefixes
    keep their literal flags (``git checkout -- <file>``) so a write rule can
    exclude them precisely.
    """
    fixed = []
    for token in cmd.strip().split():
        if token.startswith('<') or token.startswith('['):
            break
        if not include_flags and token.startswith('-'):
            break
        fixed.append(token)
    return tuple(fixed)


def _cmd_to_regex(
    cmd: str,
    read_prefixes: Tuple[Tuple[str, ...], ...] = (),
) -> Optional[str]:
    """Convert a tooldef command string to a regex matching its fixed prefix.

    Example: ``gws gmail +send --to <addr>`` ->
    ``\\bgws\\s+gmail\\s+\\+send(?![\\w-])``

    ``read_prefixes`` are the token prefixes of the same tooldef's
    ``access: read`` commands. Any read command that EXTENDS this write prefix
    contributes a negative lookahead, so the write rule stops swallowing the
    read-only subcommand that shares its spelling — ``git stash`` (write) no
    longer refuses ``git stash list`` (read) (#933). The exclusion is
    data-driven from the tooldef itself: declaring a subcommand ``access: read``
    is what releases it.
    """
    fixed = _cmd_fixed_tokens(cmd)
    if not fixed:
        return None
    parts = [re.escape(t) for t in fixed]
    pattern = r'\b' + r'\s+'.join(parts)
    continuations = sorted({
        r[len(fixed)]
        for r in read_prefixes
        if len(r) > len(fixed) and r[:len(fixed)] == fixed
    })
    if continuations:
        alts = []
        for tok in continuations:
            alt = re.escape(tok)
            if tok and (tok[-1].isalnum() or tok[-1] == '_'):
                alt += _CMD_PREFIX_TERM
            alts.append(alt)
        pattern += r'(?!\s+(?:' + '|'.join(alts) + r'))'
    last = fixed[-1]
    if last and (last[-1].isalnum() or last[-1] == '_'):
        pattern += _CMD_PREFIX_TERM
    return pattern


def load_write_patterns_from_tooldefs(tooldefs_dir: Optional[Path]) -> List[Dict[str, Any]]:
    """Generate ``ask:true`` patterns from write-tier commands in tooldef YAMLs."""
    if not yaml:
        return []
    patterns: List[Dict[str, Any]] = []
    if not tooldefs_dir or not tooldefs_dir.exists():
        return patterns
    for tf_file in sorted(tooldefs_dir.glob("*.yaml")):
        try:
            with open(tf_file, "r") as f:
                data = yaml.safe_load(f) or {}
            tool_name = data.get("name", tf_file.stem)
            commands = data.get("commands", [])
            # ``access: read`` prefixes carve read-only subcommands OUT of the
            # write rules generated below (#933) — see _cmd_to_regex.
            read_prefixes = tuple(
                p for p in (
                    _cmd_fixed_tokens(c.get("cmd", ""), include_flags=True)
                    for c in commands
                    if isinstance(c, dict) and c.get("access") == "read"
                ) if p
            )
            for cmd_def in commands:
                if cmd_def.get("access") != "write":
                    continue
                cmd_str = cmd_def.get("cmd", "")
                regex = _cmd_to_regex(cmd_str, read_prefixes)
                if not regex:
                    continue
                entry = {
                    "pattern": regex,
                    "reason": f"{tool_name}: {cmd_def.get('description', cmd_str)}",
                    "ask": True,
                    # Command-prefix rule: match command position only, never
                    # quoted argument/message content (#675).
                    "anchored": True,
                }
                # An explicit ``id:`` on the tooldef command yields a stable
                # rule ID (e.g. ``git.push``) that survives description edits —
                # needed so ``safety.unattended_allow`` can name it reliably.
                # Without one, ``_assign_rule_id`` derives a slug from the reason.
                if cmd_def.get("id"):
                    entry["id"] = str(cmd_def["id"])
                patterns.append(entry)
        except Exception:
            continue
    return patterns


_RULE_ID_SLUG_RE = re.compile(r"[^a-z0-9]+")


def _slug_for_rule(text: str, max_len: int = 60) -> str:
    """Lowercase, ASCII, kebab-case slug suitable for rule IDs."""
    s = _RULE_ID_SLUG_RE.sub("-", (text or "").lower()).strip("-")
    return s[:max_len] or "rule"


def _assign_rule_id(
    pattern_obj: Dict[str, Any],
    file_stem: str,
    taken: set,
    duplicates: Optional[set] = None,
) -> str:
    """Generate (or honor) an ID for a bash pattern. Mutates pattern_obj in place.

    A DERIVED id is de-conflicted with a ``-2`` suffix, but an EXPLICIT ``id:``
    is honored verbatim — pinning is the whole point, and renaming one would
    silently break the ``disabled_rules`` / ``unattended_allow`` entry that names
    it. So collisions are possible, and they are never benign: two live rules
    sharing one id makes both of those knobs ambiguous, and ambiguity on the
    surface #914's scoped grants are built on is not something to discover from
    behaviour. Collisions are recorded in ``duplicates`` and surfaced by
    ``agentwire doctor`` / ``safety status`` / ``safety lint`` (#916).

    A duplicate id is also the ONLY detector for a partially-applied rule set: a
    new bundled file landing next to a stale one that still carries the same
    pinned ids is otherwise invisible.
    """
    existing = pattern_obj.get("id")
    if isinstance(existing, str) and existing.strip():
        pattern_obj["id"] = existing.strip()
        if pattern_obj["id"] in taken and duplicates is not None:
            duplicates.add(pattern_obj["id"])
        taken.add(pattern_obj["id"])
        return pattern_obj["id"]
    slug = _slug_for_rule(pattern_obj.get("reason", "rule"))
    candidate = f"{file_stem}.{slug}"
    n = 2
    while candidate in taken:
        candidate = f"{file_stem}.{slug}-{n}"
        n += 1
    pattern_obj["id"] = candidate
    taken.add(candidate)
    return candidate


def load_config(
    rules_dir: Path,
    tooldefs_dir: Optional[Path] = None,
) -> Dict[str, Any]:
    """Load and merge all rule YAMLs in ``rules_dir`` plus tooldef ask-patterns.

    Bash patterns get a stable ``id`` field (``"<file>.<slug-of-reason>"``) so
    they can be referenced by the ``safety.disabled_rules`` config.
    """
    merged: Dict[str, Any] = {
        "bashToolPatterns": [],
        "mcpToolPolicies": [],
        "zeroAccessPaths": [],
        "readOnlyPaths": [],
        "noDeletePaths": [],
        "allowedPaths": [],
    }
    if not yaml:
        # No YAML parser ⇒ we cannot load ANY rules. Returning the empty rule set
        # would silently disable all protection (fail OPEN). Mark the config so
        # the decision ladder fails CLOSED instead.
        merged["_parser_unavailable"] = "pyyaml unavailable — cannot load rules"
        return merged
    if not rules_dir.exists():
        return merged
    taken_ids: set = set()
    duplicate_ids: set = set()
    yaml_files = sorted(rules_dir.glob("*.yaml"))
    for rules_file in yaml_files:
        try:
            with open(rules_file, "r") as f:
                data = yaml.safe_load(f) or {}
            for key in merged:
                items = data.get(key, []) or []
                if key in ("bashToolPatterns", "mcpToolPolicies"):
                    for it in items:
                        if isinstance(it, dict):
                            _assign_rule_id(it, rules_file.stem, taken_ids, duplicate_ids)
                            it.setdefault("source", rules_file.stem)
                merged[key].extend(items)
        except Exception:
            continue
    if tooldefs_dir is not None:
        tooldef_patterns = load_write_patterns_from_tooldefs(tooldefs_dir)
        for it in tooldef_patterns:
            _assign_rule_id(it, "tooldef", taken_ids, duplicate_ids)
            it.setdefault("source", "tooldef")
        merged["bashToolPatterns"].extend(tooldef_patterns)
    # Only present when something is actually wrong, so the healthy merged
    # config keeps exactly the keys it always had.
    if duplicate_ids:
        merged["_duplicate_rule_ids"] = sorted(duplicate_ids)
    return merged


# ============================================================================
# UNATTENDED (NO-HUMAN-PRESENT) RESOLUTION
# ============================================================================
#
# The damage-control hook classifies commands into allow / block / ask. The
# ``ask`` tier only means something when a human is present to confirm. Under
# the scheduler (cron, nobody watching) sessions run with
# ``--dangerously-skip-permissions``, so historically ``ask`` resolved to a
# SILENT allow — an unsupervised agent could deploy / drop a table / force-push.
#
# When a session is marked unattended (``AGENTWIRE_UNATTENDED=1``, stamped at
# dispatch by the scheduler), the hook resolves ``ask`` by FAILING CLOSED:
# block + notify the owner, UNLESS the matched rule's stable ID carries a GRANT.
# Grants come from three sources, most specific first:
#   1. ``AGENTWIRE_UNATTENDED_ALLOW`` — the per-task extension the scheduler
#      stamps from a task's ``unattended_allow``,
#   2. ``safety.unattended_allow`` from the host-owned damage-control files,
#   3. ``DEFAULT_UNATTENDED_ALLOW`` below (work + open a PR + notify the owner
#      by email — nothing else irreversible or outward-facing).
#
# PRECEDENCE, NOT UNION (#914): the most specific source that NAMES a rule id
# defines that rule's grant outright. A union would make the whole point of a
# scoped entry unexpressible — ``git.commit`` is already granted unscoped by the
# default set, so a task writing ``{id: git.commit, paths: [<store>]}`` under a
# union would read as a constraint and be silently meaningless. That class of
# config-that-lies is exactly what this issue is about, so naming a rule at a
# more specific level REPLACES the looser grant for that dispatch. Within one
# source, several entries for the same id union their scopes.
#
# SCOPES (#914). A grant entry is either a bare rule id (unscoped — the rule is
# permitted wherever it fires) or a mapping carrying ``paths``:
#
#     unattended_allow:
#       - outbound.agentwire-email                  # bare: unchanged, still works
#       - id: tooldef.git-create-a-commit
#         paths:
#           - ~/.claude/projects/*/memory/          # scoped: only under here
#
# A scoped grant applies only when EVERY directory the matching command would
# act on resolves inside one of ``paths``. Scope evaluation can only ever
# REFUSE a command the bare grant would have allowed; it can never permit one.
#
# WHAT IT REFUSES RATHER THAN GUESSES — an enumerated list, not a guarantee.
# ``command_scope_dirs`` refuses on: a ``cd`` not joined by ``&&``; an indirect
# runner (``sh -c``, ``xargs``, ``sudo``, ``ssh`` …); a subshell/group;
# ``eval`` / a base64 pipeline; command substitution IN A DIRECTORY-DECIDING
# POSITION (a ``cd`` target, a ``-C``/``--git-dir``/``--work-tree`` value, a
# ``GIT_DIR``-family assignment, the segment head, a git config key) — a
# substitution in an operand such as a ``-m`` message cannot move the command
# and no longer refuses (#942/#943); a ``core.worktree``/``include.*`` config
# set on the command line (``-c``/``--config-env``); an unrecognized
# environment assignment; and a rule whose pattern matches no single segment.
# It READS, rather than refuses: the cwd, ``cd <literal> &&``, git's ``-C`` /
# ``--git-dir`` / ``--work-tree``, git's ``GIT_DIR``-family environment
# assignments, the enclosing git repo root, and that root's ``core.worktree``
# redirect (#927 — measured against the scope like any other selector).
#
# That list is the honest form of the claim. An earlier draft of this comment
# said "anything that makes the target directory unknowable does not apply the
# grant", which was not true of the code beneath it: ``GIT_DIR=<other> git
# commit`` was stripped as an environment assignment and silently measured
# against the cwd — the PR reproducing the very defect class it exists to fix
# (#913 is "the rule matched a phrasing, not an operation"; this matched the
# ``-C`` phrasing and missed the assignment spelling of the same redirection,
# while the ``env(1)`` spelling was already refused). Enumerate what is handled;
# do not assert a closure property over shell semantics.
#
# NOT closed, and stated so rather than implied:
#   * The ``git config core.worktree`` REDIRECT command itself is still
#     unruled (rule-file territory, #927) — but the escape it enabled is
#     closed on the COMMIT side: scope evaluation now reads the resolved
#     repo's ``core.worktree`` and measures the redirect target against the
#     scope, so a redirected in-scope store refuses the commit. The
#     command-line spellings (``-c core.worktree=…``, ``--config-env``,
#     ``include.path``) refuse outright.
#   * Resolution is a TOCTOU window — the hook validates a path the command has
#     not used yet.
#
# Hard ``block`` rules (rm -rf, git push --force, …) are unaffected — they fire
# regardless. Interactive bypass sessions (no ``AGENTWIRE_UNATTENDED``) are
# unaffected too — their ``ask`` still resolves the old way.

# The built-in grants. Written in the SAME shape as a task's
# ``unattended_allow`` (bare id = unscoped, or ``{id, paths}`` = scoped) and
# parsed by the same parser, so a scope is expressible HERE too — not only in a
# per-task entry (#914 review §2). That matters because these ids are the
# widest grants in the system: ``git.commit`` / ``git.push`` unscoped means any
# repo on the machine, in every scheduled task, forever.
#
# They are deliberately left UNSCOPED here — narrowing them is a host policy
# decision, not something this file should make on every install's behalf, and
# a task that needs a narrower grant can already express it: naming a rule at a
# more specific level REPLACES this one (see the precedence note above), so a
# task's ``{id: git.commit, paths: [<store>]}`` genuinely binds rather than
# being swallowed by this unscoped default. A host that wants the narrow form
# machine-wide writes the scoped entry in ``~/.agentwire/damagecontrol.yml``.
#
# NOTE (#916 / review §2): these ids only exist if the LOADED tooldefs carry
# them. ``~/.agentwire/tooldefs/`` wins over the bundled copy and never
# self-heals, so on a drifted install five of the six name no rule at all and
# every one of these actions is blocked unattended. ``agentwire doctor`` now
# reports that (``_check_unattended_defaults``) instead of leaving it to be
# rediscovered as a nightly timeout.
DEFAULT_UNATTENDED_ALLOW = [
    "git.add",       # stage files
    "git.add-u",     # stage tracked changes
    "git.commit",    # commit
    "git.push",      # push (force/delete are SEPARATE hard-block/ask rules)
    "gh.pr-create",  # open a PR — the human-reviewed gate
    "outbound.agentwire-email",  # blanket allow, any recipient (#804)
    # Run the project's own tooling — tests, linters, the project CLI (#925).
    #
    # This tier is `ask` because `uv run` executes code, which is true of every
    # scheduled task by definition: the dispatch already granted "run this
    # agent on this repo". Withholding the project's OWN test runner from it
    # does not withhold code execution, it only withholds VERIFICATION — the
    # task still writes the change and still opens the PR, just without having
    # been able to run the suite over it. 18 of the 111 unattended blocks
    # measured over the 14 days to 2026-08-06 were exactly this.
    #
    # Safe to allow only because the id it grants cannot shadow a hard block.
    # Verified, not assumed: rules are evaluated in order and the FIRST match
    # returns its id, so an earlier `ask` rule CAN hide a later `block` — the
    # matrix in tests/unit/test_unattended_allow.py pins that every dangerous
    # form behind `uv run` still comes back with the DESTRUCTIVE rule's id, not
    # this one (the launcher-payload rescan that guarantees it landed in #1028).
    #
    # BOTH ids, deliberately. `uv run <script.py>` and `uv run <cmd>` are two
    # tooldef lines that compile to the IDENTICAL pattern `\buv\s+run\b`, so
    # which id a command comes back with is decided by which yaml line sits
    # higher, not by anything about the command. Allowlisting only one would be
    # guarding the phrasing: reorder uv.yaml and the permission silently
    # evaporates with nothing failing to say so.
    "tooldef.uv-run-a-script-in-project-environment",
    "tooldef.uv-run-a-command-in-project-environment",
]


def is_unattended() -> bool:
    """True when this session was dispatched with no human present (scheduler)."""
    return os.environ.get("AGENTWIRE_UNATTENDED") == "1"


