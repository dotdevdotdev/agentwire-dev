def _resolve_rules_dir() -> Path:
    """User override (~/.agentwire/damage-control/) wins; else bundled rules/."""
    user_dir = Path(os.environ.get("AGENTWIRE_DIR", os.path.expanduser("~/.agentwire")))
    user_rules = user_dir / "damage-control"
    if user_rules.exists() and any(user_rules.glob("*.yaml")):
        return user_rules
    return Path(__file__).parent / "rules"


def _resolve_tooldefs_dir():
    """User tooldefs (~/.agentwire/tooldefs/) win; else bundled."""
    user_dir = Path(os.environ.get("AGENTWIRE_DIR", os.path.expanduser("~/.agentwire")))
    user_tooldefs = user_dir / "tooldefs"
    if user_tooldefs.exists() and any(user_tooldefs.glob("*.yaml")):
        return user_tooldefs
    bundled = Path(__file__).parent.parent.parent / "tooldefs"
    return bundled if bundled.exists() else None


def _notify_unattended_block(command: str, reason: str, rule_id: str | None) -> None:
    """Fire-and-forget: email the owner that an unattended action was blocked.

    The hook is a PEP 723 script (pyyaml-only) and can't import the agentwire
    package, so it shells out to the installed CLI, which emails via the same
    Resend wiring usage-limit recovery uses. Detached + non-blocking so SMTP
    never sits on the hook's hot path; failures are swallowed (the block has
    already fired and is audit-logged regardless).
    """
    import subprocess
    try:
        subprocess.Popen(
            ["agentwire", "safety", "notify-unattended-block",
             "--reason", reason or "",
             "--rule-id", rule_id or "",
             "--command", command[:500]],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            stdin=subprocess.DEVNULL,
            start_new_session=True,
        )
    except Exception:
        pass


# Outbound MCP tools and how to synthesize the equivalent shell command they
# run under the hood. The synthesized command must match the same outbound.*
# rule the Bash shell-out matches — body is omitted (privacy + audit clarity);
# the rule keys on the verb, not the payload.
def _synthesize_command(tool_name: str, tool_input: dict) -> str | None:
    """Return the ``agentwire <verb> …`` command an outbound MCP tool runs, or None.

    Keep these in lockstep with ``email_send`` / ``quo_send`` in
    ``agentwire/mcp_server.py`` and the ``outbound.agentwire-*`` rules.
    """
    short = tool_name.split("__")[-1]  # mcp__agentwire__email_send -> email_send

    if short == "email_send":
        parts = ["agentwire", "email"]
        to = tool_input.get("to")
        recipients = to if isinstance(to, list) else ([to] if to else [])
        for addr in recipients:
            parts += ["--to", str(addr)]
        subject = tool_input.get("subject")
        if subject:
            parts += ["--subject", str(subject)]
        return " ".join(parts)

    if short == "quo_send":
        parts = ["agentwire", "quo"]
        to = tool_input.get("to")
        if to:
            parts += ["--to", str(to)]
        return " ".join(parts)

    return None


# Bridge for installs whose ~/.agentwire/damage-control/ predates
# mcp-tools.yaml (#923): a stale user rules dir wins over the bundled copy and
# carries no ``mcpToolPolicies``, so per-tool classification loads empty. Until
# the heal installs the missing file, control-plane screening must not degrade
# below the #1036 posture — this regex is consulted ONLY when zero policies
# loaded. With policies present, the same shape lives as DATA (the
# ``mcp.writeish-name`` entry in mcp-tools.yaml) and this constant is inert.
_WRITEISH_BRIDGE_RE = re.compile(
    r"(write|edit|delete|remove|move|rename|create|append|patch|mkdir|"
    r"rmdir|copy|upload|chmod|prune|kill|purge)",
    re.IGNORECASE,
)


def _iter_string_values(obj):
    if isinstance(obj, str):
        yield obj
    elif isinstance(obj, dict):
        for v in obj.values():
            yield from _iter_string_values(v)
    elif isinstance(obj, (list, tuple)):
        for v in obj:
            yield from _iter_string_values(v)


def _pathlike_args(tool_input: dict):
    """String argument values that plausibly name a filesystem path.

    Whitespace-bearing strings are prose, ``://`` marks a URL; what remains is
    screened. A missed candidate degrades to today's behaviour (unscreened),
    never to a false block.
    """
    for s in _iter_string_values(tool_input):
        if not s or " " in s or "\t" in s or "\n" in s or "://" in s:
            continue
        if "/" in s or s.startswith("~"):
            yield s


def _screen_tool_paths(tool_name: str, tool_input: dict, config: dict, writeish: bool) -> None:
    """Exit 2 when a path-valued argument violates the path ladders (#923).

    Zero-access secrets block on MENTION for every tool (same semantics as
    check_read_path — the path's mere presence in a call is the leak); the
    protected control plane is readable by design, so it is only enforced when
    the tool's POLICY says it mutates (``writeish``).
    """
    allowed = load_allowed_paths(config)
    for p in _pathlike_args(tool_input):
        blocked, reason = check_read_path(p, config)
        if not blocked and writeish:
            blocked, reason = check_protected_path(p, allowed)
        if blocked:
            log_blocked(tool_name, p, reason)
            print(f"SECURITY: Blocked MCP tool argument: {reason}: {p}", file=sys.stderr)
            sys.exit(2)


def main() -> None:
    config = load_config(_resolve_rules_dir(), _resolve_tooldefs_dir())
    config["safety"] = load_safety_config()

    try:
        input_data = json.load(sys.stdin)
    except json.JSONDecodeError as e:
        print(f"Error: Invalid JSON input: {e}", file=sys.stderr)
        sys.exit(1)
    except Exception as e:
        print(f"Error reading input: {e}", file=sys.stderr)
        sys.exit(1)

    tool_name = input_data.get("tool_name", "")
    tool_input = input_data.get("tool_input", {}) or {}
    # Same bypass semantics as the Bash hook: bypassPermissions / auto turn the
    # interactive ask into allow, but hard blocks and the unattended fail-closed
    # ladder still fire.
    permission_mode = input_data.get("permission_mode", "")
    bypass_modes = {"bypassPermissions", "auto"}

    command = _synthesize_command(tool_name, tool_input)
    if not command:
        # Not a gated outbound tool: run the per-tool policy ladder (#923
        # option 1) and screen path-valued arguments — an operation refused
        # via Bash must not be permitted via a tool.
        policy = check_mcp_tool(tool_name, config)
        decision = policy["decision"]
        reason = policy["reason"]
        rule_id = policy.get("id")

        if decision == "block":
            log_blocked(tool_name, tool_name, reason)
            print(f"SECURITY: Blocked MCP tool: {reason}", file=sys.stderr)
            sys.exit(2)

        # Path screening runs before any allow/ask verdict is emitted: a
        # protected path argument blocks regardless of the tool's tier.
        mutates = policy.get("mutates")
        if mutates is None and not config.get("mcpToolPolicies"):
            # Stale rules dir with no policies loaded — see _WRITEISH_BRIDGE_RE.
            mutates = bool(_WRITEISH_BRIDGE_RE.search(tool_name.split("__")[-1]))
        _screen_tool_paths(tool_name, tool_input, config, bool(mutates))

        if decision == "ask" and is_unattended():
            # No human present: fail closed unless the policy's id is granted.
            # A tool call names no directory, so scopeable=False — a
            # path-scoped grant refuses rather than guessing (#914).
            grants = resolve_unattended_grants(config)
            granted, why = unattended_grant_allows(
                rule_id, tool_name, grants, os.getcwd(), scopeable=False,
            )
            if granted:
                log_allowed(tool_name, tool_name, user_approved=False)
                sys.exit(0)
            try:
                log_blocked(tool_name, tool_name, f"unattended: {reason} — {why}",
                            rule_id=rule_id)
            except TypeError:
                log_blocked(tool_name, tool_name, f"unattended: {reason} — {why}")
            _notify_unattended_block(tool_name, f"{reason} — {why}", rule_id)
            print(f"SECURITY: Blocked (unattended — no human to confirm): {reason}",
                  file=sys.stderr)
            print(f"Tool: {tool_name}", file=sys.stderr)
            print(f"Why: {why}", file=sys.stderr)
            if rule_id and rule_id not in grants:
                print(f"To permit this for an unattended task, add rule id "
                      f"'{rule_id}' to its .agentwire.tasks.yml task `unattended_allow`.",
                      file=sys.stderr)
            sys.exit(2)
        elif decision == "ask" and permission_mode not in bypass_modes:
            log_asked(tool_name, tool_name, reason)
            print(json.dumps({
                "hookSpecificOutput": {
                    "hookEventName": "PreToolUse",
                    "permissionDecision": "ask",
                    "permissionDecisionReason": reason,
                }
            }))
            sys.exit(0)

        sys.exit(0)

    result = check_command(command, config)
    decision = result["decision"]
    reason = result["reason"]

    if decision == "block":
        try:
            log_blocked(tool_name, command, reason, pattern=result.get("pattern"), rule_id=result.get("id"))
        except TypeError:
            log_blocked(tool_name, command, reason)
        print(f"SECURITY: Blocked: {reason}", file=sys.stderr)
        print(f"Command: {command[:100]}{'...' if len(command) > 100 else ''}", file=sys.stderr)
        sys.exit(2)
    elif decision == "ask" and is_unattended():
        # No human present (scheduler dispatch). The interactive confirm is
        # meaningless, so fail closed: BLOCK + notify the owner, unless the
        # matched rule is explicitly on the unattended allowlist.
        rule_id = result.get("id")
        grants = resolve_unattended_grants(config)
        # `command` here is SYNTHESIZED from the tool call (`agentwire email
        # --to …`) — it names no directory, so a path-scoped grant cannot be
        # evaluated and must refuse (#914). Unscoped grants are unaffected.
        granted, why = unattended_grant_allows(
            rule_id, command, grants, os.getcwd(),
            pattern=result.get("pattern"), scopeable=False,
        )
        if granted:
            log_allowed(tool_name, command, user_approved=False)
            sys.exit(0)
        try:
            log_blocked(tool_name, command, f"unattended: {reason} — {why}",
                        pattern=result.get("pattern"), rule_id=rule_id)
        except TypeError:
            log_blocked(tool_name, command, f"unattended: {reason} — {why}")
        _notify_unattended_block(command, f"{reason} — {why}", rule_id)
        print(f"SECURITY: Blocked (unattended — no human to confirm): {reason}", file=sys.stderr)
        print(f"Command: {command[:100]}{'...' if len(command) > 100 else ''}", file=sys.stderr)
        print(f"Why: {why}", file=sys.stderr)
        if rule_id and rule_id not in grants:
            print(f"To permit this for an unattended task, add rule id "
                  f"'{rule_id}' to its .agentwire.tasks.yml task `unattended_allow`.",
                  file=sys.stderr)
        sys.exit(2)
    elif decision == "ask" and (
        permission_mode not in bypass_modes or result.get("unverifiable")
    ):
        # Same #934 rule as the Bash hook: a verb-concealing (unverifiable)
        # ask is never demoted to allow by bypassPermissions/auto.
        log_asked(tool_name, command, reason)
        output = {
            "hookSpecificOutput": {
                "hookEventName": "PreToolUse",
                "permissionDecision": "ask",
                "permissionDecisionReason": reason,
            }
        }
        print(json.dumps(output))
        sys.exit(0)
    elif result.get("escape"):
        log_escape(tool_name, command, result.get("escape_reason") or "")
        sys.exit(0)
    elif result.get("disabled"):
        log_disabled(tool_name, command)
        sys.exit(0)
    else:
        log_allowed(tool_name, command, user_approved=False)
        sys.exit(0)


if __name__ == "__main__":
    main()
