def _protected_path_patterns() -> List[str]:
    """Protected paths in both ``~``-form and ``$HOME``-expanded form.

    Commands may reference either; including both ensures the regex/glob
    matchers catch e.g. ``/Users/me/.claude/settings.json`` and
    ``~/.claude/settings.json`` alike.
    """
    out: List[str] = []
    for p in PROTECTED_CONTROL_PLANE_PATHS:
        out.append(p)
        expanded = os.path.expanduser(p)
        if expanded != p:
            out.append(expanded)
    return out


def _matched_protected_pattern(file_path: str) -> Optional[str]:
    """The protected-path pattern that matches ``file_path``, if any."""
    for pat in _protected_path_patterns():
        if match_path(file_path, pat):
            return pat
    return None


def is_protected_control_plane(file_path: str) -> bool:
    """True if ``file_path`` is part of the damage-control control plane."""
    return _matched_protected_pattern(file_path) is not None


def _protected_reason(matched_pattern: str) -> str:
    """Block reason for a protected-control-plane hit, tailored to the path.

    ``.agentwire.tasks.yml`` has a real, host-side remedy (propose-and-promote,
    #720) — name it so the agent doesn't dead-end. Everything else keeps the
    generic "edit on the host" message.
    """
    if matched_pattern.endswith(".agentwire.tasks.yml"):
        return (
            "protected task-execution control-plane file (host-owned) — draft "
            "to .agentwire.tasks.proposed.yml instead, then ask the host to run "
            "`agentwire tasks review` and `agentwire tasks promote`"
        )
    return "protected control-plane file (host-owned; edit on the host)"


def check_protected_path(
    file_path: str,
    allowed_paths: List[Dict[str, Any]],
) -> Tuple[bool, str]:
    """Block edits/writes to a control-plane file unless the user allowlisted it.

    Used by the edit/write hooks. The allowlist (a human opt-in) may override;
    nothing else does.
    """
    matched = _matched_protected_pattern(file_path)
    if matched:
        if is_path_allowed_for_op(file_path, allowed_paths, "edit"):
            return False, ""
        return True, _protected_reason(matched)
    return False, ""


def check_protected_command(
    command: str,
    allowed_paths: List[Dict[str, Any]],
) -> Tuple[bool, str]:
    """Block a bash command that writes/edits/deletes a control-plane file.

    Mirrors the ``readOnlyPaths`` matcher but is escape-hatch- and
    kill-switch-exempt. The user's allowlist may re-permit a specific path.

    Matches against the raw command AND its normalized subcommands so quoting /
    escaping (``r\\m``, ``r''m``) can't sneak a write past the control-plane gate.
    """
    subcommands, _ambiguous = normalize_subcommands(command)
    haystacks = [command] + [s for s in subcommands if s and s != command]
    for path in _protected_path_patterns():
        for hay in haystacks:
            matched, reason = check_path_patterns(
                hay,
                path,
                READ_ONLY_BLOCKED + INTERPRETER_WRITE_PATTERNS,
                "protected control-plane path",
            )
            if matched:
                op = _infer_operation_from_reason(reason)
                if is_command_path_allowed(command, allowed_paths, op):
                    break
                return True, _protected_reason(path)
    return False, ""


# ============================================================================
# PROTECTED COMMANDS (escape-hatch- AND kill-switch-EXEMPT, like the protected
# control plane above, but keyed on COMMAND SHAPE rather than a file path)
# ============================================================================
#
# Some operations are dangerous no matter which file they touch — running
# them at all IS the confused-deputy escape, not merely writing a particular
# path. ``agentwire tasks promote`` is the first case (#720/#721 review):
# it's the host-trusted program that copies a vetted draft into the protected
# ``.agentwire.tasks.yml``. If a policed/unattended agent could just invoke
# the CLI itself, the file protection above is moot — so this, like the
# protected-path check, is evaluated before ``detect_escape_hatch`` and the
# kill switch, and has NO allowlist override (there's no legitimate reason
# for an agent to ever run this; unlike a path, there's nothing to allowlist
# it TO). This is defense in depth on TOP OF ``cmd_tasks_promote``'s own
# runtime refusal (unattended check + host-context gate in ``tasks_cli.py``)
# — that second gate is what actually closes the ``python3 -c
# "from agentwire.tasks_cli import cmd_tasks_promote; ..."`` bypass, since a
# raw interpreter call never matches a bash command pattern at all.

PROTECTED_COMMAND_PATTERNS: List[Tuple[str, str]] = [
    (
        r'\bagentwire\s+tasks\s+promote\b',
        "agentwire tasks promote writes the protected .agentwire.tasks.yml — "
        "host-only, run it from your own terminal (not through an agent).",
    ),
]


def check_protected_bash_command(command: str) -> Tuple[bool, str]:
    """Block a command matching a ``PROTECTED_COMMAND_PATTERNS`` entry.

    Unconditional — no allowlist override, no escape hatch, no kill switch
    (see module note above). These are COMMAND-PREFIX patterns, so — like the
    ``anchored`` tooldef bashToolPatterns (#675) — matched only against
    ``masked_subcommands``: quoting/escaping of the command itself still
    normalizes to the literal form (``agentwire tasks prom''ote`` can't sneak
    past), but quoted CONTENT (a commit message, an echo string) that merely
    *mentions* the phrase is masked out first, so it can't false-match.
    """
    haystacks = masked_subcommands(command)
    for pattern, reason in PROTECTED_COMMAND_PATTERNS:
        for hay in haystacks:
            try:
                if re.search(pattern, hay, re.IGNORECASE):
                    return True, reason
            except re.error:
                continue
    return False, ""


_ESCAPE_HATCH_RE = re.compile(r"#\s*allow:[ \t]*([^\n]+)", re.IGNORECASE)


def detect_escape_hatch(command: str) -> Optional[str]:
    """Return the reason if ``command`` contains a ``# allow: <reason>`` marker.

    Non-empty reason required; matches the rest of the comment line so the
    marker works on multi-line / chained commands too.
    """
    if not command:
        return None
    m = _ESCAPE_HATCH_RE.search(command)
    if not m:
        return None
    reason = m.group(1).strip()
    return reason or None


# ============================================================================
# SHELL-AWARE NORMALIZATION
# ============================================================================
#
# The bash matcher historically ran the rule regexes against the RAW command
# string. With no tokenization, trivial shell quoting/escaping defeated every
# rule: ``r\m -rf /x`` (backslash), ``r''m -rf /x`` (empty quotes),
# ``R=rm; $R -rf /x`` ($VAR indirection) all read as ALLOWED while literal
# ``rm -rf /x`` blocked. We now ALSO match against a normalized form where
# quotes/escapes are removed (via ``shlex``) and simple ``$VAR`` assignments are
# resolved, split per subcommand. Anything we cannot tokenize safely — command
# substitution (``$(...)`` / backticks), ``eval``, a ``base64 -d | sh`` pipeline,
# or unbalanced quotes — FAILS CLOSED (escalated to ``ask``, which the unattended
# resolver turns into a block).

_SUBSTITUTION_RE = re.compile(r"\$\(|`")
_EVAL_RE = re.compile(r"(?:^|[\s;&|({])eval(?:\s|$)")
_BASE64_PIPE_RE = re.compile(r"\bbase64\b[^\n|]*(?:-d|--decode)[^\n|]*\|", re.IGNORECASE)
_ASSIGN_RE = re.compile(
    r"(?:^|[\n;&|]|&&|\|\|)\s*([A-Za-z_]\w*)=('[^']*'|\"[^\"]*\"|[^\s;|&]*)"
)
_SHELL_OPERATORS = {";", "&&", "||", "|", "&", "\n", ";;", "|&"}


def detect_obfuscation(command: str) -> Optional[str]:
    """Return a reason string if ``command`` hides intent behind shell features.

    These constructs can smuggle a dangerous command past static matching, so we
    decline to reason about them and fail closed instead.
    """
    if _SUBSTITUTION_RE.search(command):
        return "command substitution"
    if _EVAL_RE.search(command):
        return "eval"
    if _BASE64_PIPE_RE.search(command):
        return "base64-decode pipeline"
    return None


def normalize_subcommands(command: str) -> Tuple[List[str], Optional[str]]:
    """Tokenize ``command`` and return ``(normalized_subcommands, ambiguous)``.

    ``normalized_subcommands`` is the per-subcommand argv re-joined with single
    spaces, after ``shlex`` has stripped quotes/escapes and simple ``$VAR``
    assignments earlier in the same command have been resolved. ``ambiguous`` is
    a reason string when the command can't be tokenized safely (and the caller
    should fail closed); it is ``None`` on success.
    """
    obf = detect_obfuscation(command)
    if obf:
        return [], obf

    # Resolve simple ``VAR=value`` assignments so ``R=rm; $R -rf`` normalizes to
    # ``rm -rf``. Only literal values (no nested expansion) are resolved.
    assigns: Dict[str, str] = {}
    for m in _ASSIGN_RE.finditer(command):
        assigns[m.group(1)] = m.group(2).strip("'\"")

    try:
        lex = shlex.shlex(command, posix=True, punctuation_chars=True)
        lex.whitespace_split = True
        tokens = list(lex)
    except ValueError:
        return [], "unbalanced quotes"

    def _resolve(tok: str) -> str:
        for name, val in assigns.items():
            tok = tok.replace("${%s}" % name, val).replace("$" + name, val)
        return tok

    subs: List[str] = []
    cur: List[str] = []
    for tok in tokens:
        if tok in _SHELL_OPERATORS:
            if cur:
                subs.append(" ".join(cur))
                cur = []
            continue
        cur.append(_resolve(tok))
    if cur:
        subs.append(" ".join(cur))
    return subs, None


#
# CONTENT MASKING (#675)
#
# Tooldef rules are COMMAND-PREFIX rules (``\bgh\s+pr\s+comment\b``), but the
# haystacks above include quoted argument text — so a commit message that
# merely *mentions* "gh pr comment" false-matches the rule. Anchored rules are
# therefore matched against MASKED subcommands instead: quoted spans that can
# only be content (a quoted token containing whitespace — a message, an echo
# string, a heredoc body) are replaced with a placeholder, while quoted
# single words are kept (``"gh" pr comment`` is still a real command) and
# ``sh -c "…"`` payloads are recursively re-scanned as commands.

_MASK = "\x00"
_HEREDOC_RE = re.compile(r"<<-?\s*(['\"]?)([A-Za-z_]\w+)\1")
_SHELL_NAMES = {"sh", "bash", "zsh", "dash", "ksh"}
_ASSIGN_TOKEN_RE = re.compile(r"^[A-Za-z_]\w*=")


#
# GIT GLOBAL OPTIONS (#913)
#
# Every git rule — both the hand-written ``bashToolPatterns`` in the rule YAMLs
# (``\bgit\s+push\s+--force\b``) and the tooldef-generated ones from
# ``_cmd_to_regex`` (``\bgit\s+commit\b``) — assumes the subcommand sits
# adjacent to ``git``. It doesn't have to: ``git -C <dir> <cmd>`` is the
# idiomatic way to operate on a repo without ``cd``, and ``\s+`` cannot span
# ``-C /repo``. That single assumption defeated EVERY git rule, force-push and
# hard-reset included.
#
# Rather than teach ~15 patterns about ``-C`` (and miss the next one written),
# we emit an extra haystack per subcommand with git's global options removed,
# so present and future git rules inherit the fix for free.
#
# This is strictly ADDITIVE — the un-stripped forms stay in the haystack list.
# A rule that legitimately cares WHICH repo is being touched (a path rule, an
# allowlist check) still sees ``-C /repo`` in the raw command; stripping can
# only ever remove tokens, so the extra variant can introduce no path a rule
# didn't already see.
#
# Membership below is measured against real git (2.50.1), not assumed:
# ``-C``/``-c`` require a SEPARATE argument (``-C/tmp`` is rejected by git, so
# the attached form is not a bypass); ``--git-dir``/``--work-tree``/
# ``--namespace``/``--config-env``/``--attr-source`` accept both the ``=`` and
# the space form; ``--exec-path`` without ``=`` prints and exits, so it
# consumes nothing.

_GIT_GLOBAL_VALUE_OPTS = {
    "-C", "-c", "--git-dir", "--work-tree", "--namespace",
    "--config-env", "--attr-source",
}

_GIT_GLOBAL_FLAGS = {
    "-p", "-P", "--paginate", "--no-pager", "--bare", "--exec-path",
    "--no-optional-locks", "--no-replace-objects", "--no-lazy-fetch",
    "--no-advice", "--literal-pathspecs", "--glob-pathspecs",
    "--noglob-pathspecs", "--icase-pathspecs", "--html-path", "--man-path",
    "--info-path",
}

# Tokens allowed to precede ``git`` while still counting as a git invocation
# (``sudo git -C /repo push --force`` must normalize too — the un-stripped
# ``sudo git push --force`` already matches, so leaving this out would keep the
# very inconsistency the rule is meant to remove). ``_MASK`` covers a leading
# ``VAR=value`` assignment, which ``masked_subcommands`` has already masked.
#
# The exclusion is about ARITY AS WRITTEN, not about which wrapper it is. Every
# name below is covered when it appears BARE; the same name carrying its own
# arguments is not — ``xargs git …`` normalizes, ``xargs -n1 git …`` does not,
# and likewise ``nice`` vs ``nice -n 5``. The wrapper's argument is an
# unrecognized token, the scan bails, and no variant is produced, so that form
# keeps the bypass.
#
# Naming wrappers rather than arity is precisely the error this comment used to
# make: it listed ``xargs -n1`` as an excluded WRAPPER, which read as excluding
# ``xargs``, and bare ``xargs git -C /repo push --force`` stayed a live bypass
# under a comment implying otherwise.
#
# Argument-carrying forms are out of scope rather than half-handled, because
# consuming them means modelling each wrapper's own grammar — this bug's
# mistake at one remove. Failure there is a MISSING haystack, never an
# over-strip: we add nothing rather than stripping too much.
_GIT_INVOCATION_PREFIXES = {
    "sudo", "doas", "env", "command", "time", "nice", "nohup", "xargs", _MASK,
}


def _strip_git_global_options(words: List[str]) -> Optional[List[str]]:
    """Return ``words`` with git's global options removed, or ``None``.

    ``None`` means "no normalized variant to add": not a git invocation, no
    global options present, or nothing left after the options.
    """
    git_idx = None
    for i, w in enumerate(words):
        if w.rsplit("/", 1)[-1] == "git":
            git_idx = i
            break
        if w not in _GIT_INVOCATION_PREFIXES and not _ASSIGN_TOKEN_RE.match(w):
            return None
    if git_idx is None:
        return None

    i = git_idx + 1
    stripped = False
    while i < len(words):
        word = words[i]
        if word in _GIT_GLOBAL_VALUE_OPTS:
            # Consumes the following argument along with the flag — dropping
            # only the flag would leave the value sitting where the subcommand
            # should be, and the rule would still miss.
            i += 2
            stripped = True
            continue
        if word in _GIT_GLOBAL_FLAGS:
            i += 1
            stripped = True
            continue
        base = word.split("=", 1)[0]
        if "=" in word and (base in _GIT_GLOBAL_VALUE_OPTS or base in _GIT_GLOBAL_FLAGS):
            i += 1
            stripped = True
            continue
        # MAINTENANCE EDGE: an option git adds after 2.50.1 is an unrecognized
        # token here, so the scan stops and the partial strip leaves the
        # subcommand still out of reach — ``git --future-opt -C /r push --force``
        # reads as allow. Not exploitable today (git rejects the unknown option
        # itself), and nothing in the suite fails when git grows one, so
        # re-measure both sets on a git upgrade. Stopping is deliberate: the
        # alternative — treating anything option-shaped as strippable — would
        # let an unknown value-taking option swallow the subcommand.
        break

    if not stripped or i >= len(words):
        return None
    return words[: git_idx + 1] + words[i:]


def git_normalized_haystacks(command: str) -> List[str]:
    """Return the git-global-options-stripped forms of ``command``, if any.

    This is an ADDITIVE haystack, kept alongside the raw and masked lists
    rather than rewriting either, and fed to ALL rules — anchored and
    unanchored alike. Both halves of that sentence are load-bearing.

    ADDITIVE, because stripping is DELETION. ``-c <k>=<v>`` values are executed
    by git (``core.sshCommand``, ``core.pager``, ``alias.*``,
    ``core.fsmonitor``), so the value is a command payload sitting in the
    haystack. Where a content rule DOES match that payload — the deletion rules
    catch an ``rm``-shaped one — rewriting a haystack in place would delete it
    from the only place it appears and turn a block into an allow: the fix
    creating a worse bug than the one it closes. Coverage of these payloads is
    partial, not a guarantee this function provides: a ``curl … | sh`` value is
    allowed with or without normalization. Additivity preserves whatever
    coverage exists; it does not create any.
    (Note it is deletion, not masking, that would lose them: ``masked_subcommands``
    blanks a token only when it is FULLY quoted, and ``core.pager='…'`` carries
    an unquoted ``core.pager=`` prefix, so the payload survives masking and is
    visible in both existing haystacks.) A rule that legitimately cares WHICH
    repo is being touched — a path rule, an unattended path scope (#914) — reads
    those same un-stripped forms: the ``-C`` argument is set aside, not discarded.

    FED TO ALL RULES, because the intersection "must stay unanchored AND
    global-option-bypassable" is unreachable by a two-way split. Rules that are
    deliberately unanchored to catch an ssh-wrapped form would never see
    normalization and would stay permanently bypassed.

    Masking is applied to the new path exactly as it is to the old one — the
    variant is built from the MASKED token lists, so the anchored path receives
    the normalized command masked, rather than being handed an unmasked
    haystack that would reopen #675 on every anchored git rule.
    """
    out: List[str] = []
    for words in _masked_subcommand_words(command):
        normalized = _strip_git_global_options(words)
        if normalized is not None:
            joined = " ".join(normalized)
            if joined not in out:
                out.append(joined)
    return out


def _strip_heredoc_bodies(command: str) -> str:
    """Remove heredoc body lines (``<<EOF … EOF``) — they are content."""
    m = _HEREDOC_RE.search(command)
    if not m:
        return command
    delim = m.group(2)
    nl = command.find("\n", m.end())
    if nl == -1:
        return command
    lines = command[nl + 1:].split("\n")
    for i, line in enumerate(lines):
        if line.strip() == delim:
            rest = "\n".join(lines[i + 1:])
            return command[:nl + 1] + _strip_heredoc_bodies(rest)
    # Unterminated heredoc: everything after the marker is body.
    return command[:nl + 1]


def _scan_masked_tokens(command: str) -> List[List[Tuple[str, bool]]]:
    """Split ``command`` into subcommands of ``(token_text, fully_quoted)``.

    Quotes/escapes are resolved into the token text (so ``g''h`` -> ``gh``);
    ``fully_quoted`` is True when no character of the token was unquoted.
    """
    subs: List[List[Tuple[str, bool]]] = []
    cur: List[Tuple[str, bool]] = []
    buf: List[str] = []
    has_unquoted = False
    has_any = False

    def end_token() -> None:
        nonlocal buf, has_unquoted, has_any
        if has_any:
            cur.append(("".join(buf), not has_unquoted))
        buf, has_unquoted, has_any = [], False, False

    def end_sub() -> None:
        nonlocal cur
        end_token()
        if cur:
            subs.append(cur)
            cur = []

    i, n = 0, len(command)
    while i < n:
        c = command[i]
        if c == "'":
            j = command.find("'", i + 1)
            if j == -1:
                j = n
            buf.append(command[i + 1:j])
            has_any = True
            i = j + 1
        elif c == '"':
            j = i + 1
            out: List[str] = []
            while j < n and command[j] != '"':
                if command[j] == "\\" and j + 1 < n and command[j + 1] in '"\\$`':
                    out.append(command[j + 1])
                    j += 2
                else:
                    out.append(command[j])
                    j += 1
            buf.append("".join(out))
            has_any = True
            i = j + 1
        elif c == "\\" and i + 1 < n:
            buf.append(command[i + 1])
            has_unquoted = True
            has_any = True
            i += 2
        elif c in " \t":
            end_token()
            i += 1
        elif c in ";\n":
            end_sub()
            i += 1
        elif c in "&|":
            end_sub()
            while i < n and command[i] in "&|":
                i += 1
        else:
            buf.append(c)
            has_unquoted = True
            has_any = True
            i += 1
    end_sub()
    return subs


def masked_subcommands(command: str) -> List[str]:
    """Return per-subcommand strings with content-only quoted spans masked.

    Used for command-prefix (``anchored``) rules so quoted argument text —
    commit messages, echo strings, heredoc bodies — cannot false-match a
    command rule, while quoting obfuscation of the command itself still
    normalizes to the literal form.
    """
    return [" ".join(words) for words in _masked_subcommand_words(command)]


def _masked_subcommand_words(command: str) -> List[List[str]]:
    """Token-list form of :func:`masked_subcommands`, before joining.

    Split out so the ``sh -c "…"`` recursion and the git normalization both
    operate on tokens — re-splitting a joined string would lose the token
    boundaries a ``-C "/my dir"`` argument depends on.
    """
    command = _strip_heredoc_bodies(command)

    assigns: Dict[str, str] = {}
    for m in _ASSIGN_RE.finditer(command):
        assigns[m.group(1)] = m.group(2).strip("'\"")

    def _resolve(tok: str) -> str:
        for name, val in assigns.items():
            tok = tok.replace("${%s}" % name, val).replace("$" + name, val)
        return tok

    results: List[List[str]] = []
    for toks in _scan_masked_tokens(command):
        words: List[str] = []
        prev = ""
        for text, fully_quoted in toks:
            resolved = _resolve(text)
            is_content = fully_quoted and (not resolved or any(ch in " \t\n" for ch in resolved))
            if not words and _ASSIGN_TOKEN_RE.match(resolved):
                # Leading VAR=value assignment — its value is data here (the
                # assigns table already handles later ``$VAR`` expansion).
                words.append(_MASK)
                prev = _MASK
                continue
            if is_content:
                # A ``sh -c "…"`` payload is a command, not content — rescan.
                if (
                    words
                    and prev.startswith("-")
                    and "c" in prev
                    and words[0].rsplit("/", 1)[-1] in _SHELL_NAMES
                ):
                    results.extend(_masked_subcommand_words(resolved))
                words.append(_MASK)
                prev = _MASK
            else:
                words.append(resolved)
                prev = resolved
        if words and any(w != _MASK for w in words):
            results.append(words)
    return results


