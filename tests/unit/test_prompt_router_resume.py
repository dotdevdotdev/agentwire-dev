"""The resume dialog: detection, routing, root escalation, doctor (#905).

THE FIXTURE IS THE POINT OF THIS FILE. ``RESUME_DIALOG`` is
``tmux capture-pane -p`` output **from a 200-column pane** genuinely sitting at
this dialog, reproduced on 2026-08-05 by resuming a cloned 134k-token
conversation with the gating feature flag enabled in an isolated ``HOME``. The
option labels and body sentence were cross-checked against the string literals
in the shipped Claude Code binary (2.1.222), so they are the product's text and
not a transcription of a screenshot.

**Always record the capture width**, right next to the capture. The dialog's
body sentence is 122 columns, so it is unwrapped only on a pane wider than
that, and every narrower pane breaks a line inside it. The first version of
this file pasted that 122-column body next to an 80-column rule — a screen no
capture can produce — and the detector it exercised located its anchor with a
plain ``str.index``, which raised ``ValueError`` at 54 of the 101 widths
between 40 and 140. A single comment naming the width would have made that
visible at review time without anyone running a sweep.

So every wrapped case here is generated by :func:`render_at_width` rather than
hand-reflowed, and the width sweep asserts DETECTION at each width, not merely
the absence of an exception — with the per-pane guard in place, a broken
detector produces silent misses rather than crashes, which is strictly harder
to diagnose and would sail past an "it didn't raise" assertion.

That is the same lesson as #901 (single-launch), #898 (single-pane) and #902
(flat session names): the fixture decides what the suite can see. Here it
applied twice — first to the dialog shape that had no fixture at all, then to
the pane width that every fixture happened to share.
"""

