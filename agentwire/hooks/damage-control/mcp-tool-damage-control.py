# Tokens allowed to precede the tool while still counting as an invocation
# (``sudo git -C /repo push --force`` must normalize too — the un-stripped
# ``sudo git push --force`` already matches, so leaving this out would keep the
# very inconsistency the rule is meant to remove). ``_MASK`` covers a leading
# ``VAR=value`` assignment, which ``masked_subcommands`` has already masked.
#
# The exclusion is about ARITY AS WRITTEN, not about which wrapper it is. Every
# name below is covered when it appears BARE; the same name carrying its own
# arguments is not — ``xargs git …`` normalizes, ``xargs -n1 git …`` does not,
# and likewise ``nice`` vs ``nice -n 5``. The wrapper's argument is an
# unrecognized token, the scan bails, and no variant is produced, so that form
# keeps the bypass.
#
# Naming wrappers rather than arity is precisely the error this comment used to
# make: it listed ``xargs -n1`` as an excluded WRAPPER, which read as excluding
# ``xargs``, and bare ``xargs git -C /repo push --force`` stayed a live bypass
# under a comment implying otherwise.
#
# Argument-carrying forms are out of scope rather than half-handled, because
# consuming them means modelling each wrapper's own grammar — this bug's
# mistake at one remove. Failure there is a MISSING haystack, never an
# over-strip: we add nothing rather than stripping too much.
_WRAPPER_PREFIXES = {
    "sudo", "doas", "env", "command", "time", "nice", "nohup", "xargs", _MASK,
}


def _short_cluster_span(word: str, grammar: Dict[str, Any]) -> Optional[int]:
    """Tokens consumed by a bundled/attached short-option cluster, or ``None``.

    ``-Lname`` is one token (the value rides along); ``-uL name`` is two (the
    value-taking option ends the cluster). An unrecognized character bails the
    whole cluster rather than guessing — a guess here can swallow a subcommand.
    """
    if not word.startswith("-") or word.startswith("--") or len(word) < 2:
        return None
    chars = word[1:]
    for idx, ch in enumerate(chars):
        opt = "-" + ch
        if opt in grammar["value"]:
            # Anything left in the cluster IS the value; otherwise it is the
            # next token.
            return 1 if idx < len(chars) - 1 else 2
        if opt in grammar["flag"]:
            continue
        return None
    return 1


def _strip_global_options(words: List[str]) -> Optional[List[str]]:
    """Return ``words`` with the tool's global options removed, or ``None``.

    ``None`` means "no normalized variant to add": not an invocation of a tool
    in the table, no global options present, or nothing left after the options.
    """
    tool_idx = None
    grammar = None
    for i, w in enumerate(words):
        candidate = _GLOBAL_OPTION_TABLE.get(w.rsplit("/", 1)[-1])
        if candidate is not None:
            tool_idx = i
            grammar = candidate
            break
        if w not in _WRAPPER_PREFIXES and not _ASSIGN_TOKEN_RE.match(w):
            return None
    if grammar is None:
        return None

    i = tool_idx + 1
    stripped = False
    while i < len(words):
        word = words[i]
        if grammar["plus_selector"] and len(word) > 1 and word.startswith("+"):
            i += 1
            stripped = True
            continue
        if word in grammar["value"]:
            # Consumes the following argument along with the flag — dropping
            # only the flag would leave the value sitting where the subcommand
            # should be, and the rule would still miss.
            i += 2
            stripped = True
            continue
        if word in grammar["flag"]:
            i += 1
            stripped = True
            continue
        base = word.split("=", 1)[0]
        if "=" in word and (
            base in grammar["value"]
            or base in grammar["flag"]
            or base in grammar["value_eq_only"]
        ):
            i += 1
            stripped = True
            continue
        if grammar["short_cluster"]:
            span = _short_cluster_span(word, grammar)
            if span is not None:
                i += span
                stripped = True
                continue
        # MAINTENANCE EDGE: an option a tool adds after the measured version is
        # an unrecognized token here, so the scan stops and the partial strip
        # leaves the subcommand still out of reach — ``git --future-opt -C /r
        # push --force`` reads as allow. Not exploitable today (the tool
        # rejects the unknown option itself), and nothing in the suite fails
        # when a tool grows one, so re-measure a row on a tool upgrade.
        # Stopping is deliberate: the alternative — treating anything
        # option-shaped as strippable — would let an unknown value-taking
        # option swallow the subcommand.
        break

    if not stripped or i >= len(words):
        return None
    return words[: tool_idx + 1] + words[i:]


def global_option_normalized_haystacks(command: str) -> List[str]:
    """Return the global-options-stripped forms of ``command``, if any.

    This is an ADDITIVE haystack, kept alongside the raw and masked lists
    rather than rewriting either, and fed to ALL rules — anchored and
    unanchored alike. Both halves of that sentence are load-bearing.

    ADDITIVE, because stripping is DELETION. Some stripped values are COMMAND
    PAYLOADS: ``-c <k>=<v>`` values are executed by git (``core.sshCommand``,
    ``core.pager``, ``alias.*``, ``core.fsmonitor``), and ``tmux -c
    '<shell-command>'`` is executed by tmux, so the value is a command sitting
    in the haystack. Where a content rule DOES match that payload — the deletion rules
    catch an ``rm``-shaped one — rewriting a haystack in place would delete it
    from the only place it appears and turn a block into an allow: the fix
    creating a worse bug than the one it closes. Coverage of these payloads is
    partial, not a guarantee this function provides: a ``curl … | sh`` value is
    allowed with or without normalization. Additivity preserves whatever
    coverage exists; it does not create any.
    (Note it is deletion, not masking, that would lose them: ``masked_subcommands``
    blanks a token only when it is FULLY quoted, and ``core.pager='…'`` carries
    an unquoted ``core.pager=`` prefix, so the payload survives masking and is
    visible in both existing haystacks.) A rule that legitimately cares WHICH
    repo, cluster, profile or socket is being targeted — a path rule, an
    unattended path scope (#914) — reads those same un-stripped forms: the
    ``-C``/``--context``/``-L`` argument is set aside, not discarded.

    FED TO ALL RULES, because the intersection "must stay unanchored AND
    global-option-bypassable" is unreachable by a two-way split. Rules that are
    deliberately unanchored to catch an ssh-wrapped form would never see
    normalization and would stay permanently bypassed.

    Masking is applied to the new path exactly as it is to the old one — the
    variant is built from the MASKED token lists, so the anchored path receives
    the normalized command masked, rather than being handed an unmasked
    haystack that would reopen #675 on every anchored rule.
    """
    out: List[str] = []
    for words in _masked_subcommand_words(command):
        normalized = _strip_global_options(words)
        if normalized is not None:
            joined = " ".join(normalized)
            if joined not in out:
                out.append(joined)
    return out


def _strip_heredoc_bodies(command: str) -> str:
    """Remove heredoc body lines (``<<EOF … EOF``) — they are content."""
    m = _HEREDOC_RE.search(command)
    if not m:
        return command
    delim = m.group(2)
    nl = command.find("\n", m.end())
    if nl == -1:
        return command
    lines = command[nl + 1:].split("\n")
    for i, line in enumerate(lines):
        if line.strip() == delim:
            rest = "\n".join(lines[i + 1:])
            return command[:nl + 1] + _strip_heredoc_bodies(rest)
    # Unterminated heredoc: everything after the marker is body.
    return command[:nl + 1]


def _scan_masked_tokens(command: str) -> List[List[Tuple[str, bool, bool]]]:
    """Split ``command`` into subcommands of ``(text, fully_quoted, expands)``.

    Quotes/escapes are resolved into the token text (so ``g''h`` -> ``gh``);
    ``fully_quoted`` is True when no character of the token was unquoted.

    ``expands`` is True when the token contains a command substitution the
    shell will actually RUN — i.e. ``$(...)`` or a backtick span appearing
    unquoted or inside DOUBLE quotes. Inside single quotes the shell performs no
    expansion, so ``git commit -m '$(...)'`` is an inert literal and must stay
    maskable; treating it as a command is a false positive on a string nothing
    executes.
    """
    subs: List[List[Tuple[str, bool, bool]]] = []
    cur: List[Tuple[str, bool, bool]] = []
    buf: List[str] = []
    has_unquoted = False
    has_any = False
    expands = False

    def _has_subst(text: str) -> bool:
        return "$(" in text or "`" in text

    def end_token() -> None:
        nonlocal buf, has_unquoted, has_any, expands
        if has_any:
            cur.append(("".join(buf), not has_unquoted, expands))
        buf, has_unquoted, has_any, expands = [], False, False, False

    def end_sub() -> None:
        nonlocal cur
        end_token()
        if cur:
            subs.append(cur)
            cur = []

    i, n = 0, len(command)
    while i < n:
        c = command[i]
        if c == "'":
            j = command.find("'", i + 1)
            if j == -1:
                j = n
            # Single quotes suppress expansion entirely — deliberately does NOT
            # set `expands`, however substitution-shaped the contents look.
            buf.append(command[i + 1:j])
            has_any = True
            i = j + 1
        elif c == '"':
            j = i + 1
            out: List[str] = []
            while j < n and command[j] != '"':
                if command[j] == "\\" and j + 1 < n and command[j + 1] in '"\\$`':
                    out.append(command[j + 1])
                    j += 2
                else:
                    out.append(command[j])
                    j += 1
            span = "".join(out)
            if _has_subst(span):
                expands = True
            buf.append(span)
            has_any = True
            i = j + 1
        elif c == "\\" and i + 1 < n:
            buf.append(command[i + 1])
            has_unquoted = True
            has_any = True
            i += 2
        elif c in " \t":
            end_token()
            i += 1
        elif c in ";\n":
            end_sub()
            i += 1
        elif c in "&|":
            end_sub()
            while i < n and command[i] in "&|":
                i += 1
        else:
            buf.append(c)
            if c == "`" or (c == "(" and buf[-2:-1] == ["$"]):
                expands = True
            has_unquoted = True
            has_any = True
            i += 1
    end_sub()
    return subs


def masked_subcommands(command: str, keep=None) -> List[str]:
    """Return per-subcommand strings with content-only quoted spans masked.

    Used for command-prefix (``anchored``) rules so quoted argument text —
    commit messages, echo strings, heredoc bodies — cannot false-match a
    command rule, while quoting obfuscation of the command itself still
    normalizes to the literal form.

    ``keep`` is an optional predicate over a resolved content token; a token it
    accepts stays visible instead of being masked. The path ladders use it to
    keep quoted operands that mention the guarded path (#922).
    """
    return [" ".join(words) for words in _masked_subcommand_words(command, keep)]


def _masked_subcommand_words(command: str, keep=None) -> List[List[str]]:
    """Token-list form of :func:`masked_subcommands`, before joining."""
    return [words for words, _payload in _masked_subcommand_entries(command, keep)]


def _masked_subcommand_entries(
    command: str, keep=None, _depth: int = 0
) -> List[Tuple[List[str], bool]]:
    """``(words, is_payload_text)`` form of :func:`masked_subcommands`.

    Split out so the ``sh -c "…"`` recursion and the git normalization both
    operate on tokens — re-splitting a joined string would lose the token
    boundaries a ``-C "/my dir"`` argument depends on.

    ``is_payload_text`` marks an entry that is executable TEXT extracted from
    an exec-surface option (``python3 -c '…'``) rather than a command whose
    tokens hold shell positions — anchored matching must scan those anywhere,
    never at command position (#922).
    """
    command = _strip_heredoc_bodies(command)

    assigns: Dict[str, str] = {}
    for m in _ASSIGN_RE.finditer(command):
        assigns[m.group(1)] = m.group(2).strip("'\"")

    def _resolve(tok: str) -> str:
        for name, val in assigns.items():
            tok = tok.replace("${%s}" % name, val).replace("$" + name, val)
        return tok

    if _depth > _RESCAN_MAX_DEPTH:
        return []
    results: List[Tuple[List[str], bool]] = []
    for toks in _scan_masked_tokens(command):
        words: List[str] = []
        # Resolved text of EVERY token, content included — the wrapper-payload
        # rescan below (#924/#921) needs the text the masked entry blanks.
        raws: List[str] = []
        prev = ""
        for text, fully_quoted, expands in toks:
            resolved = _resolve(text)
            raws.append(resolved)
            # A quoted token holding a COMMAND SUBSTITUTION is not content, no
            # matter how much prose surrounds it: ``git commit -m "$(rm -rf
            # /x)"`` runs the payload. Masking it hid the payload from every
            # anchored rule, and because ``git.commit`` carries an UNSCOPED
            # default grant the residual ``ask`` resolved to ALLOW with no human
            # — the fail-closed guarantee gone for that shape (#915 review).
            #
            # The failure needed three things and no one of them alone: this
            # PR's anchoring (payload unseen), #917's unscoped grant (ask ->
            # allow unattended), and the pre-existing whitespace-keyed masking.
            # The ``echo "$(…)"`` control has the same shape with no grant and
            # still fails closed, which is what proves the grant load-bearing.
            #
            # NB the mirror arrangement (``rm -rf "$(cat f)"`` — dangerous verb
            # OUTSIDE the quotes) never broke: masking blanks the same token,
            # but the verb is in command position and survives. The hazard is
            # a benign outer command with the danger INSIDE the quotes.
            #
            # Not masking is strictly MORE inclusive, so it cannot weaken any
            # rule; the cost is that a report quoting a substitution alongside a
            # rule token can false-positive again, which is the safe direction.
            # `expands` comes from the SCANNER, which knows the quote type:
            # single quotes suppress expansion, so `git commit -m '$(...)'` is
            # an inert literal and stays maskable. Deriving this from `resolved`
            # instead would lose that distinction and false-positive on a string
            # the shell never runs.
            is_content = (
                fully_quoted
                and not expands
                and (not resolved or any(ch in " \t\n" for ch in resolved))
            )
            if not words and _ASSIGN_TOKEN_RE.match(resolved):
                # Leading VAR=value assignment — its value is data here (the
                # assigns table already handles later ``$VAR`` expansion).
                words.append(_MASK)
                prev = _MASK
                continue
            if is_content:
                # A ``sh -c "…"`` payload is a command, not content — rescan.
                #
                # ANY word so far may be the shell, not just words[0]: a wrapper
                # prefix (``env FOO=1 sh -c``, ``nohup sh -c``, ``timeout 5 sh
                # -c``, ``xargs -I{} sh -c``, ``find . -exec sh -c``) puts the
                # shell in the middle. Keying on words[0] alone meant every one
                # of those payloads was masked away with nothing rescanning it —
                # a BLOCK -> ALLOW regression once the rules are anchored, since
                # the raw haystack is no longer consulted for them.
                #
                # DO NOT HARMONISE THIS WITH ``_strip_global_options``, which
                # scans only the narrow ``_WRAPPER_PREFIXES`` set and documents
                # the resulting gap. The two loops look alike and want OPPOSITE
                # answers, because they do different things:
                #
                #   here  — RE-SCANS a quoted payload that is already isolated.
                #           A false positive costs a rescan of prose, bounded,
                #           and anchoring is what contains it.
                #   there — SYNTHESISES a new command-position haystack. Scan
                #           any word and ``echo git -C /r push --force`` finds
                #           "git" at index 1, emits ``echo git push --force``,
                #           and the force-push rule matches an ECHO — a false
                #           BLOCK on prose, produced by the guard that exists
                #           because prose was being blocked (#675/#915).
                #
                # Verified: that echo is ``allow`` today and must stay so.
                # Any-word is right for a payload you re-scan and wrong for a
                # haystack you construct.
                if (
                    words
                    and prev.startswith("-")
                    and "c" in prev
                    and any(w.rsplit("/", 1)[-1] in _SHELL_NAMES for w in words)
                ):
                    results.extend(
                        _masked_subcommand_entries(resolved, keep, _depth + 1)
                    )
                elif keep is not None and keep(resolved):
                    # Ladder keep-predicate (#922): this content token mentions
                    # the guarded path, so it stays visible — masking may only
                    # remove verbs that had nothing to do with the path.
                    words.append(resolved)
                    prev = resolved
                    continue
                else:
                    # Not a shell payload — but it may still be the value of an
                    # EXEC SURFACE option, where the token is executable text
                    # rather than data. Emit it as its own haystack entry so the
                    # anchored rules see it; do NOT re-parse it as shell, since
                    # `python3 -c` payloads are Python that merely contain a
                    # command.
                    exec_flags = None
                    for w in words:
                        cand = _EXEC_SURFACES.get(w.rsplit("/", 1)[-1])
                        if cand is not None:
                            exec_flags = cand
                            break
                    if exec_flags is not None and (
                        not exec_flags or prev in exec_flags
                    ):
                        results.append(([resolved], True))
                words.append(_MASK)
                prev = _MASK
            else:
                words.append(resolved)
                prev = resolved
        if words and any(w != _MASK for w in words):
            results.append((words, False))
        # Wrapper-payload rescan (#924) + exec-valued git config values (#921):
        # both are commands smuggled through a single segment's arguments, and
        # both are re-scanned as commands in their own right so every rule —
        # anchored ones at real command positions — applies to them. Reads
        # ``raws`` because the masked walk above has already blanked quoted
        # payloads to ``_MASK``.
        payloads: List[str] = []
        ssh_payload = _ssh_remote_payload(raws)
        if ssh_payload:
            payloads.append(ssh_payload)
        payloads.extend(_git_exec_config_payloads(raws))
        for payload in payloads:
            results.extend(_masked_subcommand_entries(payload, keep, _depth + 1))
    return results


#
# COMMAND-POSITION ENFORCEMENT FOR ANCHORED RULES (#922, mechanism 3)
#
# ``anchored: true`` has always MEANT "match command position only, never
# argument content" (#675), but the implementation only swapped the haystack —
# the regex itself still matched anywhere in the masked string. Masking removes
# multi-word quoted prose, so what slipped through was every verb that arrives
# as a bare or single-word-quoted OPERAND: ``grep -c "rm" core.yaml`` matched
# ``\brm\s+[^-]`` inside grep's arguments, and a trailing ``# comment``
# mentioning ``git reset --hard`` matched the reset rule (the whitespace-keyed
# masking gap in #922).
#
# The fix is positional: an anchored rule's match must START inside one of the
# tokens that can actually BE the command — the leading wrapper chain (sudo,
# env, xargs, timeout 5, nice -n 19 …) plus the first real command token.
# ``grep`` ends that chain, so ``rm`` as grep's operand is no longer a
# matchable position; ``rm`` after ``sudo -u user`` still is. Spans cover the
# whole token, so a path-invoked ``/usr/bin/git push`` still matches at ``git``.
#
# Two entry classes are exempt and scanned anywhere, both because their text
# has no shell positions to enforce: exec-surface payloads (``python3 -c '…'``,
# emitted as bare program text) and segments running a tool whose arguments ARE
# a program (the _EXEC_SURFACES / _SHELL_NAMES tables — tmux/watch/awk/sh…).
# Rules that deliberately match argument content (payloads.yaml, remote.yaml)
# are unanchored and read the raw haystacks; nothing here touches them.

# Wrappers whose presence keeps the command position OPEN: the real command of
# ``sudo rm`` / ``timeout 5 rm`` / ``npx prisma`` is still the next token. A
# superset of ``_WRAPPER_PREFIXES`` (which synthesizes haystacks and must stay
# narrow — see the note there); here a too-wide entry only costs a false BLOCK,
# never a bypass, so the arg-taking runners and package launchers are included.
_POSITION_WRAPPERS = _WRAPPER_PREFIXES | {
    "timeout", "setsid", "stdbuf", "ionice", "parallel",
    # package launchers — ``npx prisma migrate deploy`` runs prisma
    "npx", "pnpx", "bunx", "uvx", "pipx",
    # two-token launchers (``uv run <tool>``, ``npm exec <tool>``): both halves
    # keep the chain open; the worst case is an extra allowed START, never a
    # missed one.
    "uv", "npm", "pnpm", "yarn", "bun", "bundle", "run", "exec", "dlx",
}


def _allowed_match_spans(words: List[str]) -> List[Tuple[int, int]]:
    """Char spans of ``" ".join(words)`` where an anchored rule may START.

    Walks the leading wrapper chain: wrapper names, masks, assignments,
    option-shaped tokens, their values and bare numbers all keep the chain
    open; the first token that is none of those is the real command — its span
    is the last allowed one. Every token in the chain is itself an allowed
    start (the wrapper might be the ruled tool, as in ``\\bsudo\\s+rm\\b``).
    """
    spans: List[Tuple[int, int]] = []
    pos = 0
    prev_was_option = False
    for word in words:
        spans.append((pos, pos + len(word)))
        pos += len(word) + 1
        base = word.rsplit("/", 1)[-1]
        if base in _POSITION_WRAPPERS or word == _MASK or _ASSIGN_TOKEN_RE.match(word):
            prev_was_option = False
            continue
        if word.startswith("-"):
            prev_was_option = True
            continue
        if prev_was_option or (word[:1].isdigit()):
            prev_was_option = False
            continue
        break
    return spans


def anchored_match_entries(command: str) -> List[Tuple[str, Optional[List[Tuple[int, int]]]]]:
    """``(haystack, allowed start spans | None)`` pairs for anchored rules.

    ``None`` means match anywhere — exec-surface payload text and segments
    whose tool executes its arguments (see the section note above).
    """
    entries: List[Tuple[str, Optional[List[Tuple[int, int]]]]] = []
    for words, payload in _masked_subcommand_entries(command):
        text = " ".join(words)
        if payload or "$(" in text or "`" in text or any(
            w.rsplit("/", 1)[-1] in _EXEC_SURFACES
            or w.rsplit("/", 1)[-1] in _SHELL_NAMES
            or " " in w or "\t" in w
            for w in words
        ):
            # Match anywhere: payload text has no shell positions; a LIVE
            # command substitution runs wherever it sits — position-gating
            # ``git commit -m "$(rm -rf /x)"`` would hand the payload to the
            # granted carrier rule instead of the rm rule (#915 review); and a
            # token with INTERNAL whitespace is a quoted payload riding an
            # unquoted prefix (``git -c core.pager='rm -rf /x' fetch``), whose
            # coverage lives on matching inside it.
            entries.append((text, None))
        else:
            entries.append((text, _allowed_match_spans(words)))
    return entries


def _normalized_match_entries(command: str) -> List[Tuple[str, Optional[List[Tuple[int, int]]]]]:
    """Global-option-stripped variants with their allowed start spans."""
    out: List[Tuple[str, Optional[List[Tuple[int, int]]]]] = []
    seen: set = set()
    for words, payload in _masked_subcommand_entries(command):
        normalized = _strip_global_options(words)
        if normalized is None:
            continue
        text = " ".join(normalized)
        if text in seen:
            continue
        seen.add(text)
        out.append((text, None if payload else _allowed_match_spans(normalized)))
    return out


def _search_match_entries(
    pattern: str,
    entries: List[Tuple[str, Optional[List[Tuple[int, int]]]]],
) -> bool:
    """``re.search`` over entries, honoring each entry's allowed start spans."""
    for text, spans in entries:
        try:
            if spans is None:
                if re.search(pattern, text, re.IGNORECASE):
                    return True
                continue
            for m in re.finditer(pattern, text, re.IGNORECASE):
                if any(start <= m.start() < end for start, end in spans):
                    return True
        except re.error:
            return False
    return False


