def check_command(command: str, config: Dict[str, Any]) -> Dict[str, Any]:
    """Decide whether a bash command should be allowed/blocked/asked.

    Returns ``{decision, reason, pattern, command}`` plus optional ``id``,
    ``escape_reason``, ``escape``, ``disabled``.

    Order:
      0. Protected control plane → BLOCK (escape-hatch- AND kill-switch-exempt;
         only the user's allowlist re-permits) — runs FIRST so an agent can't
         self-authorize a write to the files that gate everything else.
      0.5. Protected commands → BLOCK (same exemption, no allowlist override —
         a command whose mere invocation is the escape, not a path it touches).
      1. Escape hatch (``# allow: <reason>``) → ALLOW (escape=True)
      2. Kill switch (``config["safety"]["enabled"] is False``) → ALLOW (disabled=True)
      3. Hard-blocked bash patterns (skip if ``id`` in ``disabled_rules``)
      4. Ask patterns
      5. Bypassable bash patterns → check allowlist for required operation
      6. zeroAccessPaths → check allowlist with ``read`` permission
      7. readOnlyPaths → match against READ_ONLY_BLOCKED operation patterns
      8. noDeletePaths → match against NO_DELETE_BLOCKED patterns
    """
    safety_cfg = config.get("safety", {}) if isinstance(config.get("safety"), dict) else {}
    disabled_rules = set(safety_cfg.get("disabled_rules", []) or [])
    is_enabled = safety_cfg.get("enabled", True)

    allowed = load_allowed_paths(config)

    # Protected control plane FIRST — before the escape hatch and the kill
    # switch. An agent must never be able to self-authorize a write to the
    # files that define safety itself (#466).
    prot_blocked, prot_reason = check_protected_command(command, allowed)
    if prot_blocked:
        return {
            "decision": "block",
            "reason": prot_reason,
            "pattern": "protectedControlPlane",
            "command": command,
            "protected": True,
        }

    # Protected COMMANDS — same tier, same reason (an agent-invoked
    # `agentwire tasks promote` is the confused-deputy escape itself, not a
    # path it happens to touch).
    cmd_blocked, cmd_reason = check_protected_bash_command(command)
    if cmd_blocked:
        return {
            "decision": "block",
            "reason": cmd_reason,
            "pattern": "protectedCommand",
            "command": command,
            "protected": True,
        }

    # Parser unavailable ⇒ no rules loaded ⇒ fail closed (block), before the
    # escape hatch / kill switch can wave it through.
    if config.get("_parser_unavailable"):
        return {
            "decision": "block",
            "reason": str(config["_parser_unavailable"]),
            "pattern": "parserUnavailable",
            "command": command,
        }

    escape_reason = detect_escape_hatch(command)
    if escape_reason:
        return {
            "decision": "allow",
            "reason": f"Escape hatch: {escape_reason}",
            "pattern": None,
            "command": command,
            "escape": True,
            "escape_reason": escape_reason,
        }

    if is_enabled is False:
        return {
            "decision": "allow",
            "reason": "safety disabled",
            "pattern": None,
            "command": command,
            "disabled": True,
        }

    bash_patterns = config.get("bashToolPatterns", [])
    zero_access = config.get("zeroAccessPaths", [])
    read_only = config.get("readOnlyPaths", [])
    no_delete = config.get("noDeletePaths", [])

    # Match rules against the raw command AND its normalized subcommands, so a
    # quoting/escaping/$VAR trick (``r\m``, ``r''m``, ``R=rm; $R -rf``) is caught
    # the same as the literal form. ``ambiguous`` is set when the command hides
    # behind substitution/eval/base64-pipe/unbalanced-quotes — we fail closed to
    # ``ask`` at the end (the unattended resolver turns that into a block).
    subcommands, ambiguous = normalize_subcommands(command)
    haystacks = [command] + [s for s in subcommands if s and s != command]
    # Anchored (command-prefix) rules match only masked subcommands, so quoted
    # argument text — commit messages, echo strings — can't false-match (#675),
    # and only at COMMAND POSITION, so a bare/single-word operand can't supply
    # the verb either (#922) — see anchored_match_entries.
    anchored_entries = anchored_match_entries(command)
    # Third variant (#913 git, #919 the class): the tool with its global
    # options stripped, so a rule written as ``\bgit\s+push\b`` or
    # ``\btmux\s+kill-server\b`` still sees the subcommand behind
    # ``git -C <dir>`` / ``tmux -L <socket>``. ADDED to whichever list a rule
    # already reads — neither is rewritten — so the raw command stays reachable
    # for the rules that need it, and derived from the masked tokens so it can
    # never make quoted content matchable. Both halves are load-bearing:
    # bundled git rules are anchored (masked path), while the rules installed
    # on this machine carry zero ``anchored: true`` and read the raw path, so
    # covering one alone would fix the bypass in only one of the two rule sets
    # in play.
    normalized_haystacks = global_option_normalized_haystacks(command)
    normalized_entries = _normalized_match_entries(command)

    def _search(pat: str, hays: List[str]) -> bool:
        for hay in hays:
            try:
                if re.search(pat, hay, re.IGNORECASE):
                    return True
            except re.error:
                return False
        return False

    bypassable_matches: List[Tuple[str, str, Optional[str]]] = []
    # A block match outranks an ask match regardless of rule-file load order:
    # `git -c core.pager="rm -rf /x" log` matches both `git.config-exec-key`
    # (ask) and the rm rule (block), and returning whichever the loop met
    # first would demote a hard block to a confirm (#921). Ask matches are
    # therefore recorded and returned only after every rule has been read.
    first_ask: Optional[Dict[str, Any]] = None

    for pattern_obj in bash_patterns:
        if not isinstance(pattern_obj, dict):
            continue
        rule_id = pattern_obj.get("id")
        if rule_id and rule_id in disabled_rules:
            continue
        pattern = pattern_obj.get("pattern", "")
        reason = pattern_obj.get("reason", "Matched pattern")
        should_ask = pattern_obj.get("ask", False)
        bypassable = pattern_obj.get("bypassable", False)
        anchored = pattern_obj.get("anchored", False)
        try:
            if anchored:
                hit = _search_match_entries(pattern, anchored_entries + normalized_entries)
            else:
                hit = _search(pattern, haystacks + normalized_haystacks)
            if hit:
                if should_ask:
                    if first_ask is None:
                        first_ask = {
                            "decision": "ask",
                            "reason": reason,
                            "pattern": pattern,
                            "command": command,
                            "id": rule_id,
                        }
                elif bypassable:
                    bypassable_matches.append((pattern, reason, rule_id))
                else:
                    return {
                        "decision": "block",
                        "reason": reason,
                        "pattern": pattern,
                        "command": command,
                        "id": rule_id,
                    }
        except re.error:
            continue

    for pattern, reason, rule_id in bypassable_matches:
        operation = _infer_operation_from_reason(reason)
        if not is_command_path_allowed(command, allowed, operation):
            return {
                "decision": "block",
                "reason": reason,
                "pattern": pattern,
                "command": command,
                "id": rule_id,
            }

    # Ordering (#915 × #921 × #934). A rule-level ask returns HERE — after
    # every rule block (so `git -c core.pager="<deletion>" log` blocks by the
    # deletion rule no matter which rule file loads first) but BEFORE the path
    # ladders, whose prose-prone verb+path pairing is exactly the #915 false
    # positive an anchored ask like `git.commit` exists to absorb. The one
    # exception is a VERB-CONCEALING command: its ask id may be granted or
    # bypass-demoted, so letting it shadow the concealment verdict would
    # compose a grant with a substitution into an unguarded run — concealment
    # is decided after the ladders (a real ladder block still outranks it)
    # and outranks the collected ask.
    concealing = ambiguity_conceals_verb(command) if ambiguous else None
    if first_ask is not None and not concealing:
        return first_ask

    for path in zero_access:
        if any(matches_path_in_command(path, hay) for hay in haystacks):
            if is_command_path_allowed(command, allowed, "read"):
                continue
            return {
                "decision": "block",
                "reason": f"Zero-access path: {path}",
                "pattern": f"zeroAccessPath: {path}",
                "command": command,
            }

    # The readOnly/noDelete ladders pair a destructive verb with the path, so
    # the verb must come from command text, never quoted content (#922) — the
    # keep-predicate haystacks keep path-mentioning operands visible while
    # masking prose. zeroAccessPaths stays on the raw haystacks: it blocks a
    # MENTION regardless of any verb, so masking has nothing to fix there.
    for path in read_only:
        op = None
        for hay in path_ladder_haystacks(command, path):
            matched, reason = check_path_patterns(hay, path, READ_ONLY_BLOCKED, "read-only path")
            if matched:
                op = _infer_operation_from_reason(reason)
                break
        if op is not None:
            if is_command_path_allowed(command, allowed, op):
                continue
            return {
                "decision": "block",
                "reason": f"Read-only path: {path}",
                "pattern": f"readOnlyPath: {path}",
                "command": command,
            }

    for path in no_delete:
        if any(
            check_path_patterns(hay, path, NO_DELETE_BLOCKED, "no-delete path")[0]
            for hay in path_ladder_haystacks(command, path)
        ):
            if is_command_path_allowed(command, allowed, "delete"):
                continue
            return {
                "decision": "block",
                "reason": f"No-delete path: {path}",
                "pattern": f"noDeletePath: {path}",
                "command": command,
            }

    # Verb concealment outranks the ordinary ask collected above (`uv run
    # $(echo rm) -rf` matches the uv-run ask rule, whose id may carry an
    # unattended grant and is demoted by bypass — the unverifiable tier must
    # win whenever the command's verb cannot be seen), and only a real block
    # outranks concealment.
    if concealing:
        return {
            "decision": "ask",
            "reason": (
                f"Unverifiable command ({concealing}) — nothing can "
                "analyze what this runs, so a human must confirm it "
                "(not demoted by bypass)"
            ),
            "pattern": f"ambiguous:{concealing}",
            "command": command,
            "id": "core.ambiguous-command",
            "unverifiable": True,
        }

    if first_ask is not None:
        return first_ask

    # Nothing matched. If the command hid behind substitution/eval/etc. we
    # could not verify it statically — fail closed to ``ask``. Two populations
    # share this fallback and resolve differently by mode (#934): a
    # verb-concealing shape is UNVERIFIABLE-BY-CONSTRUCTION, and the hooks do
    # not demote it to allow under bypassPermissions/auto — obscuring a
    # payload must never be the permissive path. An operand-position
    # substitution keeps the ordinary ask tier, which bypass demotes (the
    # documented "don't stop me for things you recognize" trade). Unattended
    # resolves both to block (minus grants).
    if ambiguous:
        # Concealing shapes returned above, before the ask ladder; what
        # reaches here is operand-position substitution — the ordinary,
        # bypass-demotable confirm.
        return {
            "decision": "ask",
            "reason": f"Unverifiable command ({ambiguous}) — confirm before running",
            "pattern": f"ambiguous:{ambiguous}",
            "command": command,
            "id": "core.ambiguous-command",
        }

    return {
        "decision": "allow",
        "reason": "No patterns matched",
        "pattern": None,
        "command": command,
    }


def check_path(file_path: str, config: Dict[str, Any]) -> Tuple[bool, str]:
    """File-path-only check used by edit/write hooks. Returns ``(blocked, reason)``.

    The protected control plane is checked FIRST, before the kill switch — the
    files that gate safety stay agent-unwritable even when safety is disabled;
    only the user's allowlist re-permits them (#466).
    """
    allowed = load_allowed_paths(config)

    prot_blocked, prot_reason = check_protected_path(file_path, allowed)
    if prot_blocked:
        return True, prot_reason

    safety_cfg = config.get("safety", {}) if isinstance(config.get("safety"), dict) else {}
    if safety_cfg.get("enabled", True) is False:
        return False, ""

    if is_path_allowed_for_op(file_path, allowed, "edit"):
        return False, ""

    for zero_path in config.get("zeroAccessPaths", []):
        if match_path(file_path, zero_path):
            return True, f"zero-access path {zero_path} (no operations allowed)"

    for readonly in config.get("readOnlyPaths", []):
        if match_path(file_path, readonly):
            return True, f"read-only path {readonly}"

    return False, ""


def check_read_path(file_path: str, config: Dict[str, Any]) -> Tuple[bool, str]:
    """File-path-only check for content-reading tools (Read/Grep/Glob).

    The Bash/Edit/Write hooks never see native ``Read``/``Grep``/``Glob`` tool
    calls, so a ``zeroAccessPaths`` secret (``~/.agentwire/.env``, ``~/.ssh/id_rsa``,
    ``*.pem``) could be exfiltrated by reading it directly. Claude Code fires a
    blocking ``PreToolUse`` hook for these tools too, so the read-tool hook runs
    ``file_path`` through this check and blocks a zero-access read.

    Only ``zeroAccessPaths`` deny reads — ``readOnlyPaths`` are readable by
    definition, and the control plane is host-owned config the agent may read
    (only its *writes* are blocked). The kill switch disables this like any other
    rule; the allowlist (a human opt-in) re-permits a specific read.
    """
    allowed = load_allowed_paths(config)
    if is_path_allowed_for_op(file_path, allowed, "read"):
        return False, ""

    safety_cfg = config.get("safety", {}) if isinstance(config.get("safety"), dict) else {}
    if safety_cfg.get("enabled", True) is False:
        return False, ""

    for zero_path in config.get("zeroAccessPaths", []):
        if match_path(file_path, zero_path):
            return True, f"zero-access path {zero_path} (no read access)"

    return False, ""


# ============================================================================
# MCP TOOL POLICY (#923)
# ============================================================================
#
# The bash rules are written against shell command STRINGS; an MCP tool call is
# a name plus a JSON argument object, so those rules cannot transfer without
# importing the string-matching defects (#915/#916). What a rule MEANS for a
# structured tool call is a per-tool classification — issue #923's option (1):
# each tool carries a tier the same decision ladder the Bash hook uses, with a
# stable id that ``unattended_allow`` / ``disabled_rules`` can name.
#
# Policies live in the same rule YAMLs the heal deploys, under
# ``mcpToolPolicies``. An entry is::
#
#     - tool: mcp__agentwire__worktree_remove   # exact full tool name, OR
#       match: "(write|delete|remove)"          # regex searched on the name
#       tier: ask            # allow | ask | block   (default: ask)
#       mutates: true        # screen protected control-plane path args
#       id: mcp.agentwire.worktree-remove
#       reason: tears down a worktree and can delete a branch
#
# First match wins, in rule-file load order. ``mutates`` decides whether the
# tool's path-valued arguments are screened against the PROTECTED control
# plane (zero-access secrets are screened for every tool regardless — the
# path's mere presence in a call is the leak). Defaulted to true for any
# non-``allow`` tier.
#
# THE DEFAULT FOR UNCLASSIFIED TOOLS — the decision #923 calls "the whole
# design" — is ALLOW with path screening, i.e. exactly the #1036 posture,
# stated as data rather than implied by a matcher. Fail-closed would make
# every unclassified tool (every third-party server, every tool added after
# this file shipped) dead until classified — and in an unattended session a
# wrongful tool refusal is a silent loop, which prices worse than the residual
# gap: the dangerous core is classified explicitly, secrets are screened for
# every tool, and control-plane writes are caught by the bundled name-shape
# fallback entry (data, host-editable — no longer a hardcoded regex).

_MCP_TIERS = {"allow", "ask", "block"}


def check_mcp_tool(tool_name: str, config: Dict[str, Any]) -> Dict[str, Any]:
    """Decide allow/ask/block for an MCP tool CALL by per-tool policy (#923).

    Returns ``{decision, reason, id, mutates, matched}`` — the same decision
    vocabulary as :func:`check_command`, so the hook's unattended fail-closed
    ladder and ``unattended_allow`` grants apply to tools unchanged. A tool
    call names no filesystem target, so grants are evaluated with
    ``scopeable=False`` by the caller (a path-scoped grant refuses).

    ``mutates`` is None when NO policy matched — the caller distinguishes
    "classified as non-mutating" from "unclassified" (the latter may fall back
    to a bridge heuristic on installs whose rules dir predates mcp-tools.yaml).
    """
    safety_cfg = config.get("safety", {}) if isinstance(config.get("safety"), dict) else {}
    disabled_rules = set(safety_cfg.get("disabled_rules", []) or [])

    # No YAML parser ⇒ no policies loaded ⇒ fail closed, same as check_command.
    if config.get("_parser_unavailable"):
        return {
            "decision": "block",
            "reason": str(config["_parser_unavailable"]),
            "id": None,
            "mutates": None,
            "matched": False,
        }

    if safety_cfg.get("enabled", True) is False:
        return {
            "decision": "allow",
            "reason": "safety disabled",
            "id": None,
            "mutates": None,
            "matched": False,
            "disabled": True,
        }

    for entry in config.get("mcpToolPolicies", []) or []:
        if not isinstance(entry, dict):
            continue
        rule_id = entry.get("id")
        if rule_id and rule_id in disabled_rules:
            continue
        exact = entry.get("tool")
        pattern = entry.get("match")
        hit = False
        if isinstance(exact, str) and exact:
            hit = exact == tool_name
        elif isinstance(pattern, str) and pattern:
            try:
                hit = bool(re.search(pattern, tool_name, re.IGNORECASE))
            except re.error:
                continue
        if not hit:
            continue
        tier = str(entry.get("tier", "ask")).strip().lower()
        if tier not in _MCP_TIERS:
            # An unknown tier is a policy the author believes they set. Fail
            # toward the confirmable middle, never silently to allow.
            tier = "ask"
        return {
            "decision": tier,
            "reason": entry.get("reason", f"MCP tool policy {rule_id or exact or pattern}"),
            "id": rule_id,
            "mutates": bool(entry.get("mutates", tier != "allow")),
            "matched": True,
        }

    return {
        "decision": "allow",
        "reason": "no MCP tool policy matched",
        "id": None,
        "mutates": None,
        "matched": False,
    }
