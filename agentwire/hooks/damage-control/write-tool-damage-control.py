def _cmd_to_regex(cmd: str) -> Optional[str]:
    """Convert a tooldef command string to a regex matching its fixed prefix.

    Stops at the first flag (- or --), placeholder (<...>), or optional ([...]).
    Example: ``gws gmail +send --to <addr>`` -> ``\\bgws\\s+gmail\\s+\\+send\\b``
    """
    tokens = cmd.strip().split()
    fixed = []
    for token in tokens:
        if token.startswith('<') or token.startswith('[') or token.startswith('-'):
            break
        fixed.append(token)
    if not fixed:
        return None
    parts = [re.escape(t) for t in fixed]
    pattern = r'\b' + r'\s+'.join(parts)
    last = fixed[-1]
    if last and (last[-1].isalnum() or last[-1] == '_'):
        pattern += r'\b'
    return pattern


def load_write_patterns_from_tooldefs(tooldefs_dir: Optional[Path]) -> List[Dict[str, Any]]:
    """Generate ``ask:true`` patterns from write-tier commands in tooldef YAMLs."""
    if not yaml:
        return []
    patterns: List[Dict[str, Any]] = []
    if not tooldefs_dir or not tooldefs_dir.exists():
        return patterns
    for tf_file in sorted(tooldefs_dir.glob("*.yaml")):
        try:
            with open(tf_file, "r") as f:
                data = yaml.safe_load(f) or {}
            tool_name = data.get("name", tf_file.stem)
            for cmd_def in data.get("commands", []):
                if cmd_def.get("access") != "write":
                    continue
                cmd_str = cmd_def.get("cmd", "")
                regex = _cmd_to_regex(cmd_str)
                if not regex:
                    continue
                entry = {
                    "pattern": regex,
                    "reason": f"{tool_name}: {cmd_def.get('description', cmd_str)}",
                    "ask": True,
                }
                # An explicit ``id:`` on the tooldef command yields a stable
                # rule ID (e.g. ``git.push``) that survives description edits —
                # needed so ``safety.unattended_allow`` can name it reliably.
                # Without one, ``_assign_rule_id`` derives a slug from the reason.
                if cmd_def.get("id"):
                    entry["id"] = str(cmd_def["id"])
                patterns.append(entry)
        except Exception:
            continue
    return patterns


_RULE_ID_SLUG_RE = re.compile(r"[^a-z0-9]+")


def _slug_for_rule(text: str, max_len: int = 60) -> str:
    """Lowercase, ASCII, kebab-case slug suitable for rule IDs."""
    s = _RULE_ID_SLUG_RE.sub("-", (text or "").lower()).strip("-")
    return s[:max_len] or "rule"


def _assign_rule_id(pattern_obj: Dict[str, Any], file_stem: str, taken: set) -> str:
    """Generate (or honor) an ID for a bash pattern. Mutates pattern_obj in place."""
    existing = pattern_obj.get("id")
    if isinstance(existing, str) and existing.strip():
        pattern_obj["id"] = existing.strip()
        taken.add(pattern_obj["id"])
        return pattern_obj["id"]
    slug = _slug_for_rule(pattern_obj.get("reason", "rule"))
    candidate = f"{file_stem}.{slug}"
    n = 2
    while candidate in taken:
        candidate = f"{file_stem}.{slug}-{n}"
        n += 1
    pattern_obj["id"] = candidate
    taken.add(candidate)
    return candidate


def load_config(
    rules_dir: Path,
    tooldefs_dir: Optional[Path] = None,
) -> Dict[str, Any]:
    """Load and merge all rule YAMLs in ``rules_dir`` plus tooldef ask-patterns.

    Bash patterns get a stable ``id`` field (``"<file>.<slug-of-reason>"``) so
    they can be referenced by the ``safety.disabled_rules`` config.
    """
    merged: Dict[str, Any] = {
        "bashToolPatterns": [],
        "zeroAccessPaths": [],
        "readOnlyPaths": [],
        "noDeletePaths": [],
        "allowedPaths": [],
    }
    if not yaml:
        # No YAML parser ⇒ we cannot load ANY rules. Returning the empty rule set
        # would silently disable all protection (fail OPEN). Mark the config so
        # the decision ladder fails CLOSED instead.
        merged["_parser_unavailable"] = "pyyaml unavailable — cannot load rules"
        return merged
    if not rules_dir.exists():
        return merged
    taken_ids: set = set()
    yaml_files = sorted(rules_dir.glob("*.yaml"))
    for rules_file in yaml_files:
        try:
            with open(rules_file, "r") as f:
                data = yaml.safe_load(f) or {}
            for key in merged:
                items = data.get(key, []) or []
                if key == "bashToolPatterns":
                    for it in items:
                        if isinstance(it, dict):
                            _assign_rule_id(it, rules_file.stem, taken_ids)
                            it.setdefault("source", rules_file.stem)
                merged[key].extend(items)
        except Exception:
            continue
    if tooldefs_dir is not None:
        tooldef_patterns = load_write_patterns_from_tooldefs(tooldefs_dir)
        for it in tooldef_patterns:
            _assign_rule_id(it, "tooldef", taken_ids)
            it.setdefault("source", "tooldef")
        merged["bashToolPatterns"].extend(tooldef_patterns)
    return merged


# ============================================================================
# UNATTENDED (NO-HUMAN-PRESENT) RESOLUTION
# ============================================================================
#
# The damage-control hook classifies commands into allow / block / ask. The
# ``ask`` tier only means something when a human is present to confirm. Under
# the scheduler (cron, nobody watching) sessions run with
# ``--dangerously-skip-permissions``, so historically ``ask`` resolved to a
# SILENT allow — an unsupervised agent could deploy / drop a table / force-push.
#
# When a session is marked unattended (``AGENTWIRE_UNATTENDED=1``, stamped at
# dispatch by the scheduler), the hook resolves ``ask`` by FAILING CLOSED:
# block + notify the owner, UNLESS the matched rule's stable ID is on the
# allowlist. The allowlist is the union of:
#   1. ``DEFAULT_UNATTENDED_ALLOW`` below (tight — work + open a PR, nothing
#      irreversible or outward-facing),
#   2. ``safety.unattended_allow`` from global / project config,
#   3. ``AGENTWIRE_UNATTENDED_ALLOW`` (comma-separated) — the per-task
#      extension the scheduler stamps from a task's ``unattended_allow``.
#
# Hard ``block`` rules (rm -rf, git push --force, …) are unaffected — they fire
# regardless. Interactive bypass sessions (no ``AGENTWIRE_UNATTENDED``) are
# unaffected too — their ``ask`` still resolves the old way.

DEFAULT_UNATTENDED_ALLOW = {
    "git.add",       # stage files
    "git.add-u",     # stage tracked changes
    "git.commit",    # commit
    "git.push",      # push (force/delete are SEPARATE hard-block/ask rules)
    "gh.pr-create",  # open a PR — the human-reviewed gate
}


def is_unattended() -> bool:
    """True when this session was dispatched with no human present (scheduler)."""
    return os.environ.get("AGENTWIRE_UNATTENDED") == "1"


def resolve_unattended_allow(config: Dict[str, Any]) -> set:
    """Effective unattended allowlist: defaults ∪ config ∪ per-task env extension."""
    allow = set(DEFAULT_UNATTENDED_ALLOW)
    safety_cfg = config.get("safety", {}) if isinstance(config.get("safety"), dict) else {}
    for rid in safety_cfg.get("unattended_allow", []) or []:
        if rid:
            allow.add(str(rid))
    env_allow = os.environ.get("AGENTWIRE_UNATTENDED_ALLOW", "")
    for rid in env_allow.split(","):
        rid = rid.strip()
        if rid:
            allow.add(rid)
    return allow


def load_safety_config(
    global_config_path: Optional[Path] = None,
    cwd: Optional[str] = None,
) -> Dict[str, Any]:
    """Resolve the effective safety knobs from the dedicated damage-control files.

    The kill switch and rule knobs live in HOST-OWNED, agent-unwritable files
    (see ``is_protected_control_plane``) — never in ``config.yaml`` /
    ``.agentwire.yml``, which the policed agent can edit:

      * Global:  ``~/.agentwire/damagecontrol.yml``
      * Project: ``.damagecontrol.yml`` (nearest, walking up from ``cwd``)

    Each holds top-level ``enabled`` / ``disabled_rules`` / ``unattended_allow``.
    Returns ``{enabled, disabled_rules, unattended_allow}``. A project
    ``.damagecontrol.yml`` may both loosen AND tighten ``enabled`` (it simply
    wins); ``disabled_rules`` / ``unattended_allow`` are merged (set-union).

    Fail-secure: a missing/unreadable/yaml-less global file ⇒ ``enabled: true``.
    """
    enabled = True
    disabled_rules: List[str] = []
    unattended_allow: List[str] = []
    project_enabled: Optional[bool] = None
    if not yaml:
        return {"enabled": enabled, "disabled_rules": disabled_rules,
                "unattended_allow": unattended_allow}

    def _absorb(data: Any) -> Optional[bool]:
        """Pull knobs from a parsed policy doc; return its ``enabled`` (or None)."""
        local_enabled: Optional[bool] = None
        if isinstance(data, dict):
            if "enabled" in data and data["enabled"] is not None:
                local_enabled = bool(data["enabled"])
            rules = data.get("disabled_rules", [])
            if isinstance(rules, list):
                disabled_rules.extend(str(r) for r in rules if r)
            allow = data.get("unattended_allow", [])
            if isinstance(allow, list):
                unattended_allow.extend(str(a) for a in allow if a)
        return local_enabled

    if global_config_path is None:
        global_config_path = Path.home() / ".agentwire" / "damagecontrol.yml"
    try:
        if global_config_path.exists():
            with open(global_config_path, "r") as f:
                gdata = yaml.safe_load(f) or {}
            genabled = _absorb(gdata)
            if genabled is not None:
                enabled = genabled
    except Exception:
        pass

    if cwd is None:
        cwd = os.environ.get("PWD", os.getcwd())
    current = os.path.abspath(cwd)
    while True:
        candidate = os.path.join(current, ".damagecontrol.yml")
        if os.path.isfile(candidate):
            try:
                with open(candidate, "r") as f:
                    pdata = yaml.safe_load(f) or {}
                project_enabled = _absorb(pdata)
            except Exception:
                pass
            break
        parent = os.path.dirname(current)
        if parent == current:
            break
        current = parent

    if project_enabled is not None:
        enabled = project_enabled

    return {
        "enabled": enabled,
        "disabled_rules": sorted(set(disabled_rules)),
        "unattended_allow": sorted(set(unattended_allow)),
    }


# ============================================================================
# PROTECTED CONTROL PLANE (escape-hatch- AND kill-switch-EXEMPT)
# ============================================================================
#
# Damage control reads its kill switch, its rules, and its own hook
# registration from files on disk. If the policed agent can write those files,
# it can disable safety, act, and re-enable — defeating everything (#466). So
# the WHOLE control plane is hard-protected: any write/edit/delete/move/chmod
# targeting one of these paths is BLOCKED, and — unlike every other rule — the
# ``# allow:`` escape hatch and the ``enabled: false`` kill switch do NOT
# override it. Only the user's ``allowedPaths`` allowlist can re-permit a path,
# because that is a human, host-side opt-in (the agent cannot add to it without
# editing a protected file, which is itself blocked).
#
# The guarantee: the agent only ever operates within the freedom the human
# preset. Loosening is always a host-side act.

PROTECTED_CONTROL_PLANE_PATHS = [
    "~/.agentwire/damagecontrol.yml",   # global kill switch + rule knobs
    "*.damagecontrol.yml",              # project kill switch + rule knobs (any dir)
    "~/.claude/settings.json",          # PreToolUse hook registration
    "~/.agentwire/hooks/damage-control/*.py",  # the hook scripts themselves
    "~/.claude/hooks/*",                # agentwire-owned Claude Code hooks
    "~/.agentwire/damage-control/*.yaml",      # the damage-control rule files
    # Execution-plane configs: agentwire runs strings from these files through
    # its OWN ``subprocess.run(..., shell=True)`` calls (scheduler gate commands
    # in scheduler.py, service healthchecks in services.py) — those subprocesses
    # do NOT traverse the Claude Code hook, so a policed agent that can write a
    # gate/healthcheck gets unguarded code execution on the next tick (a
    # confused-deputy escape). Treat them as control plane (#466 lockdown).
    "~/.agentwire/scheduler.yaml",      # scheduler gate commands run via shell
    "~/.agentwire/config.yaml",         # service healthcheck commands run via shell
    # Per-project task config: ``.agentwire.yml`` also defines task pre/post/gate
    # commands. Protecting it closes the same escape, with an ergonomic tradeoff —
    # under worktree dispatch the agent can no longer author its own task config,
    # so task authoring becomes a host-side act (consistent with the control-plane
    # guarantee: loosening is always host-side).
    "*.agentwire.yml",                  # project session/task config (any dir)
]


def _protected_path_patterns() -> List[str]:
    """Protected paths in both ``~``-form and ``$HOME``-expanded form.

    Commands may reference either; including both ensures the regex/glob
    matchers catch e.g. ``/Users/me/.claude/settings.json`` and
    ``~/.claude/settings.json`` alike.
    """
    out: List[str] = []
    for p in PROTECTED_CONTROL_PLANE_PATHS:
        out.append(p)
        expanded = os.path.expanduser(p)
        if expanded != p:
            out.append(expanded)
    return out


def is_protected_control_plane(file_path: str) -> bool:
    """True if ``file_path`` is part of the damage-control control plane."""
    for pat in _protected_path_patterns():
        if match_path(file_path, pat):
            return True
    return False


def check_protected_path(
    file_path: str,
    allowed_paths: List[Dict[str, Any]],
) -> Tuple[bool, str]:
    """Block edits/writes to a control-plane file unless the user allowlisted it.

    Used by the edit/write hooks. The allowlist (a human opt-in) may override;
    nothing else does.
    """
    if is_protected_control_plane(file_path):
        if is_path_allowed_for_op(file_path, allowed_paths, "edit"):
            return False, ""
        return True, "protected control-plane file (host-owned; edit on the host)"
    return False, ""


def check_protected_command(
    command: str,
    allowed_paths: List[Dict[str, Any]],
) -> Tuple[bool, str]:
    """Block a bash command that writes/edits/deletes a control-plane file.

    Mirrors the ``readOnlyPaths`` matcher but is escape-hatch- and
    kill-switch-exempt. The user's allowlist may re-permit a specific path.

    Matches against the raw command AND its normalized subcommands so quoting /
    escaping (``r\\m``, ``r''m``) can't sneak a write past the control-plane gate.
    """
    subcommands, _ambiguous = normalize_subcommands(command)
    haystacks = [command] + [s for s in subcommands if s and s != command]
    for path in _protected_path_patterns():
        for hay in haystacks:
            matched, reason = check_path_patterns(
                hay, path, READ_ONLY_BLOCKED, "protected control-plane path"
            )
            if matched:
                op = _infer_operation_from_reason(reason)
                if is_command_path_allowed(command, allowed_paths, op):
                    break
                return True, f"Protected control-plane path: {path}"
    return False, ""


_ESCAPE_HATCH_RE = re.compile(r"#\s*allow:[ \t]*([^\n]+)", re.IGNORECASE)


def detect_escape_hatch(command: str) -> Optional[str]:
    """Return the reason if ``command`` contains a ``# allow: <reason>`` marker.

    Non-empty reason required; matches the rest of the comment line so the
    marker works on multi-line / chained commands too.
    """
    if not command:
        return None
    m = _ESCAPE_HATCH_RE.search(command)
    if not m:
        return None
    reason = m.group(1).strip()
    return reason or None


# ============================================================================
# SHELL-AWARE NORMALIZATION
# ============================================================================
#
# The bash matcher historically ran the rule regexes against the RAW command
# string. With no tokenization, trivial shell quoting/escaping defeated every
# rule: ``r\m -rf /x`` (backslash), ``r''m -rf /x`` (empty quotes),
# ``R=rm; $R -rf /x`` ($VAR indirection) all read as ALLOWED while literal
# ``rm -rf /x`` blocked. We now ALSO match against a normalized form where
# quotes/escapes are removed (via ``shlex``) and simple ``$VAR`` assignments are
# resolved, split per subcommand. ``eval`` and a ``base64 -d | sh`` pipeline are
# unconditionally unverifiable and FAIL CLOSED (escalated to ``ask``, which the
# unattended resolver turns into a block).
#
# Command substitution (``$(...)`` / backticks) is handled position-aware (#502).
# Failing closed on ALL substitution over-blocked benign data-argument use that
# agents run constantly (``echo $(date)``, ``git log --since=$(date ...)``,
# ``cat "$(pwd)/file"``). Instead we MASK each substitution to one opaque token
# and apply an ALLOWLIST model: a masked substitution DEFAULTS to dangerous
# (escalate → ``ask``) and passes only when its position is affirmatively DATA.
# It is dangerous — i.e. its output can become an executed command word — when:
#   * it is the command word (argv-0) of a subcommand (``$(echo rm) -rf /`` — the
#     benign-looking inner is irrelevant, the *output* runs); or
#   * it is the argument of a command-consuming flag (``find -exec``/``-execdir``/
#     ``-ok``/``-okdir`` — ``find . -exec $(echo rm) {} +``); or
#   * it sits anywhere in ``argv[1:]`` of a head that is NOT a recognized
#     data-position command. This is the key inversion: command-wrappers that run
#     their args as a command (``sudo``, ``xargs``, ``ionice``, ``chrt``,
#     ``flock``, ``firejail``, ``setpriv`` …) are an unbounded set, so rather than
#     enumerate them we allow only the known-data heads (``_DATA_SAFE_HEADS``) and
#     fail SAFE on everything else.
# The static skeleton (substitution as one opaque token) is still fed through the
# normal rule ladder, so ``rm -rf $(...)`` is also caught there.

_EVAL_RE = re.compile(r"(?:^|[\s;&|({])eval(?:\s|$)")
_BASE64_PIPE_RE = re.compile(r"\bbase64\b[^\n|]*(?:-d|--decode)[^\n|]*\|", re.IGNORECASE)
_ASSIGN_RE = re.compile(
    r"(?:^|[\n;&|]|&&|\|\|)\s*([A-Za-z_]\w*)=('[^']*'|\"[^\"]*\"|[^\s;|&]*)"
)
_SHELL_OPERATORS = {";", "&&", "||", "|", "&", "\n", ";;", "|&"}

# Opaque stand-in for a masked command substitution. Alphanumeric + underscores
# so it survives shlex tokenization and never matches a path/rule on its own.
_SUBST_PLACEHOLDER = "__awsubst__"

# Substitution policy is an ALLOWLIST, not a blocklist (#502). Enumerating
# dangerous command-wrappers (``sudo``, ``xargs``, ``ionice``, ``chrt``,
# ``flock``, ``firejail``, ``setpriv``, ``proot`` …) is whack-a-mole — every one
# runs ``argv[1:]`` as a command, so a masked substitution there IS the command
# word, and the set is effectively unbounded. Instead we DEFAULT a masked
# substitution to dangerous (escalate → ``ask``) and allow it only when its
# position is affirmatively DATA: a substitution argument to one of these
# recognized non-wrapper, non-interpreter heads (text/file utilities + VCS
# read), where the substitution's output is consumed as a string/path/pattern
# and never executed. An unknown head ⇒ ask (fail safe), not allow (fail open).
_DATA_SAFE_HEADS = {
    "echo", "printf", "cat", "tac", "ls", "grep", "egrep", "fgrep", "zgrep",
    "rg", "ag", "head", "tail", "test", "[", "git", "tar", "sort", "uniq",
    "wc", "cut", "tr", "diff", "comm", "jq", "yq", "basename", "dirname",
    "realpath", "readlink", "stat", "file", "du", "df", "date", "pwd", "find",
    "fd", "column", "nl", "fold", "rev", "paste", "join", "expand", "seq",
}

# Flags whose FOLLOWING argument is a command word that the tool will execute —
# the substitution there is run, not passed as data (``find ... -exec $(echo rm)
# {} +`` smuggles a masked ``rm`` into find's command slot). Checked for EVERY
# head (incl. data-safe ``find``), before the data-position allow (#502).
_COMMAND_CONSUMING_FLAGS = {
    "-exec", "-execdir", "-ok", "-okdir",
}


def _mask_substitutions(command: str) -> Tuple[str, bool, bool]:
    """Replace each ``$(...)`` / ```...``` with a placeholder token.

    Returns ``(masked, had_substitution, unbalanced)``. ``unbalanced`` is True
    when a substitution is opened but never closed (we fail closed on it). Nested
    ``$(...)`` parens are balanced; arithmetic ``$((...))`` is masked too (it is
    inert data, never command position).
    """
    out: List[str] = []
    i = 0
    n = len(command)
    had = False
    while i < n:
        c = command[i]
        if c == "`":
            j = command.find("`", i + 1)
            if j == -1:
                return "".join(out) + command[i:], True, True
            out.append(_SUBST_PLACEHOLDER)
            had = True
            i = j + 1
        elif c == "$" and i + 1 < n and command[i + 1] == "(":
            depth = 1
            j = i + 2
            while j < n and depth > 0:
                if command[j] == "(":
                    depth += 1
                elif command[j] == ")":
                    depth -= 1
                j += 1
            if depth != 0:
                return "".join(out) + command[i:], True, True
            out.append(_SUBST_PLACEHOLDER)
            had = True
            i = j
        else:
            out.append(c)
            i += 1
    return "".join(out), had, False


def _has_subst(tok: str) -> bool:
    return _SUBST_PLACEHOLDER in tok


def _dangerous_substitution(subcommands_tokens: List[List[str]]) -> Optional[str]:
    """Return a reason if any masked substitution sits in a dangerous position.

    ``subcommands_tokens`` is the per-subcommand token list (placeholders intact).
    """
    for toks in subcommands_tokens:
        if not toks:
            continue
        # Substitution in command position — its output is what runs.
        if _has_subst(toks[0]):
            return "command substitution in command position"
        # Substitution landing in a command-consuming flag's argument (the
        # command word that ``find -exec`` / ``-ok`` / … will run). Checked for
        # every head, since data-safe ``find`` still has exec slots.
        for i, tok in enumerate(toks[:-1]):
            if tok.strip("'\"") in _COMMAND_CONSUMING_FLAGS and _has_subst(toks[i + 1]):
                return "command substitution in a command-consuming argument"
        # Any other substitution in argv[1:]: allow ONLY when the head is a
        # recognized data-position command; otherwise it may be a command-wrapper
        # whose argument becomes the executed command — fail safe to ``ask``.
        if any(_has_subst(t) for t in toks[1:]):
            head = os.path.basename(toks[0].strip("'\""))
            if head not in _DATA_SAFE_HEADS:
                return "command substitution argument to an unrecognized command (possible wrapper)"
    return None


def detect_obfuscation(command: str) -> Optional[str]:
    """Return a reason string if ``command`` hides intent behind shell features.

    ``eval`` and ``base64 -d | sh`` are unconditionally unverifiable — they run
    their argument/stdin as code, so we decline to reason about them and fail
    closed. Command substitution is NOT flagged here; it is handled position-aware
    in :func:`normalize_subcommands` (#502).
    """
    if _EVAL_RE.search(command):
        return "eval"
    if _BASE64_PIPE_RE.search(command):
        return "base64-decode pipeline"
    return None


def normalize_subcommands(command: str) -> Tuple[List[str], Optional[str]]:
    """Tokenize ``command`` and return ``(normalized_subcommands, ambiguous)``.

    ``normalized_subcommands`` is the per-subcommand argv re-joined with single
    spaces, after command substitutions have been masked to an opaque token,
    ``shlex`` has stripped quotes/escapes, and simple ``$VAR`` assignments earlier
    in the same command have been resolved. ``ambiguous`` is a reason string when
    the command can't be verified safely (and the caller should fail closed); it
    is ``None`` on success. Benign data-argument substitution returns its masked
    skeleton with ``ambiguous=None`` so the normal rule ladder still inspects it.
    """
    obf = detect_obfuscation(command)
    if obf:
        return [], obf

    masked, had_subst, unbalanced = _mask_substitutions(command)
    if unbalanced:
        return [], "unbalanced command substitution"

    # Resolve simple ``VAR=value`` assignments so ``R=rm; $R -rf`` normalizes to
    # ``rm -rf``. Only literal values (no nested expansion) are resolved.
    assigns: Dict[str, str] = {}
    for m in _ASSIGN_RE.finditer(masked):
        assigns[m.group(1)] = m.group(2).strip("'\"")

    try:
        lex = shlex.shlex(masked, posix=True, punctuation_chars=True)
        lex.whitespace_split = True
        tokens = list(lex)
    except ValueError:
        return [], "unbalanced quotes"

    def _resolve(tok: str) -> str:
        for name, val in assigns.items():
            tok = tok.replace("${%s}" % name, val).replace("$" + name, val)
        return tok

    subs: List[str] = []
    sub_tokens: List[List[str]] = []
    cur: List[str] = []
    for tok in tokens:
        if tok in _SHELL_OPERATORS:
            if cur:
                subs.append(" ".join(cur))
                sub_tokens.append(cur)
                cur = []
            continue
        cur.append(_resolve(tok))
    if cur:
        subs.append(" ".join(cur))
        sub_tokens.append(cur)

    ambiguous = _dangerous_substitution(sub_tokens) if had_subst else None
    return subs, ambiguous


