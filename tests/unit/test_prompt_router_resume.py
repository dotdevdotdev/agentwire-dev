# From the real capture, taken on a 200-column pane. The only edit is that the
# transcript ABOVE the rule was trimmed to one line; every line from the rule
# down is byte-for-byte what tmux emitted, including the 200-column rule and
# the trailing blank lines tmux pads the pane height with (the liveness check
# anchors on the END of the screen, so stripping those tests a screen that
# never occurs).
#
# The width matters and is the reason this constant is not the whole story:
# the body sentence is 122 columns, so it fits UNWRAPPED only on a pane this
# wide. Narrower panes — 80 and 64 columns are what this fleet actually runs —
# break a line inside it. See RESUME_DIALOG_AT_92 and the width sweep below;
# an earlier version of this file had an 80-column rule beside the 122-column
# body, a combination no capture can produce, and that reflow is exactly why
# nothing here exercised wrapping.
RESUME_DIALOG = """\
⏺ Read 2 files, ran 4 shell commands
────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────
  This session is 2m old and 134.1k tokens.

  Resuming the full session will consume a substantial portion of your usage limits. We recommend resuming from a summary.

  ❯ 1. Resume from summary (recommended)
    2. Resume full session as-is
    3. Don't ask me again

  Enter to confirm · Esc to cancel

"""


def render_at_width(screen: str, width: int) -> str:
    """Re-render *screen* as a pane of *width* columns would show it.

    Hard-wraps every over-long line, preserving the leading indent on
    continuations the way the dialog's own renderer does. This is the fixture
    generator the first version of this file lacked.
    """
    out = []
    for line in screen.split("\n"):
        if len(line) <= width:
            out.append(line)
            continue
        indent = " " * (len(line) - len(line.lstrip()))
        out += textwrap.wrap(line, width, subsequent_indent=indent) or [line]
    return "\n".join(out)


# The same dialog on a 92-column pane. A line break lands inside the anchor
# sentence, which is the case that used to raise ValueError out of the
# detector — and out of the whole sweep with it.
